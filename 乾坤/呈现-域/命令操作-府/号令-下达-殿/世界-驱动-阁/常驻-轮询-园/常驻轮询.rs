//! 常驻-轮询-园：任务线消费——「世界 守护」常驻循环 +「世界 驱动」单条执行。
//! 设计稿 §1.5.5 任务线机制：对话发布的任务线由守护消费，防 CLI 退出丢任务。

use crate::{读模型配置, 打开存储, 工作区根};
use rizhi_fu::{info, warn};
use std::time::Duration;

/// 周期维护间隔：守护每消费/空转 300 轮做一次世界自我维护
/// （生产化 2.3/2.4）：刷新依赖图（防滞后误判）+ 重新建档（规模/成功率指标保鲜）。
/// 300 轮 ≈ 空转 10 分钟一次；任务执行中一轮可达分钟级，自然更稀——全量扫描耗时长，
/// 频率过高会阻塞任务消费（2026-08-17 轮9 体检：原 30 轮≈60 秒一次过频）。
const 维护间隔轮数: u32 = 300;

/// 「世界 守护」：常驻循环消费待执行任务线（间隔 2 秒）。
/// 界主开一个终端跑它，世界的"心脏"就跳起来了——对话发布的任务全部异步执行，完成后鸿钧汇报进对话记录。
/// 注意：本命令不退出；单实例运行（多实例由任务线锁文件互斥，先到先得）。
pub fn 世界守护() -> String {
    let 配置 = 读模型配置();
    let 存储 = 打开存储();
    // 启动自检（生产化 3.1）：工作区/模型配置/构建产物目录 三要素确认后开跑。
    let 根 = 工作区根();
    let 构建目录 = 根.join("道果树").join("构建物-域");
    let 自检 = [
        ("工作区根", 根.exists()),
        ("模型配置", !配置.密钥.is_empty() && !配置.地址.is_empty()),
        ("构建产物目录", 构建目录.exists()),
    ];
    for (名, 就绪) in 自检 {
        if 就绪 {
            info!(名, "启动自检通过");
        } else {
            warn!(名, "启动自检未通过（世界仍启动，相关能力可能受限）");
        }
    }
    info!("世界守护启动（常驻）");
    let mut 轮 = 0u32;
    loop {
        轮 += 1;
        // 周期维护：依赖图刷新 + 档案重建（防依赖图滞后误判打回、成功率指标保鲜）。
        if 轮 % 维护间隔轮数 == 0 {
            let 根 = 工作区根();
            match shihai_fu::扫描(&存储, &根) {
                Ok(条数) => info!(条数, "周期维护：依赖图已刷新"),
                Err(说明) => warn!(说明 = %说明, "周期维护：依赖图刷新失败"),
            }
            if let Err(说明) = tianting_fu::建档落盘() {
                warn!(说明 = %说明, "周期维护：档案重建失败");
            }
        }
        match tianting_fu::执行一条待执行任务线(&配置, &存储) {
            Ok(Some(汇报)) => {
                info!(汇报 = %汇报.chars().take(120).collect::<String>(), "任务线完成");
            }
            Ok(None) => std::thread::sleep(Duration::from_secs(2)),
            Err(错误) => {
                warn!(错误 = %错误, "任务线执行异常，稍后继续轮询");
                std::thread::sleep(Duration::from_secs(5));
            }
        }
    }
}

/// 「世界 驱动」：立即执行一条待执行任务线（手动驱动，供未跑守护时使用）。
pub fn 世界驱动() -> String {
    let 配置 = 读模型配置();
    let 存储 = 打开存储();
    match tianting_fu::执行一条待执行任务线(&配置, &存储) {
        Ok(Some(汇报)) => format!("已执行一条任务线\n{汇报}"),
        Ok(None) => "当前无待执行任务线（锁被占用时本轮跳过，稍后再试）".to_string(),
        Err(错误) => format!("执行失败：{错误}"),
    }
}

/// 「世界 中止」：中止指定任务线（待执行不再被领取；执行中任务完成后撤销产物不汇报）。
pub fn 世界中止(任务线id: &str) -> String {
    match tianting_fu::中止任务线(任务线id.trim()) {
        Ok(文本) => 文本,
        Err(错误) => format!("中止失败：{错误}"),
    }
}
