//! 常驻-轮询-园：任务线消费——「世界 守护」常驻循环 +「世界 驱动」单条执行。
//! 设计稿 §1.5.5 任务线机制：对话发布的任务线由守护消费，防 CLI 退出丢任务。
//!
//! 并发消费（2026-08-18 入稿）：任务级并发——守护/驱动 各起 并发度 个工作线程并行循环调
//! `执行一条待执行任务线`。任务线排他锁只覆盖"领取那一下"(短)，执行期(分钟级)不持锁，
//! 故多线程能在不同时刻各自领到不同任务线并行跑；构建由调度器内部锁串行，id 全局唯一。
//! 收益：队列积压时总墙钟从 N×单条 降到 ≈单条，直击"一条任务等十几分钟"的感知慢。

use crate::{工作区根, 打开存储, 投递想法, 状态目录, 读模型配置};
use rizhi_fu::{info, warn};
use std::time::Duration;

/// 周期维护间隔：守护每消费/空转 300 轮做一次世界自我维护
/// （生产化 2.3/2.4）：刷新依赖图（防滞后误判）+ 重新建档（规模/成功率指标保鲜）。
/// 300 轮 ≈ 空转 10 分钟一次；任务执行中一轮可达分钟级，自然更稀——全量扫描耗时长，
/// 频率过高会阻塞任务消费（2026-08-17 轮9 体检：原 30 轮≈60 秒一次过频）。
const 维护间隔轮数: u32 = 300;

/// 自进化间隔：守护每消费/空转 10 轮做一次巡世扫描 + 候选消费（阶段五自转）。
/// 与维护间隔 300 轮区分——维护做全量依赖图刷新 + 建档（重），自进化做巡世扫描 +
/// 候选投递（轻），故频率更密。10 轮 ≈ 空转 20 秒一次；任务执行中一轮可达分钟级，自然更稀。
const 自进化间隔轮数: u32 = 10;

/// 并发消费度：守护/驱动 同时并行执行的任务线数。默认 4。
/// 依据：任务全链的墙钟主要耗在等 LLM API 响应(CPU 占用极小)；
/// 4 条并行既不抢爆构建锁(调度器内部串行)，也能把队列积压有效削平。
pub fn 并发度() -> usize {
    std::env::var("WORLD_WORKER_N")
        .ok()
        .and_then(|值| 值.trim().parse().ok())
        .filter(|&n| (1..=16).contains(&n))
        .unwrap_or(4)
}

/// 「世界 守护」：常驻循环消费待执行任务线（间隔 2 秒），并发度 个工作线程并行。
/// 界主开一个终端跑它，世界的"心脏"就跳起来了——对话发布的任务全部异步执行，完成后鸿钧汇报进对话记录。
/// 注意：本命令不退出；单实例运行（多实例由任务线锁文件互斥，先到先得）。
pub fn 世界守护() -> String {
    let 配置 = 读模型配置();
    let 存储 = 打开存储();
    // 启动自检（生产化 3.1）：工作区/模型配置/构建产物目录 三要素确认后开跑。
    let 根 = 工作区根();
    let 构建目录 = 根.join("道果树").join("构建物-域");
    let 自检 = [
        ("工作区根", 根.exists()),
        ("模型配置", !配置.密钥.is_empty() && !配置.地址.is_empty()),
        ("构建产物目录", 构建目录.exists()),
    ];
    for (名, 就绪) in 自检 {
        if 就绪 {
            info!(名, "启动自检通过");
        } else {
            warn!(名, "启动自检未通过（世界仍启动，相关能力可能受限）");
        }
    }
    let 并发 = 并发度();
    info!(并发, "世界守护启动（常驻，并发消费）");
    // 并行工作线程：各自循环领任务线执行。任务线排他锁保证互斥领取、执行期不持锁即可并行。
    std::thread::scope(|作用域| {
        for 序号 in 0..并发 {
            let 配置 = &配置;
            let 存储 = &存储;
            作用域.spawn(move || {
                let mut 轮 = 0u32;
                loop {
                    轮 += 1;
                    // 周期维护：只在第一个工作线程做，防多线程重复全量扫描（阻塞任务消费）。
                    if 序号 == 0 && 轮.is_multiple_of(维护间隔轮数) {
                        let 根 = 工作区根();
                        match shihai_fu::扫描(存储, &根) {
                            Ok(条数) => info!(条数, "周期维护：依赖图已刷新"),
                            Err(说明) => warn!(说明 = %说明, "周期维护：依赖图刷新失败"),
                        }
                        if let Err(说明) = tianting_fu::建档落盘() {
                            warn!(说明 = %说明, "周期维护：档案重建失败");
                        }
                    }
                    // 自进化（阶段五）：只在第一个工作线程，每 N 轮自动巡世扫描 + 候选消费。
                    if 序号 == 0 && 轮.is_multiple_of(自进化间隔轮数) {
                        自进化一轮();
                    }
                    match tianting_fu::执行一条待执行任务线(配置, 存储) {
                        Ok(Some(汇报)) => {
                            info!(汇报 = %汇报.chars().take(120).collect::<String>(), "任务线完成");
                        }
                        Ok(None) => std::thread::sleep(Duration::from_secs(2)),
                        Err(错误) => {
                            warn!(错误 = %错误, "任务线执行异常，稍后继续轮询");
                            std::thread::sleep(Duration::from_secs(5));
                        }
                    }
                }
            });
        }
    });
    "世界守护已退出（异常）".to_string()
}

/// 自进化一轮：巡世扫描（产出候选入池）→ 若候选池非空，消费一个最高优先级候选。
/// 闭环从「界主手动触发」变「自转」（设计稿 §12 阶段五）。
fn 自进化一轮() {
    // 巡世扫描：天道巡逻世界，产出候选与违逆报告。
    let 报告 = tianting_fu::扫描世界(&工作区根());
    info!(
        候选数 = 报告.候选.len(),
        违逆数 = 报告.违逆.len(),
        "自进化：巡世扫描完成"
    );
    // 候选入池（按 目标 去重），与「巡世 扫描」命令同逻辑。
    let 状态目录 = 状态目录();
    let mut 状态 = match tianting_fu::确保世界状态初始化(&状态目录) {
        Ok(状态) => 状态,
        Err(错误) => {
            warn!(错误 = %错误, "自进化：世界状态初始化失败");
            return;
        }
    };
    for 候选 in &报告.候选 {
        if !状态.巡世候选池.iter().any(|已有| 已有.目标 == 候选.目标) {
            状态.巡世候选池.push(候选.clone());
        }
    }
    // 候选消费：若池非空，取最高优先级投递想法，与「巡世 驱动」命令同逻辑。
    if 状态.巡世候选池.is_empty() {
        return;
    }
    状态.巡世候选池.sort_by(|a, b| b.优先级.cmp(&a.优先级));
    let 候选 = 状态.巡世候选池[0].clone();
    let 想法文本 = format!("【巡世候选】{}\n依据：{}", 候选.目标, 候选.依据);
    info!(候选目标 = %候选.目标, 优先级 = ?候选.优先级, "自进化：投递候选为想法");
    let _ = 投递想法(&想法文本);
    状态.巡世候选池.retain(|c| c.目标 != 候选.目标);
    if let Err(错误) = tianting_fu::写世界状态(&状态目录, &状态) {
        warn!(错误 = %错误, "自进化：候选池落盘失败");
        return;
    }
    info!(
        剩余候选数 = 状态.巡世候选池.len(),
        "自进化：候选已消费并落盘"
    );
}

/// 「世界 驱动」：立即执行一条待执行任务线（手动驱动，供未跑守护时使用）。
/// 单次调用执行一条（保持 CLI 简单可预期）。
pub fn 世界驱动() -> String {
    let 配置 = 读模型配置();
    let 存储 = 打开存储();
    match tianting_fu::执行一条待执行任务线(&配置, &存储) {
        Ok(Some(汇报)) => format!("已执行一条任务线\n{汇报}"),
        Ok(None) => "当前无待执行任务线（锁被占用时本轮跳过，稍后再试）".to_string(),
        Err(错误) => format!("执行失败：{错误}"),
    }
}

/// 「世界 中止」：中止指定任务线（待执行不再被领取；执行中任务完成后撤销产物不汇报）。
pub fn 世界中止(任务线id: &str) -> String {
    match tianting_fu::中止任务线(任务线id.trim()) {
        Ok(文本) => 文本,
        Err(错误) => format!("中止失败：{错误}"),
    }
}
