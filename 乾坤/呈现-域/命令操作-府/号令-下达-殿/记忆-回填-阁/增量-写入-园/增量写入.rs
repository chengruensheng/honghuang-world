//! 记忆回填 / 记忆播种：写记录进识海格位

use crate::{工作区根, 打开存储, 读模型配置};
use rizhi_fu::{error, info};

pub fn 记忆回填(格位: &str, 内容: &str) -> String {
    if 格位.trim().is_empty() {
        error!("记忆回填失败：格位名为空");
        return "回填失败：格位名为空".to_string();
    }
    let 存储 = 打开存储();
    let 记录 = shihai_fu::记录::新(格位, 内容, "号令回填", "人类");
    match 存储.写记录(&记录) {
        Ok(_) => {
            info!(格位, "记忆回填完成");
            format!("记忆已回填\n格位：{格位}")
        }
        Err(错误) => {
            error!(格位, "记忆回填失败：{错误}");
            format!("回填失败：{错误}")
        }
    }
}

pub fn 记忆播种() -> String {
    let 根 = 工作区根();
    let 存储 = 打开存储();
    match shihai_fu::扫描(&存储, &根) {
        Ok(条数) => {
            info!(条数, "记忆播种完成");
            format!("记忆已播种（代码扫描）\n写入：{条数} 条记录")
        }
        Err(错误) => {
            error!("记忆播种失败：{错误}");
            format!("播种失败：{错误}")
        }
    }
}

/// 记忆补语义：唤起 LLM 补依赖图里空解释符号的语义，写回依赖图。
pub fn 记忆补语义() -> String {
    let 根 = 工作区根();
    let 配置 = 读模型配置();
    match shihai_fu::补符号解释(&根, &配置) {
        Ok(条数) => {
            info!(条数, "记忆补语义完成");
            format!("符号语义已补全\n补全：{条数} 个符号解释")
        }
        Err(错误) => {
            error!("记忆补语义失败：{错误}");
            format!("补语义失败：{错误}")
        }
    }
}

