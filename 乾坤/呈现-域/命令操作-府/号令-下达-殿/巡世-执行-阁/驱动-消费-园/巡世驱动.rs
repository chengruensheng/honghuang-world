//! 巡世驱动：候选池按优先级取最高 → 构造想法 → 走投递想法全链 → 候选出池落盘。
//!
//! 候选池从「只进不出」变为「自主消费」，达成阶段二第 4 条验收标准
//! 「世界自主闭环（巡世→要求→设计→实现→验收→版本）」（设计稿 §12 P2-7，Line 1119）。

use crate::{投递想法, 状态目录};
use rizhi_fu::{error, info};

/// 巡世驱动：候选池按优先级取最高 → 构造想法 → 走投递想法全链 → 候选出池落盘。
pub fn 巡世驱动() -> String {
    let 状态目录 = 状态目录();
    let mut 状态 = match tianting_fu::确保世界状态初始化(&状态目录) {
        Ok(状态) => 状态,
        Err(错误) => {
            error!(错误 = %错误, "巡世驱动：世界状态初始化失败");
            return format!("巡世驱动失败：{错误}");
        }
    };
    if 状态.巡世候选池.is_empty() {
        return "巡世候选池为空，请先执行「巡世 扫描」".to_string();
    }
    // 按优先级排序（高>中>低），取最高。
    状态.巡世候选池.sort_by(|a, b| b.优先级.cmp(&a.优先级));
    let 候选 = 状态.巡世候选池[0].clone();
    let 想法文本 = format!("【巡世候选】{}\n依据：{}", 候选.目标, 候选.依据);
    info!(候选目标 = %候选.目标, 优先级 = ?候选.优先级, "巡世驱动：投递候选为想法");
    let 回执 = 投递想法(&想法文本);
    // 候选出池：移除已消费的候选（按 目标 匹配，防同目标重复消费）。
    状态.巡世候选池.retain(|c| c.目标 != 候选.目标);
    if let Err(错误) = tianting_fu::写世界状态(&状态目录, &状态) {
        error!(错误 = %错误, "巡世驱动：候选池落盘失败");
        return format!("巡世驱动失败（候选池未落盘）：{错误}\n{回执}");
    }
    info!(剩余候选数 = 状态.巡世候选池.len(), "巡世驱动完成并落盘");
    format!(
        "巡世驱动完成\n消费候选：{}\n优先级：{:?}\n剩余候选：{} 条\n投递回执：\n{回执}",
        候选.目标,
        候选.优先级,
        状态.巡世候选池.len()
    )
}
