//! 巡世执行：天道巡世扫描，产出候选与违逆报告并落盘世界状态

use crate::{工作区根, 状态目录};
use rizhi_fu::{error, info, warn};

/// 巡世扫描：天道巡逻世界，产出巡世报告并落盘世界状态。
/// 报告入「天道报告库」（按 id 去重），候选并入「巡世候选池」（按 目标 去重）——
/// 候选池不再恒 0，鸿钧可据此化为要求（设计稿 §12 P2-7）。
pub fn 巡世扫描() -> String {
    let 报告 = tianting_fu::扫描世界(&工作区根());
    let 状态目录 = 状态目录();
    let 当前 = tianting_fu::确保世界状态初始化(&状态目录);
    let mut 状态 = match 当前 {
        Ok(状态) => 状态,
        Err(错误) => {
            error!(错误 = %错误, "巡世扫描：世界状态初始化失败");
            return format!("巡世扫描失败：{错误}");
        }
    };
    // 天道报告库：按 id 去重追加（同一次扫描不重复入库）。
    if !状态.天道报告库.iter().any(|已有| 已有.id == 报告.id) {
        状态.天道报告库.push(报告.clone());
    }
    // 巡世候选池：按 目标 去重并入。
    for 候选 in &报告.候选 {
        if !状态.巡世候选池.iter().any(|已有| 已有.目标 == 候选.目标) {
            状态.巡世候选池.push(候选.clone());
        }
    }
    if let Err(错误) = tianting_fu::写世界状态(&状态目录, &状态) {
        error!(错误 = %错误, "巡世扫描：候选池落盘失败");
        return format!("巡世扫描失败：{错误}");
    }
    info!(候选数 = 报告.候选.len(), 违逆数 = 报告.违逆.len(), 候选池总数 = 状态.巡世候选池.len(), "巡世扫描完成并落盘");
    format!(
        "巡世扫描完成\nid：{}\n候选：{} 条（候选池累计 {} 条）\n违逆：{} 条",
        报告.id,
        报告.候选.len(),
        状态.巡世候选池.len(),
        报告.违逆.len()
    )
}

pub fn 巡世报告() -> String {
    let 报告 = tianting_fu::扫描世界(&工作区根());
    if 报告.候选.is_empty() && 报告.违逆.is_empty() {
        warn!("巡世报告无候选无违逆");
    }
    let mut 行 = format!("巡世报告\nid：{}\n", 报告.id);
    for 候选 in &报告.候选 {
        行.push_str(&format!("- {}（{}）· {:?}\n", 候选.目标, 候选.依据, 候选.优先级));
    }
    for 违逆 in &报告.违逆 {
        行.push_str(&format!("- 违逆：{} → {}\n", 违逆.路径, 违逆.违逆内容));
    }
    if 报告.候选.is_empty() && 报告.违逆.is_empty() {
        行.push_str("（无候选、无违逆）");
    }
    行
}
