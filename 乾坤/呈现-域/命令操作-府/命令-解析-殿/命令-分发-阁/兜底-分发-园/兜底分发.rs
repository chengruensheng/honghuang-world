pub fn 命令清单() -> String {
    let mut 行 = String::from("号令命令清单（域 动作 · 权限）\n");
    for (域, 动作, 权) in 命令表 {
        行.push_str(&format!("  {域} {动作} · {权}\n"));
    }
    行
}

/// 按 域+动作 分发调用
pub fn 分发调用(调用: &调用) -> 结果 {
    let 取参 = |索引: usize| 调用.参数.get(索引).cloned().unwrap_or_default();
    let 取旗 = |名: &str| {
        调用
            .旗标
            .iter()
            .find(|(键, _)| 键 == 名)
            .map(|(_, 值)| 值.clone())
            .unwrap_or_default()
    };
    match (调用.域.as_str(), 调用.动作.as_str()) {
        ("帮助", _) => 成功(命令清单()),
        ("想法", "投递") => 成功(投递想法(&取参(0))),
        ("想法", "列表") => 成功(事项列表("想法")),
        ("想法", "详情") => 成功(事项详情("想法", &取参(0))),
        ("要求", "化为") => 成功(化为要求(&取参(0))),
        ("要求", "列表") => 成功(事项列表("要求")),
        ("要求", "详情") => 成功(事项详情("要求", &取参(0))),
        ("设计", "上呈") => 成功(上呈设计(&取参(0), &取旗("文件"))),
        ("设计", "确认") => 成功(确认设计(&取参(0), &取参(1), &取旗("意见"))),
        ("设计", "列表") => 成功(事项列表("设计")),
        ("设计", "详情") => 成功(事项详情("设计", &取参(0))),
        ("验收", "裁决") => 成功(裁决验收(&取参(0), &取参(1), &取旗("意见"))),
        ("验收", "历史") => 成功(事项列表("验收")),
        ("验收", "详情") => 成功(事项详情("验收", &取参(0))),
        ("版本", "存档") => 成功(存档版本()),
        ("版本", "列表") => 成功(呈现版本历史()),
        ("版本", "详情") => 成功(版本详情(&取参(0))),
        ("版本", "回退") => 成功(回退版本(&取参(0))),
        ("记忆", "投影") => 成功(记忆投影(&取参(0))),
        ("记忆", "回填") => 成功(记忆回填(&取参(0), &取参(1))),
        ("记忆", "播种") => 成功(记忆播种()),
        ("记忆", "补语义") => 成功(记忆补语义()),
        ("记忆", "建档") => 成功(记忆建档()),
        ("世界", "状态") => 成功(呈现世界状态()),
        ("世界", "时间") => 成功(呈现世界时刻()),
        // 契约：「世界 时辰」无副作用只读查询、不引入缓存、不写入日志与会话状态、不留共享可变状态
        ("世界", "时辰") => 成功(呈现世界时刻()),
        ("世界", "历法") => 成功(呈现世界历法()),
        ("世界", "纪元") => 成功(呈现世界纪元()),
        ("世界", "检索") => 成功(全文检索(&取参(0))),
        ("世界", "直播") => 成功(世界直播()),
        ("世界", "守护") => 成功(世界守护()),
        ("世界", "驱动") => 成功(世界驱动()),
        ("世界", "中止") => 成功(世界中止(&取参(0))),
        ("队列", "水位") => 成功(呈现队列水位()),
        ("流水", "列表") => 成功(流水列表()),
        ("流水", "总览") => 成功(全流程总览()),
        ("流水", "跟踪") => 成功(流水跟踪(&取参(0), 取旗("全文") == "true")),
        ("流水", "跟随") => 成功(流水跟随(&取参(0))),
        ("巡世", "扫描") => 成功(巡世扫描()),
        ("巡世", "报告") => 成功(巡世报告()),
        ("装配", "检查") => 成功(呈现装配()),
        ("对话", "发言") => 成功(对话发言(&取参(0))),
        ("对话", "历史") => 成功(对话历史()),
        (域, 动作) => {
            warn!(域, 动作, "未知命令");
            失败(format!("未知命令：{域} {动作}（号令 帮助 查看清单）"))
        }
    }
}

fn 成功(内容: String) -> 结果 {
    结果::成功(内容)
}

fn 失败(内容: String) -> 结果 {
    结果::失败(内容)
}
