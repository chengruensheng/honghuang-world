    /// 呈现世界纪元格式校验：`纪元：YYYY年 · 干 支（第N甲子）· 生肖X`
    /// - 3 个汉字"纪元："开头
    /// - 4 位年份数字段（位置 3..7）
    /// - "年"在位置 7
    /// - 包含"年 · "、"甲子）"、"· 生肖"三个特征片段
    #[test]
    fn 验证呈现世界纪元格式() {
        let 输出 = 呈现世界纪元();
        let 字符: Vec<char> = 输出.chars().collect();
        assert!(输出.starts_with("纪元："), "输出应以'纪元：'开头：{输出}");
        assert!(输出.contains("年 · "), "输出应含'年 · '：{输出}");
        assert!(输出.contains("甲子）"), "输出应含'甲子）'：{输出}");
        assert!(输出.contains("· 生肖"), "输出应含'· 生肖'：{输出}");
        assert!(
            字符.len() >= 8,
            "输出至少 8 字符（含'纪元：YYYY年'）：{输出}"
        );
        assert!(
            字符[3..7].iter().all(|c| c.is_ascii_digit()),
            "年份段应为 4 位数字：{输出}"
        );
        assert_eq!(字符[7], '年', "位置 7 应为'年'：{输出}");
    }
