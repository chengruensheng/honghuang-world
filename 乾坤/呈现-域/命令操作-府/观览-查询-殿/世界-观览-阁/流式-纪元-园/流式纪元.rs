//! 流式-纪元-园：当前公历年对应的天干地支、生肖与六十甲子序号。
//!
//! 不引入额外时间库，纯 std：拿 UNIX 秒戳 + 8h 偏移 + 历法推算年份，再按干支规则换算。

use std::time::{SystemTime, UNIX_EPOCH};

/// 北京时间相对 UTC 的偏移（秒）
const 北京偏移秒: u64 = 8 * 3600;

/// 十天干
const 天干表: [&str; 10] = ["甲", "乙", "丙", "丁", "戊", "己", "庚", "辛", "壬", "癸"];
/// 十二地支
const 地支表: [&str; 12] = [
    "子", "丑", "寅", "卯", "辰", "巳",
    "午", "未", "申", "酉", "戌", "亥",
];
/// 十二生肖（与地支同序号）
const 生肖表: [&str; 12] = [
    "鼠", "牛", "虎", "兔", "龙", "蛇",
    "马", "羊", "猴", "鸡", "狗", "猪",
];

fn 是否闰年(年: u64) -> bool {
    (年 % 4 == 0 && 年 % 100 != 0) || 年 % 400 == 0
}

fn 当年天数(年: u64) -> u64 {
    if 是否闰年(年) { 366 } else { 365 }
}

/// 取北京时间当前公历年份（与流式-时刻-园算法一致：UTC 秒戳 + 8h 偏移 → 自 1970 起的天数 → 逐年累减得年）。
pub fn 当前公历年() -> u64 {
    let 总秒_utc = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_secs())
        .unwrap_or(0);
    let 总秒 = 总秒_utc + 北京偏移秒;
    let 总分 = 总秒 / 60;
    let 总时 = 总分 / 60;
    let 总日 = 总时 / 24;

    let mut 年: u64 = 1970;
    let mut 剩余日 = 总日;
    loop {
        let 当年 = 当年天数(年);
        if 剩余日 < 当年 {
            break;
        }
        剩余日 -= 当年;
        年 += 1;
    }
    年
}

/// 天干序号转中文（0=甲, 1=乙, ..., 9=癸）。
pub fn 天干名(序号: u64) -> &'static str {
    天干表[序号 as usize % 10]
}

/// 地支序号转中文（0=子, 1=丑, ..., 11=亥）。
pub fn 地支名(序号: u64) -> &'static str {
    地支表[序号 as usize % 12]
}

/// 生肖序号转中文（与地支同序号：0=鼠, 1=牛, ..., 11=猪）。
pub fn 生肖名(序号: u64) -> &'static str {
    生肖表[序号 as usize % 12]
}

/// 干支纪年推算结果
pub struct 干支纪年 {
    /// 公历年
    pub 公历年: u64,
    /// 天干（甲/乙/.../癸）
    pub 天干: &'static str,
    /// 地支（子/丑/.../亥）
    pub 地支: &'static str,
    /// 生肖（鼠/牛/.../猪）
    pub 生肖: &'static str,
    /// 六十甲子序号（1-60）
    pub 甲子序: u64,
}

/// 按公历年推算干支纪年。
/// 基准：公元 4 年 = 甲子（干序 0、支序 0、甲子序 1）。
/// 干序 = (年 - 4) rem_euclid 10
/// 支序 = (年 - 4) rem_euclid 12
/// 甲子序 = ((年 - 4) rem_euclid 60) + 1（1-60）
/// rem_euclid 确保年小于 4 时（如公元 1-3 年）也能正确回到循环前端。
pub fn 干支推算(年: u64) -> 干支纪年 {
    let 差 = (年 as i64) - 4;
    let 干序 = 差.rem_euclid(10) as u64;
    let 支序 = 差.rem_euclid(12) as u64;
    let 甲子序 = 差.rem_euclid(60) as u64 + 1;
    干支纪年 {
        公历年: 年,
        天干: 天干名(干序),
        地支: 地支名(支序),
        生肖: 生肖名(支序),
        甲子序,
    }
}

/// 取当前北京时间所在公历年对应的干支纪年并返回格式化字符串。
/// 格式：`纪元：YYYY年 · 干 支（第N甲子）· 生肖X`
pub fn 呈现世界纪元() -> String {
    let 年 = 当前公历年();
    let 纪元 = 干支推算(年);
    format!(
        "纪元：{}年 · {} {}（第{}甲子）· 生肖{}",
        纪元.公历年, 纪元.天干, 纪元.地支, 纪元.甲子序, 纪元.生肖
    )
}

