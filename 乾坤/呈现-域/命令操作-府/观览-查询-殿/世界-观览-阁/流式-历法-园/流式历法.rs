//! 呈现北京时间当前公历日期 + 24 节气判定算法。
//!
//! 节气算法思路：
//! 1. 用 Meeus 简化公式（精度 ≈0.01°）算太阳黄经。
//! 2. 把黄经归一化到 [0°, 360°），按 15° 一档映射到 24 节气之一。
//! 3. 春分 = 0°；夏至 = 90°；秋分 = 180°；冬至 = 270°；立春 = 315°。
//! 4. 边界归属：rounded 落点决定归属节气（每档覆盖 ±7.5°）。

use rizhi_fu::{info, warn};
use std::time::{SystemTime, UNIX_EPOCH};

const 北京偏移秒: u64 = 8 * 60 * 60;
const 每日秒数: u64 = 24 * 60 * 60;
const 平年月天: [u64; 12] = [31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31];

/// J2000.0 起点（2000-01-01 12:00:00 UTC）的 Unix 时间戳（秒）。
const J2000_UTC_秒: f64 = 946_728_000.0;
/// J2000.0 对应的儒略日 JD。
const J2000_JD: f64 = 2_451_545.0;

/// 判断指定年份是否为闰年。
///
/// 规则：4 整除且非 100 整除，或 400 整除。
/// 边界样例：2000（400 整除）→true；1900（100 整除）→false；2024（4 整除）→true；2023→false。
pub fn 是否闰年(年份: u64) -> bool {
    (年份.is_multiple_of(4) && !年份.is_multiple_of(100)) || 年份.is_multiple_of(400)
}

/// 返回指定年份的总天数。
fn 当年天数(年份: u64) -> u64 {
    365 + u64::from(是否闰年(年份))
}

/// 呈现北京时间当前日期，格式为 YYYY-MM-DD。
pub fn 呈现世界历法() -> String {
    let 总秒_utc = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|时长| 时长.as_secs())
        .unwrap_or(0);
    let 总日 = (总秒_utc + 北京偏移秒) / 每日秒数;

    // 自 1970-01-01 起算的零基天数。
    let mut 年: u64 = 1970;
    let mut 剩余日 = 总日;
    loop {
        let 当年 = 当年天数(年);
        if 剩余日 < 当年 {
            break;
        }
        剩余日 -= 当年;
        年 += 1;
    }

    // 推算一基月份与日期。
    let 闰 = 是否闰年(年);
    let mut 月: u64 = 1;
    let mut 日 = 剩余日 + 1;
    for (序, &天) in 平年月天.iter().enumerate() {
        let 实际天 = if 序 == 1 && 闰 { 29 } else { 天 };
        if 日 <= 实际天 {
            月 = 序 as u64 + 1;
            break;
        }
        日 -= 实际天;
    }

    format!("{年:04}-{月:02}-{日:02}")
}

// ===== 24 节气判定 =====

/// 24 节气名（按黄经从春分 0° 起，每 15° 一档；圆周 360° 闭环）。
const 节气名: [&str; 24] = [
    "春分", //  0°
    "清明", // 15°
    "谷雨", // 30°
    "立夏", // 45°
    "小满", // 60°
    "芒种", // 75°
    "夏至", // 90°
    "小暑", // 105°
    "大暑", // 120°
    "立秋", // 135°
    "处暑", // 150°
    "白露", // 165°
    "秋分", // 180°
    "寒露", // 195°
    "霜降", // 210°
    "立冬", // 225°
    "小雪", // 240°
    "大雪", // 255°
    "冬至", // 270°
    "小寒", // 285°
    "大寒", // 300°
    "立春", // 315°
    "雨水", // 330°
    "惊蛰", // 345°
];

/// 太阳黄经（度）→ 节气索引（0-23）。
/// 边界归属：每 15° 一档，黄经四舍五入到最近的 15° 倍数。
fn 黄经到节气索引(黄经度: f64) -> usize {
    let 归一 = 黄经度.rem_euclid(360.0);
    let 索引 = (归一 / 15.0).round() as i64;
    索引.rem_euclid(24) as usize
}

/// Meeus《天文算法》简化版：基于 J2000.0 起算日数计算太阳黄经（度）。
/// 精度约 0.01°，足以分辨 15° 一档的节气（相邻节气间隔约 15.2 天）。
fn 太阳黄经(J2000日数: f64) -> f64 {
    // 平黄经（度，从春分点起算）
    let 平黄经 = (280.460 + 0.9856474 * J2000日数).rem_euclid(360.0);
    // 平近点角（度）
    let 平近点角 = (357.528 + 0.9856003 * J2000日数).rem_euclid(360.0);
    let g = 平近点角.to_radians();
    // 黄经（度）含主章动修正
    平黄经 + 1.915 * g.sin() + 0.020 * (2.0 * g).sin()
}

/// 解析公历日期字符串 YYYY-MM-DD → (年, 月, 日)。
fn 解析公历(日期: &str) -> Option<(i64, u64, u64)> {
    let parts: Vec<&str> = 日期.split('-').collect();
    if parts.len() != 3 {
        return None;
    }
    let 年 = parts[0].parse::<i64>().ok()?;
    let 月 = parts[1].parse::<u64>().ok()?;
    let 日 = parts[2].parse::<u64>().ok()?;
    if !(1..=12).contains(&月) || !(1..=31).contains(&日) {
        return None;
    }
    Some((年, 月, 日))
}

/// 公历日期（视为 BJT 日期，正午为参考时刻）→ J2000.0 起算日数。
/// 公式：JD = INT(365.25·(Y+4716)) + INT(30.6001·(M+1)) + D + B - 1524.5（Meeus 第 7 章）。
fn 公历到J2000(年: i64, 月: u64, 日: u64) -> f64 {
    let y = if 月 <= 2 { 年 - 1 } else { 年 };
    let m = if 月 <= 2 {
        月 as i64 + 12
    } else {
        月 as i64
    };
    let a = y / 100;
    let b = 2 - a + a / 4;
    let jd = (365.25 * (y as f64 + 4716.0)).floor()
        + (30.6001 * (m as f64 + 1.0)).floor()
        + 日 as f64
        + b as f64
        - 1524.5;
    jd - J2000_JD
}

/// 当前 UTC 时刻 → J2000.0 起算日数。
fn 当前J2000() -> f64 {
    let 总秒_utc = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|时长| 时长.as_secs() as f64)
        .unwrap_or(0.0);
    (总秒_utc - J2000_UTC_秒) / 每日秒数 as f64
}

/// 推算当前 UTC 时刻对应节气（北京时间视角）。
pub fn 推算节气() -> String {
    let jd = 当前J2000();
    let 黄经 = 太阳黄经(jd);
    let 索引 = 黄经到节气索引(黄经);
    let 名 = 节气名[索引];
    info!(节气 = %名, 黄经 = 黄经, "推算节气完成");
    format!("节气：{名}\n黄经：{黄经:.2}°")
}

/// 推算指定公历日期（YYYY-MM-DD，视为 BJT 日期）对应节气。
/// 参数为空时按当前时刻推算。
pub fn 推算指定节气(日期: &str) -> String {
    if 日期.trim().is_empty() {
        return 推算节气();
    }
    let (年, 月, 日) = match 解析公历(日期) {
        Some(t) => t,
        None => {
            warn!(日期, "节气日期格式非法");
            return format!("日期格式非法：{日期}（需 YYYY-MM-DD，如 2024-03-20）");
        }
    };
    let jd = 公历到J2000(年, 月, 日);
    let 黄经 = 太阳黄经(jd);
    let 索引 = 黄经到节气索引(黄经);
    let 名 = 节气名[索引];
    info!(日期 = %日期, 节气 = %名, 黄经 = 黄经, "推算指定节气完成");
    format!("日期：{日期}\n节气：{名}\n黄经：{黄经:.2}°")
}

#[cfg(test)]
mod tests {
    use super::*;

    /// 400 整除典型边界：2000 年应为闰年。
    #[test]
    fn 是否闰年_2000_400整除为闰年() {
        assert!(是否闰年(2000), "2000 应为闰年（400 整除）");
    }

    /// 100 整除但非 400 整除典型边界：1900 年应为平年。
    #[test]
    fn 是否闰年_1900_100整除不为闰年() {
        assert!(!是否闰年(1900), "1900 应为平年（100 整除但非 400）");
    }

    /// 4 整除但非 100 整除典型边界：2024 年应为闰年。
    #[test]
    fn 是否闰年_2024_4整除为闰年() {
        assert!(是否闰年(2024), "2024 应为闰年（4 整除且非 100）");
    }

    /// 普通年典型边界：2023 年应为平年。
    #[test]
    fn 是否闰年_2023_普通年不为闰年() {
        assert!(!是否闰年(2023), "2023 应为平年（普通年）");
    }
}
