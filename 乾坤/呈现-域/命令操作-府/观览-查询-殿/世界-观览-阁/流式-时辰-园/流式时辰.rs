//! 流式-时辰-园：十二时辰映射核心（地支纪时 + 时段描述）
//!
//! 24 元常量化真值表 + 纯函数查表 + 格式化辅助 + 当前时辰入口。
//! 链路无 Result、无 unwrap、无错误传播；越界统一兜底。

/// 24 小时制小时（0..=23）对应的十二时辰名。
/// - 子时=23/00、丑时=01/02、寅时=03/04、卯时=05/06
/// - 辰时=07/08、巳时=09/10、午时=11/12、未时=13/14
/// - 申时=15/16、酉时=17/18、戌时=19/20、亥时=21/22
///   边界：hour=23 与 hour=0 同为「子时」（跨夜显式两段）；
///   hour=11 与 hour=12 同为「午时」（跨午线显式两段）。
pub const 时辰名表: [&str; 24] = [
    /* 00 */ "子时", /* 01 */ "丑时", "丑时", /* 03 */ "寅时", "寅时",
    /* 05 */ "卯时", "卯时", /* 07 */ "辰时", "辰时", /* 09 */ "巳时", "巳时",
    /* 11 */ "午时", "午时", /* 13 */ "未时", "未时", /* 15 */ "申时", "申时",
    /* 17 */ "酉时", "酉时", /* 19 */ "戌时", "戌时", /* 21 */ "亥时", "亥时",
    /* 23 */ "子时",
];

/// 24 小时制小时（0..=23）对应的时段描述。
/// 边界同上：23 与 0 同为「二十三点到一点」；11 与 12 同为「十一点到十三点」。
pub const 时段描述: [&str; 24] = [
    /* 00 */ "二十三点到一点",
    /* 01 */ "一点到三点",
    "一点到三点",
    /* 03 */ "三点到五点",
    "三点到五点",
    /* 05 */ "五点到七点",
    "五点到七点",
    /* 07 */ "七点到九点",
    "七点到九点",
    /* 09 */ "九点到十一点",
    "九点到十一点",
    /* 11 */ "十一点到十三点",
    "十一点到十三点",
    /* 13 */ "十三点到十五点",
    "十三点到十五点",
    /* 15 */ "十五点到十七点",
    "十五点到十七点",
    /* 17 */ "十七点到十九点",
    "十七点到十九点",
    /* 19 */ "十九点到二十一点",
    "十九点到二十一点",
    /* 21 */ "二十一点到二十三点",
    "二十一点到二十三点",
    /* 23 */ "二十三点到一点",
];

/// 兜底元组：越界小时（>= 24）统一返回。
const 兜底元组: (&str, &str) = ("时辰未知", "时辰未知");

/// 纯函数：根据 24 小时制小时查表返回（时辰名, 时段描述）。
/// 越界值（hour >= 24）统一返回兜底元组（"时辰未知", "时辰未知"）。
/// 链路无 Result、无 unwrap、无错误传播。
pub fn 时辰由小时(hour: u32) -> (&'static str, &'static str) {
    if hour >= 24 {
        return 兜底元组;
    }
    (时辰名表[hour as usize], 时段描述[hour as usize])
}

/// 格式化辅助：一次性产出「辰时（七点到九点）」样式的字符串。
pub fn 格式化时辰(名: &str, 段: &str) -> String {
    format!("{名}（{段}）")
}

/// 入口函数：取当前北京时间（UTC+8）的时辰并格式化输出。
/// 链路无 Result、无 unwrap、无错误传播：
/// UNIX 秒戳 + 8h 偏移 → 总秒 mod 86400 / 3600 = 北京时间小时 → 查表 → 格式化。
pub fn 当前时辰() -> String {
    // 北京时间相对 UTC 的偏移（秒）
    const 北京偏移秒: u64 = 8 * 3600;
    let 总秒_utc = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_secs())
        .unwrap_or(0);
    let 时 = ((总秒_utc + 北京偏移秒) / 3600 % 24) as u32;
    let (名, 段) = 时辰由小时(时);
    格式化时辰(名, 段)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// 全 24 小时索引真值表校验（含子时跨夜、午时跨午线两段显式）。
    #[test]
    fn 验证全索引真值表() {
        // 子时跨夜显式两段：23 与 0 同为「子时 / 二十三点到一点」
        assert_eq!(时辰名表[0], "子时");
        assert_eq!(时段描述[0], "二十三点到一点");
        assert_eq!(时辰名表[23], "子时");
        assert_eq!(时段描述[23], "二十三点到一点");
        assert_eq!(时辰由小时(0), ("子时", "二十三点到一点"));
        assert_eq!(时辰由小时(23), ("子时", "二十三点到一点"));

        // 丑时 01/02
        assert_eq!(时辰由小时(1), ("丑时", "一点到三点"));
        assert_eq!(时辰由小时(2), ("丑时", "一点到三点"));
        // 寅时 03/04
        assert_eq!(时辰由小时(3), ("寅时", "三点到五点"));
        assert_eq!(时辰由小时(4), ("寅时", "三点到五点"));
        // 卯时 05/06
        assert_eq!(时辰由小时(5), ("卯时", "五点到七点"));
        assert_eq!(时辰由小时(6), ("卯时", "五点到七点"));
        // 辰时 07/08
        assert_eq!(时辰由小时(7), ("辰时", "七点到九点"));
        assert_eq!(时辰由小时(8), ("辰时", "七点到九点"));
        // 巳时 09/10 —— 重点校验 9→巳时（非辰时）
        assert_eq!(时辰由小时(9), ("巳时", "九点到十一点"));
        assert_ne!(时辰由小时(9).0, "辰时", "hour=9 不应是辰时");
        assert_eq!(时辰由小时(10), ("巳时", "九点到十一点"));

        // 午时跨午线显式两段：11 与 12 同为「午时 / 十一点到十三点」
        assert_eq!(时辰由小时(11), ("午时", "十一点到十三点"));
        assert_eq!(时辰由小时(12), ("午时", "十一点到十三点"));
        // 未时 13/14 —— 重点校验 13→未时
        assert_eq!(时辰由小时(13), ("未时", "十三点到十五点"));
        assert_eq!(时辰由小时(14), ("未时", "十三点到十五点"));

        // 申时 15/16
        assert_eq!(时辰由小时(15), ("申时", "十五点到十七点"));
        assert_eq!(时辰由小时(16), ("申时", "十五点到十七点"));
        // 酉时 17/18
        assert_eq!(时辰由小时(17), ("酉时", "十七点到十九点"));
        assert_eq!(时辰由小时(18), ("酉时", "十七点到十九点"));
        // 戌时 19/20 —— 重点校验 19/20→戌时
        assert_eq!(时辰由小时(19), ("戌时", "十九点到二十一点"));
        assert_eq!(时辰由小时(20), ("戌时", "十九点到二十一点"));
        // 亥时 21/22 —— 重点校验 21→亥时（非戌时）
        assert_eq!(时辰由小时(21), ("亥时", "二十一点到二十三点"));
        assert_ne!(时辰由小时(21).0, "戌时", "hour=21 不应是戌时");
        assert_eq!(时辰由小时(22), ("亥时", "二十一点到二十三点"));

        // 真值表逐项断言：0..=23 全覆盖
        for hour in 0u32..24 {
            let (名, 段) = 时辰由小时(hour);
            assert_eq!(名, 时辰名表[hour as usize], "hour={hour} 时辰名不一致");
            assert_eq!(段, 时段描述[hour as usize], "hour={hour} 时段描述不一致");
        }
    }

    /// 越界值统一兜底：hour >= 24 返回（「时辰未知」，「时辰未知」）。
    #[test]
    fn 验证越界兜底() {
        assert_eq!(时辰由小时(24), ("时辰未知", "时辰未知"));
        assert_eq!(时辰由小时(25), ("时辰未知", "时辰未知"));
        assert_eq!(时辰由小时(99), ("时辰未知", "时辰未知"));
        assert_eq!(时辰由小时(u32::MAX), ("时辰未知", "时辰未知"));
    }

    /// 格式化辅助产出「辰时（七点到九点）」样式。
    #[test]
    fn 验证格式化时辰() {
        assert_eq!(格式化时辰("辰时", "七点到九点"), "辰时（七点到九点）");
        assert_eq!(
            格式化时辰("子时", "二十三点到一点"),
            "子时（二十三点到一点）"
        );
        assert_eq!(
            格式化时辰("午时", "十一点到十三点"),
            "午时（十一点到十三点）"
        );
        // 兜底元组同样能格式化（保证链路不抛）
        assert_eq!(格式化时辰("时辰未知", "时辰未知"), "时辰未知（时辰未知）");
    }

    /// 入口函数返回非空字符串、含「时」字与「（...点到...点）」模式或兜底。
    #[test]
    fn 验证当前时辰入口() {
        let 输出 = 当前时辰();
        assert!(!输出.is_empty(), "当前时辰输出不应为空");
        // 合法输出：含「（」与「）」，且以「时」结尾；兜底输出含「未知」
        if 输出.contains("未知") {
            assert_eq!(输出, "时辰未知（时辰未知）");
        } else {
            assert!(输出.ends_with("）"), "合法输出应以 '）' 结尾：{输出}");
            assert!(
                输出.starts_with("子时")
                    || 输出.starts_with("丑时")
                    || 输出.starts_with("寅时")
                    || 输出.starts_with("卯时")
                    || 输出.starts_with("辰时")
                    || 输出.starts_with("巳时")
                    || 输出.starts_with("午时")
                    || 输出.starts_with("未时")
                    || 输出.starts_with("申时")
                    || 输出.starts_with("酉时")
                    || 输出.starts_with("戌时")
                    || 输出.starts_with("亥时"),
                "合法输出应以十二时辰起始：{输出}"
            );
            assert!(输出.contains("点到"), "合法输出应含 '点到'：{输出}");
        }
    }
}
