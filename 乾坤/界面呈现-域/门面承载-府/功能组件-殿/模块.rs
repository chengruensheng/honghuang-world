//! 功能组件-殿：承载各槽位的具体组件。
//!
//! 隔离约定（与布局层一致）：
//! - 组件只经 挂载契约（乾坤界面.挂载）进入槽位，不得触碰 .界面-* 结构；
//! - 组件样式只引用背景层令牌（var(--契) 等），不写死色值；
//! - 每个组件园导出「样式 + 脚本」源码字符串，由页面承载殿内联组装。
//!
//! 聚合出口：统一暴露 组件样式 / 组件脚本（合并全部组件），组装模块只认这一对。

#[path = "侧栏图标-阁/模块.rs"]
mod 侧栏图标_阁;

#[path = "设置面板-阁/模块.rs"]
mod 设置面板_阁;

#[path = "顶栏状态-阁/模块.rs"]
mod 顶栏状态_阁;

#[path = "底栏状态-阁/模块.rs"]
mod 底栏状态_阁;

#[path = "对话流-阁/模块.rs"]
mod 对话流_阁;

#[path = "看板流-阁/模块.rs"]
mod 看板流_阁;

#[path = "左栏视图-阁/模块.rs"]
mod 左栏视图_阁;

pub use 侧栏图标_阁::{图标脚本, 图标样式};
pub use 设置面板_阁::{面板脚本, 面板样式};
pub use 顶栏状态_阁::{顶栏脚本, 顶栏样式};
pub use 底栏状态_阁::{底栏脚本, 底栏样式};
pub use 对话流_阁::{对话脚本, 对话样式};
pub use 看板流_阁::{看板脚本, 看板样式};
pub use 左栏视图_阁::{视图脚本, 视图样式};

/// 全部组件样式合并（供页面承载殿内联）
pub fn 组件样式() -> String {
    format!("{图标样式}\n{面板样式}\n{顶栏样式}\n{底栏样式}\n{对话样式}\n{看板样式}\n{视图样式}")
}

/// 全部组件脚本合并（供页面承载殿内联）
pub fn 组件脚本() -> String {
    format!("{图标脚本}\n{面板脚本}\n{顶栏脚本}\n{底栏脚本}\n{对话脚本}\n{看板脚本}\n{视图脚本}")
}
