const 初始列表 = 静态元数据.map((引擎) => ({ ...引擎, 数值: '—', 单位: '', 副: '加载中…', 占比: '0%' }));

export const 引擎存储 = 创建存储({ 列表: 初始列表 });

const 取json = (响应) => 响应.json();

/** 从后端拉取五引擎真实数据并聚合为卡片数值 */
export async function 加载引擎数据() {
  try {
    const [任务, 迭代, 记忆, 规则, 事件, 版本] = await Promise.all([
      fetch('/api/tasks').then(取json),
      fetch('/api/iterations').then(取json),
      fetch('/api/memories').then(取json),
      fetch('/api/rules').then(取json),
      fetch('/api/events').then(取json),
      fetch('/api/iterations/version').then(取json),
    ]);
    const 列表 = 静态元数据.map((引擎) => 聚合(引擎, 任务, 迭代, 记忆, 规则, 事件, 版本));
    引擎存储.更新({ 列表 });
  } catch (错误) {
    console.warn('加载引擎数据失败（后端未就绪？）', 错误);
  }
}

function 聚合(引擎, 任务, 迭代, 记忆, 规则, 事件, 版本) {
  switch (引擎.名) {
    case '太初': {
      const 待受理 = 任务.filter((t) => t.status === '待受理').length;
      const 进行中 = 任务.filter((t) => t.status === '进行中').length;
      return { ...引擎, 数值: 任务.length, 单位: '个', 副: `进行中 ${进行中} · 待受理 ${待受理}`, 占比: 占比(任务.length, 100) };
    }
    case '量劫': {
      const 进行中 = 迭代.filter((i) => i.status === '进行中').length;
      return { ...引擎, 数值: 版本格式(版本), 单位: '', 副: `当前版本 · 进行中 ${进行中}`, 占比: 占比(迭代.length, 100) };
    }
    case '乾坤': {
      const 待归档 = 记忆.filter((m) => m.归档).length;
      return { ...引擎, 数值: 记忆.length, 单位: '条', 副: `待归档 ${待归档} · 已索引`, 占比: 占比(记忆.length, 200) };
    }
    case '道韵':
      return { ...引擎, 数值: 规则.length, 单位: '条', 副: `规则总数 ${规则.length}`, 占比: 占比(规则.length, 100) };
    case '混沌':
      return { ...引擎, 数值: 事件.length, 单位: '条', 副: `事件总数 ${事件.length}`, 占比: 占比(事件.length, 1000) };
    default:
      return 引擎;
  }
}

function 版本格式(版本) {
  if (!版本) return '0.0.0';
  return `${版本.主}.${版本.次}.${版本.修订}`;
}

function 占比(数值, 上限) {
  const 百分比 = Math.min(100, Math.round((数值 / 上限) * 100));
  return `${百分比}%`;
}
