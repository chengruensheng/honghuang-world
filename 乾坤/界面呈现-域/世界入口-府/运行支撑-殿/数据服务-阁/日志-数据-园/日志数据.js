// 日志数据.js —— 运行日志共享存储（跨视图通信：对话视图写，日志视图读）

import { 创建存储 } from '../../状态管理-阁/响应式-核心-园/响应式核心.js';

export const 日志存储 = 创建存储({ 记录: [] });

/** 追加一条运行日志 */
export function 记日志(标签, 样式, 内容) {
  const 记录 = {
    标签,
    样式,
    内容,
    时间: new Date().toTimeString().slice(0, 8),
  };
  日志存储.更新({ 记录: [...日志存储.取值().记录, 记录] });
}