/** 事件类型 → 图标（未知类型兜底 `•`） */
export const 事件图标 = (类型) =>
  ({ '思考': '💭', '工具调用': '🔧', '工具结果': '✅', '任务答复': '📝' }[类型] || '•');

/** 事件类型 → proc-item 附加 CSS 类（未知类型空串，对话视图不加类） */
export const 事件类型类 = (类型) =>
  ({ '思考': 'think', '工具调用': 'tool-call', '工具结果': 'tool-result', '任务答复': 'reply' }[类型] || '');

/** 角色 → 中文名；`中文映射` 缺省/未命中/角色缺失时退回 `角色 || '?'` */
export const 事件角色 = (角色, 中文映射) => (中文映射 && 中文映射[角色]) || 角色 || '?';
