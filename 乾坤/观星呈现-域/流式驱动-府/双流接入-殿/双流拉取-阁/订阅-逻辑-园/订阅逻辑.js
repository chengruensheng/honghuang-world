import { 运行时, 连接语, 刷天机空态, 总线, 广播 } from "/底座骨架-府/台面框架-殿/视图装配-阁/装配-逻辑-园/运行时中枢.js";
import { 事件词表 } from "/契约词表-府/常量定义-殿/事件词表-阁/词表-数据-园/契约词表.js";
import { 事件脚本 } from "/契约词表-府/常量定义-殿/演示语料-阁/样例-数据-园/演示语料.js";

export function 停(){
  运行时.播放计时.forEach(clearTimeout); 运行时.播放计时 = [];
  // 摘掉 onerror 再关：否则关闭动作本身会被当成「断线」写进状态语
  if(运行时.事件源){ 运行时.事件源.onerror = null; 运行时.事件源.close(); 运行时.事件源 = null; }
  if(运行时.阶段源){ 运行时.阶段源.onerror = null; 运行时.阶段源.close(); 运行时.阶段源 = null; }
  运行时.已连流.clear();
}

/** 请观测台面清台回到初始态——本府不碰 DOM，经总线发令。
    （切模式与重放共用这一份口径：清右栏、隐藏阶段条、左栏退回初始态，由对方一次做全。） */
function 请复位(空态语){ 广播(总线.复位呈现, {空态语}); }

export function 重放事件(){
  停();
  请复位();
  连接语("演示数据 · 契约对齐");
  运行时.待确认 = false;                 // 演示不跑确认发布流程
  广播(总线.播放脚本, {脚本: 事件脚本});
}

/** 状态语只描述已确认的事实，不描述意图 */
export function 刷连接语(){
  const 流 = [...运行时.已连流];
  if(流.length >= 2){ 连接语("实时 · 已连接 " + 流.join(" + ")); 刷天机空态("实时已连接，等待任务事件…"); }
  else if(流.length === 1){ 连接语("实时 · 部分连接（" + 流[0] + "）"); 刷天机空态("实时部分连接，等待任务事件…"); }
  else { 连接语("实时 · 未连接"); 刷天机空态("实时流未连接 · 检查后端服务是否在运行"); }
}

/** 订阅一条 AG-UI 流；帧经词表白名单校验后经总线转交 观测台面-府 归位 */
export function 订阅(路径, 标签){
  const 源 = new EventSource(路径);
  源.onopen = ()=>{ 运行时.已连流.add(标签); 刷连接语(); };
  源.onmessage = (e)=>{
    try{
      const ev = JSON.parse(e.data);
      if(!事件词表.includes(ev.type)){ console.warn("词表外事件：", ev); return; }
      广播(总线.收到帧, {帧: ev});
    }catch(err){ console.warn("非法帧：", e.data); }
  };
  源.onerror = ()=>{ 运行时.已连流.delete(标签); 刷连接语(); };
  return 源;
}

export function 连实时(){
  停();
  请复位("实时 · 连接中…");
  连接语("实时 · 连接中…");
  // 过程流：思考 / 工具调用 / 工具结果 / 任务答复
  运行时.事件源 = 订阅("/api/dev/stream/agui", "过程流");
  // 阶段流：阶段完成 / 运行结束 / 运行错误（另一条契约流，与过程流并行订阅）
  运行时.阶段源 = 订阅("/api/dev/stream/agui/state", "阶段流");
}
