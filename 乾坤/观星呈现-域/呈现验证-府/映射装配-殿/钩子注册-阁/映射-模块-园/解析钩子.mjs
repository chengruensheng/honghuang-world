/* ============================================================
   观星呈现-域 · 呈现验证-府 · 映射装配-殿 · 解析钩子
   呈现域源码一律以 `/xxx` 绝对路径 import（HTTP 托管根 = 域根，
   见 对外契约.toml 的 static_dir）。node 侧不存在这个托管根，
   必须把 `/xxx` 折回域根，否则被测模块的依赖链在 node 下一律解析失败——
   测试跑不起来，「覆盖」就是一句空话。

   回退层级：域/呈现验证-府/映射装配-殿/钩子注册-阁/映射-模块-园/ → 域根 = 四层。
   ============================================================ */

const 域根 = new URL('../../../../', import.meta.url);

export async function resolve(说明符, 上下文, 下一跳){
  if(说明符.startsWith('/')) return 下一跳(new URL('.' + 说明符, 域根).href, 上下文);
  return 下一跳(说明符, 上下文);
}
