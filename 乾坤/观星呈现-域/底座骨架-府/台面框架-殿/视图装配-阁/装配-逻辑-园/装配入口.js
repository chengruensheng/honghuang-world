/** 发送「呈上」：统一走道祖接待（POST + 手动读 SSE）。界面默认即实时，无演示分支。 */
function 呈上(得){
  const 框 = $("#输入");
  const 文 = 框.value.trim();
  if(!文) return;
  框.value = "";
  const 流 = $("#对话流");
  if(!得.左栏){ 流.innerHTML = `<div class="空" style="height:auto;padding:30px 10px"><div class="符">○</div><div class="语">对话呈现未就绪</div></div>`; return; }
  流.querySelector(".空")?.remove();
  const {泡} = 得.左栏.起消息(流, "来客", "刚刚");
  泡.textContent = 文;
  流.parentElement.scrollTop = 流.parentElement.scrollHeight;
  得.接待?.问道祖(文);
}

/** 交互接线：基础图标栏（切视图 / 展开栏开合）/ 发送 / 输入法回车 */
function 接线(得){
  const 切视图 = (名, 取数据 = true)=>{
    $("#视图-观星台").classList.toggle("显", 名 === "观星台");
    $("#视图-看板").classList.toggle("显", 名 === "看板");
    $("#视图-格位").classList.toggle("显", 名 === "格位");
    $("#视图-道规").classList.toggle("显", 名 === "道规");
    $("#轨观星台").classList.toggle("当前", 名 === "观星台");
    $("#轨看板").classList.toggle("当前", 名 === "看板");
    $("#轨格位").classList.toggle("当前", 名 === "格位");
    $("#轨道规").classList.toggle("当前", 名 === "道规");
    // 进某视图即取一次权威数据；由「点任务号跳转」触发时传 false——
    // 那条路径自己会等数据回来再定位，这里再取一次就是白跑一趟。
    if(取数据){
      if(名 === "看板") 得.看板?.拉看板();
      else if(名 === "格位") 得.认知?.拉格位();
      else if(名 === "道规") 得.认知?.拉道规();
    }
  };
  得.切视图 = 切视图;   // 总线里的「按任务号跳看板」要复用同一份切换口径
  $("#轨观星台").addEventListener("click", ()=>切视图("观星台"));
  $("#轨看板").addEventListener("click", ()=>切视图("看板"));
  $("#轨格位").addEventListener("click", ()=>切视图("格位"));
  $("#轨道规").addEventListener("click", ()=>切视图("道规"));

  // 侧面板（活动栏模式）：点面钮打开对应面板，再点同一钮收起，点别的则切换；只动展开栏，不碰主视图。
  // 承面板：按 data-面板 名分别挂内容——架构/设计接真实文件清单，其余维持「待承纳」占位。
  const 承面板 = (名)=>{
    const 身 = $("#展身");
    if(名 === "架构"){ if(得.文档) 得.文档.拉架构(); else 身.innerHTML = `<div class="展空">文档呈现未就绪</div>`; }
    else if(名 === "设计"){ if(得.文档) 得.文档.拉设计(); else 身.innerHTML = `<div class="展空">文档呈现未就绪</div>`; }
    else 身.innerHTML = `<div class="展空" id="展空">此面板由基础栏图标开启<br>内容待后续承纳</div>`;
  };
  let 当前面板 = "";
  document.querySelectorAll(".面钮").forEach(钮=>{
    钮.addEventListener("click", ()=>{
      const 名 = 钮.dataset.面板;
      const 栏 = $("#展开栏");
      const 收起 = 栏.classList.contains("开") && 当前面板 === 名;
      document.querySelectorAll(".面钮").forEach(b=>{
        b.setAttribute("aria-expanded", (!收起 && b === 钮) ? "true" : "false");
      });
      if(收起){ 栏.classList.remove("开"); 当前面板 = ""; return; }
      $("#展标题").textContent = 名;   // 名取自静态 data-面板，textContent 落字无注入面
      栏.classList.add("开");
      当前面板 = 名;
      承面板(名);
    });
  });

  $("#发送").addEventListener("click", ()=>呈上(得));
  $("#输入").addEventListener("keydown", (e)=>{
    // 中文输入法选字时的 Enter 是「确认候选词」，不是「发送」——必须放过
    if(e.isComposing || e.keyCode === 229) return;
    if(e.key === "Enter" && !e.shiftKey){ e.preventDefault(); $("#发送").click(); }
  });
}

/** 底栏「当前任务与角色」：只陈述帧里已确认的事实；同一棒（runId+号+角色）只写一次。
    任务号位置兼容两版契约：实时在顶层 ev.任务id，历史样例在 ev.input.任务id。 */
let 底栏棒键 = "";
function 底栏随帧(ev){
  const 位 = $("#底栏当前");
  if(!位 || !ev) return;
  const 号 = ev.任务id || (ev.input && ev.input.任务id);
  if(!号) return;
  const 角 = ev.角色 || "";
  if(ev.type === "RUN_FINISHED"){ 位.textContent = `任务 #${号} · 本轮驱动收尾`; 底栏棒键 = ""; return; }
  if(ev.type === "RUN_ERROR"){ 位.textContent = `任务 #${号} · 驱动出错`; return; }
  if(ev.type === "STEP_FINISHED"){ if(角) 位.textContent = `任务 #${号} · ${角}已交接`; return; }
  const 键 = `${ev.runId}|${号}|${角}`;
  if(角 && 键 !== 底栏棒键){ 底栏棒键 = 键; 位.textContent = `任务 #${号} · ${角}任期中`; }
}

/** 总线承接：府与府之间不互相 import，只经总线发令；
    顶层编排（本入口）是唯一的接线台——把一府的发令转给另一府的接口。
    注意顺序：订阅府被调用后会立刻广播「复位呈现」，故本表必须在连流之前接好。 */
function 承总线(得){
  const 接 = (名, 处理)=> 得.底架.监听(名, 处理);
  const 线 = 得.底架.总线;
  接(线.收到帧,     (d)=>{ 得.帧流?.收帧(d.帧); 底栏随帧(d.帧); });   // 流式驱动 → 观测台面：喂一帧；底栏同步当前任务/角色
  接(线.复位呈现,   (d)=>得.帧流?.复位呈现(d.空态语));     // 流式驱动 → 观测台面：清台回初始态
  接(线.播放脚本,   (d)=>得.帧流?.播放脚本(d.脚本));       // 流式驱动 → 观测台面：按节拍重放样例
  接(线.请求拉看板, ()=>得.看板?.拉看板());                // 观测台面 → 看板流转：取一次权威数据
  接(线.请求看板定位, async (d)=>{                        // 观测台面 → 看板流转：切到看板并定位该任务卡
    得.切视图?.("看板", false);
    // 先取一次权威数据再定位，否则定位的是上一版渲染的卡片（任务刚流转时会找不到）。
    await 得.看板?.拉看板();
    得.看板?.定位任务(d.任务id);
  });
  接(线.请求重放,   ()=>得.订阅?.重放事件());              // 观测台面（发布）→ 流式驱动：重放
  接(线.接待开启,   (d)=>得.左栏?.接待开启(d));            // 流式驱动 → 观测台面：起接待气泡
  接(线.接待思考,   (d)=>得.左栏?.接待思考(d));            // 流式驱动 → 观测台面：推理条（独立通道）
  接(线.接待增量,   (d)=>得.左栏?.接待增量(d));            // 流式驱动 → 观测台面：流式追加
  接(线.接待收尾,   (d)=>得.左栏?.接待收尾(d));            // 流式驱动 → 观测台面：收尾 + 确认钮
}

async function 启动(){
  const {得, 失} = await 装载(模块清单);
  const 架 = 得.底架;
  if(!架){
    降级("#对话流", "运行时中枢未就绪 · 呈现层无法启动");
    降级("#事件流", "运行时中枢未就绪 · 呈现层无法启动");
    return;
  }

  // 未装载成功的模块：在其负责区域落降级提示——界面只说已确认的事实，不假装正常
  失.forEach(([名, 错])=>{
    console.error(`[观星呈现] ${名} 装载失败：`, 错);
    if(名 === "左栏") 降级("#对话流", "对话呈现未就绪（该府装载失败）");
    if(名 === "筛选") 降级("#角色入口", "角色筛选未就绪（该府装载失败）");
    if(名 === "看板") 降级("#泳道区", "看板呈现未就绪（该府装载失败）");
    if(名 === "认知") 降级("#格位区", "认知呈现未就绪（该府装载失败）");
    if(名 === "帧流") 降级("#事件流", "天机事件呈现未就绪（观测台面-府装载失败）");
    if(名 === "订阅") 降级("#事件流", "天机事件流未就绪（流式驱动-府装载失败）");
  });

  if(得.筛选){ 得.筛选.渲染入口(); 得.筛选.渲染天机筛(); }

  // 首屏直连真实契约：看板读 /api/board，天机接 AG-UI 双流。界面默认即实时（演示切换已下架）。
  架.运行时.模式 = "实时";
  if(得.左栏) 得.左栏.渲染对话();
  if(得.看板) 得.看板.拉看板();

  接线(得);
  承总线(得);                    // 总线必须先接好：连流一开口就会广播「复位呈现」
  if(得.订阅) 得.订阅.连实时();
}

启动().catch(错=>{
  console.error("[观星呈现] 装配失败：", 错);
  降级("#对话流", "呈现层装配失败：" + (错 && 错.message ? 错.message : 错));
});
