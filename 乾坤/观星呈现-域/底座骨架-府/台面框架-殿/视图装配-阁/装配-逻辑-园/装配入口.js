/* ============================================================
   观星呈现-域 · 底座骨架-府 · 装配入口
   域层唯一的装配点：把各府动态装载起来，再把交互接上。

   韧性：一律用 await import() 逐府装载，每府各包一层 try/catch。
   哪一府出错，只在该府负责的区域落降级提示，骨架（index.html）
   与其余府照常工作。若用静态 import，一处语法错就整链全挂，无隔离可言。
   见 rules/呈现域规则.md 四·2。
   ============================================================ */

/** 装配入口自身不 import 任何府：底座骨架崩了它仍能给出降级提示 */
const $ = (s)=>document.querySelector(s);

/** 逐府装载：返回成功表与失败清单。单个府失败不抛出，交给降级处理。 */
async function 装载(清单){
  const 得 = {}, 失 = [];
  for(const [府, 路径] of 清单){
    try{ 得[府] = await import(路径); }
    catch(错){ 失.push([府, 错]); }
  }
  return {得, 失};
}

/** 府级降级：把失败写进该府负责的区域——界面对「哪一块坏了」要照实说 */
function 降级(区选择器, 说明){
  const 区 = $(区选择器);
  if(区) 区.innerHTML = `<div class="空" style="height:auto;padding:30px 10px"><div class="符">○</div><div class="语">${说明}</div></div>`;
}

/** 模块清单 —— 域 → 府 是唯一的装配依赖方向；府与府之间只经总线通信，互不 import。
    每个府只列一个对外模块，府内其它模块随它一并装载（依赖链由浏览器解析）。 */
const 模块清单 = [
  ["底架", "/底座骨架-府/台面框架-殿/视图装配-阁/装配-逻辑-园/运行时中枢.js"],
  ["帧流", "/观测台面-府/天机事件-殿/帧流归位-阁/编排-逻辑-园/帧编排.js"],
  ["左栏", "/观测台面-府/万仙对话-殿/消息渲染-阁/对话-渲染-园/对话渲染.js"],
  ["筛选", "/观测台面-府/筛选联动-殿/角色入口-阁/筛选-逻辑-园/筛选联动.js"],
  ["看板", "/看板流转-府/泳道绘现-殿/卡面渲染-阁/看板-渲染-园/看板渲染.js"],
  ["订阅", "/流式驱动-府/双流接入-殿/双流拉取-阁/订阅-逻辑-园/订阅逻辑.js"],
  ["接待", "/流式驱动-府/双流接入-殿/接待往返-阁/问答-逻辑-园/接待逻辑.js"],
];

/** 发送「呈上」：演示模式回固定话术；实时模式走道祖接待（POST + 手动读 SSE） */
function 呈上(得){
  const 框 = $("#输入");
  const 文 = 框.value.trim();
  if(!文) return;
  框.value = "";
  const 流 = $("#对话流");
  if(!得.左栏){ 流.innerHTML = `<div class="空" style="height:auto;padding:30px 10px"><div class="符">○</div><div class="语">对话呈现未就绪</div></div>`; return; }
  流.querySelector(".空")?.remove();
  const {泡} = 得.左栏.起消息(流, "来客", "刚刚");
  泡.textContent = 文;
  流.parentElement.scrollTop = 流.parentElement.scrollHeight;
  if(得.底架.运行时.模式 === "演示"){
    setTimeout(()=>{
      const {泡:回} = 得.左栏.起消息(流, "道祖", "主控");
      回.textContent = "（演示模式）已收到。切到「实时」，此消息会由 /api/dev/chat/stream 流式返回真实答复。";
      流.parentElement.scrollTop = 流.parentElement.scrollHeight;
    }, 600);
    return;
  }
  得.接待?.问道祖(文);
}

/** 交互接线：视图切换 / 模式切换 / 发送 / 输入法回车 */
function 接线(得){
  const 切视图 = (名)=>{
    $("#视图-观星台").classList.toggle("显", 名 === "观星台");
    $("#视图-看板").classList.toggle("显", 名 === "看板");
    $("#签观星台").classList.toggle("当前", 名 === "观星台");
    $("#签看板").classList.toggle("当前", 名 === "看板");
    if(名 === "看板" && 得.底架.运行时.模式 === "实时") 得.看板?.拉看板();   // 实时态每次进看板都取一次权威数据
  };
  $("#签观星台").addEventListener("click", ()=>切视图("观星台"));
  $("#签看板").addEventListener("click", ()=>切视图("看板"));

  $("#钮演示").addEventListener("click", ()=>{
    得.底架.运行时.模式 = "演示";
    $("#钮演示").classList.add("选"); $("#钮实时").classList.remove("选");
    得.订阅?.重放事件();
  });
  $("#钮实时").addEventListener("click", ()=>{
    得.底架.运行时.模式 = "实时";
    $("#钮实时").classList.add("选"); $("#钮演示").classList.remove("选");
    得.订阅?.连实时();
  });
  $("#发送").addEventListener("click", ()=>呈上(得));
  $("#输入").addEventListener("keydown", (e)=>{
    // 中文输入法选字时的 Enter 是「确认候选词」，不是「发送」——必须放过
    if(e.isComposing || e.keyCode === 229) return;
    if(e.key === "Enter" && !e.shiftKey){ e.preventDefault(); $("#发送").click(); }
  });
}

/** 总线承接：府与府之间不互相 import，只经总线发令；
    顶层编排（本入口）是唯一的接线台——把一府的发令转给另一府的接口。
    注意顺序：订阅府被调用后会立刻广播「复位呈现」，故本表必须在连流之前接好。 */
function 承总线(得){
  const 接 = (名, 处理)=> 得.底架.监听(名, 处理);
  const 线 = 得.底架.总线;
  接(线.收到帧,     (d)=>得.帧流?.收帧(d.帧));            // 流式驱动 → 观测台面：喂一帧
  接(线.复位呈现,   (d)=>得.帧流?.复位呈现(d.空态语));     // 流式驱动 → 观测台面：清台回初始态
  接(线.播放脚本,   (d)=>得.帧流?.播放脚本(d.脚本));       // 流式驱动 → 观测台面：按节拍重放样例
  接(线.请求拉看板, ()=>得.看板?.拉看板());                // 观测台面 → 看板流转：取一次权威数据
  接(线.请求重放,   ()=>得.订阅?.重放事件());              // 观测台面（发布）→ 流式驱动：重放
  接(线.接待开启,   (d)=>得.左栏?.接待开启(d));            // 流式驱动 → 观测台面：起接待气泡
  接(线.接待增量,   (d)=>得.左栏?.接待增量(d));            // 流式驱动 → 观测台面：流式追加
  接(线.接待收尾,   (d)=>得.左栏?.接待收尾(d));            // 流式驱动 → 观测台面：收尾 + 确认钮
}

async function 启动(){
  const {得, 失} = await 装载(模块清单);
  const 架 = 得.底架;
  if(!架){
    降级("#对话流", "运行时中枢未就绪 · 呈现层无法启动");
    降级("#事件流", "运行时中枢未就绪 · 呈现层无法启动");
    return;
  }

  // 未装载成功的模块：在其负责区域落降级提示——界面只说已确认的事实，不假装正常
  失.forEach(([名, 错])=>{
    console.error(`[观星呈现] ${名} 装载失败：`, 错);
    if(名 === "左栏") 降级("#对话流", "对话呈现未就绪（该府装载失败）");
    if(名 === "筛选") 降级("#角色入口", "角色筛选未就绪（该府装载失败）");
    if(名 === "看板") 降级("#泳道区", "看板呈现未就绪（该府装载失败）");
    if(名 === "帧流") 降级("#事件流", "天机事件呈现未就绪（观测台面-府装载失败）");
    if(名 === "订阅") 降级("#事件流", "天机事件流未就绪（流式驱动-府装载失败）");
  });

  if(得.筛选){ 得.筛选.渲染入口(); 得.筛选.渲染天机筛(); }

  // 首屏直连真实契约：看板读 /api/board，天机接 AG-UI 双流。
  // 演示语料保留为契约样例（切「演示」即重放），不再是默认面对用户的那一面。
  架.运行时.模式 = "实时";
  $("#钮实时").classList.add("选"); $("#钮演示").classList.remove("选");
  if(得.左栏) 得.左栏.渲染对话();
  if(得.看板) 得.看板.拉看板();

  接线(得);
  承总线(得);                    // 总线必须先接好：连流一开口就会广播「复位呈现」
  if(得.订阅) 得.订阅.连实时();
}

启动().catch(错=>{
  console.error("[观星呈现] 装配失败：", 错);
  降级("#对话流", "呈现层装配失败：" + (错 && 错.message ? 错.message : 错));
});
