/** 帧筛选：左栏对话与右栏天机共用这一份判据，两处各算一套早晚漂移 */
export const 过筛 = (ev)=> 运行时.筛选 === "全部" || (ev.角色 || "系统") === 运行时.筛选;

/** 状态语（顶栏）：只描述已确认的事实，不描述意图 */
export function 连接语(文){ $("#连接语").textContent = 文; }

/** 天机空态：无事件时不留白屏——空态本身要说明「在等什么」。
    但该区若已被顶层标为故障，则不改写：故障说明是确认过的事实，
    让「等待事件…」盖掉「该府装载失败」，等于界面替一个坏掉的区域自述正常。 */
export function 渲染天机空态(语){
  const 区 = $("#事件流");
  if(区.dataset.降级) return;
  区.innerHTML = `<div class="空"><div class="符">○</div><div class="语">${转义(语)}</div></div>`;
}

/** 空态只在「当前没有棒」时才改写——已经有内容了就别往中间插空态。
    只依赖 $ 与 渲染天机空态，故与它们同归公共底座，供各府共用。 */
export function 刷天机空态(语){
  if($("#事件流").querySelector(".棒")) return;
  渲染天机空态(语);
}

