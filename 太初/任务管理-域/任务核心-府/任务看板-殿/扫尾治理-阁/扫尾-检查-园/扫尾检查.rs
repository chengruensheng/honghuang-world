use crate::任务模型_殿::{漂移报告, 扫尾记录};

/// 扫尾检查：把漂移报告 + 自检结果组合为任务级扫尾结论。
///
/// 判定：存在未兑现声明 / 存在未声明新增 / 实现自检不通过，任一成立即不通过。
/// `实现文档声明数` 由调用方传入（已从实现文档 `代码变更` 提取）。
pub fn 扫尾检查(
    检查时间: u64,
    实现文档声明数: usize,
    自检通过: bool,
    报告: &漂移报告,
) -> 扫尾记录 {
    let mut 说明 = String::new();
    if !自检通过 {
        说明 = "实现文档自检未通过".into();
    }
    let 零漂移 = 报告.零漂移();
    if !零漂移 {
        if !说明.is_empty() {
            说明.push('；');
        }
        说明.push_str(&format!(
            "漂移 {} 项（声明未兑现 {} / 多余新增 {}）",
            报告.未兑现数 + 报告.多余数,
            报告.未兑现数,
            报告.多余数
        ));
    }
    扫尾记录 {
        检查时间,
        变更总数: 实现文档声明数,
        兑现数: 报告.兑现数,
        未兑现数: 报告.未兑现数,
        多余数: 报告.多余数,
        通过: 自检通过 && 零漂移,
        漂移项: 报告.漂移项.clone(),
        说明,
    }
}