#[cfg(test)]
mod tests {
    use hm_agent::{驱动会话存储, 运行检查点, 检查点消息上限, 会话事件回放上限, 驱动过程事件};
    use hm_content_contract::对话消息;

    /// 构造一条驱动过程事件桩（字段齐全，供会话事件断言）
    fn 事件桩(任务id: Option<u64>, 序号: u64) -> 驱动过程事件 {
        驱动过程事件 {
            序号,
            任务id,
            角色: Some("圣人".into()),
            层级: Some("火".into()),
            轮次: 0,
            类型: "任务答复".into(),
            工具名: String::new(),
            内容: format!("事件{序号}"),
            时间: 0,
        }
    }

    /// 构造一条对话消息桩（检查点消息快照用）
    fn 消息桩(序号: u64) -> 对话消息 {
        对话消息::系统(format!("消息{序号}"))
    }

    /// 构造运行检查点桩
    fn 检查点桩(会话id: u64, 任务id: u64, 角色: &str, 轮次: usize, 消息: Vec<对话消息>) -> 运行检查点 {
        运行检查点 {
            会话id,
            任务id,
            角色: 角色.into(),
            阶段提示: "设计".into(),
            消息,
            任务清单: vec![],
            轮次,
            时间: 0,
        }
    }

    /// 唯一临时目录（进程id + 时间戳，测试隔离）
    fn 临时目录(名: &str) -> std::path::PathBuf {
        std::env::temp_dir().join(format!(
            "洪荒会话存储测试_{名}_{}_{}",
            std::process::id(),
            std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .unwrap_or_default()
                .as_nanos()
        ))
    }

    /// 会话存储：纯内存模式 创建/追加/清单/回放 闭环
    #[test]
    fn 会话存储_内存创建追加清单回放() {
        let 存储 = 驱动会话存储::新(None);
        let id = 存储.创建会话("手动驱动");
        存储.追加事件(id, &事件桩(Some(1), 1));
        存储.追加事件(id, &事件桩(Some(1), 2));
        存储.结束会话(id, "已完成", Some("推进 1 轮".into()));

        let 清单 = 存储.清单();
        assert_eq!(清单.len(), 1, "纯内存模式应有一项会话清单");
        assert_eq!(清单[0].会话id, id);
        assert_eq!(清单[0].状态, "已完成");
        assert_eq!(清单[0].事件数, 2);

        let 详情 = 存储.回放(id).expect("内存模式应能回放会话");
        assert_eq!(详情.事件.len(), 2);
        assert_eq!(详情.事件[0].序号, 1);
        assert_eq!(详情.事件[0].任务id, Some(1));
    }

    /// 会话存储：目录模式落盘，新实例（模拟重启）可回看
    #[test]
    fn 会话存储_目录持久化往返重启可回看() {
        let 目录 = 临时目录("目录往返");
        let 存储 = 驱动会话存储::新(Some(目录.to_string_lossy().to_string()));
        let id = 存储.创建会话("发布自动");
        存储.追加事件(id, &事件桩(Some(1), 1));
        存储.结束会话(id, "空闲", Some("无可驱动任务".into()));

        // 模拟重启：新实例指向同目录
        let 重启 = 驱动会话存储::新(Some(目录.to_string_lossy().to_string()));
        let 清单 = 重启.清单();
        assert_eq!(清单.len(), 1, "重启后应能从盘读回会话清单");
        assert_eq!(清单[0].会话id, id);
        let 详情 = 重启.回放(id).expect("重启后应能回放会话");
        assert_eq!(详情.事件.len(), 1, "重启后应能读回事件");
    }

    /// 驱动过程事件：层级随事件落盘并可回放；旧会话文件（无「层级」字段）反序列化不失败。
    /// 后者是加固点：加字段前落盘的 jsonl 仍要能回放，否则历史会话全部读不出。
    #[test]
    fn 会话事件_层级落盘回放且旧格式兼容() {
        let 目录 = 临时目录("层级往返");
        let 存储 = 驱动会话存储::新(Some(目录.to_string_lossy().to_string()));
        let id = 存储.创建会话("发布自动");
        存储.追加事件(id, &事件桩(Some(1), 1));

        let 重启 = 驱动会话存储::新(Some(目录.to_string_lossy().to_string()));
        let 详情 = 重启.回放(id).expect("应能回放");
        assert_eq!(详情.事件[0].层级.as_deref(), Some("火"), "层级应随事件落盘并可回放");

        let 旧行 = r#"{"序号":9,"任务id":1,"角色":"圣人","轮次":0,"类型":"思考","工具名":"","内容":"旧事件","时间":0}"#;
        let 旧事件: 驱动过程事件 = serde_json::from_str(旧行).expect("旧格式（无层级）须能反序列化");
        assert_eq!(旧事件.层级, None, "旧格式缺省层级应为 None");
    }

    /// 会话存储：单会话事件超限仅保留最新 5000 条
    #[test]
    fn 会话存储_单会话事件最新上限截断() {
        let 存储 = 驱动会话存储::新(None);
        let id = 存储.创建会话("手动驱动");
        let 总量 = 会话事件回放上限 + 10;
        for i in 1..=总量 {
            存储.追加事件(id, &事件桩(Some(1), i as u64));
        }
        let 详情 = 存储.回放(id).expect("应能回放");
        assert_eq!(详情.事件.len(), 会话事件回放上限, "回放应截断到上限条数");
        // 保留的是最新的：首条序号应为 总量-上限+1
        let 期望首序号 = (总量 - 会话事件回放上限 + 1) as u64;
        assert_eq!(详情.事件[0].序号, 期望首序号, "截断应保留最新事件");
    }

    /// 检查点：保存后读取往返一致
    #[test]
    fn 检查点_保存读取往返() {
        let 存储 = 驱动会话存储::新(None);
        let id = 存储.创建会话("发布自动");
        let 检查点 = 检查点桩(id, 1, "圣人", 1, vec![消息桩(1), 消息桩(2)]);
        存储.保存检查点(&检查点);

        let 读取 = 存储.读取检查点(id, 1).expect("保存后应能读取检查点");
        assert_eq!(读取.会话id, id);
        assert_eq!(读取.任务id, 1);
        assert_eq!(读取.角色, "圣人");
        assert_eq!(读取.轮次, 1);
        assert_eq!(读取.消息.len(), 2);
        assert_eq!(读取.消息[0].内容.as_deref(), Some("消息1"));
    }

    /// 检查点：消息快照超限仅保留最新 50 条
    #[test]
    fn 检查点_消息超限截断() {
        let 存储 = 驱动会话存储::新(None);
        let id = 存储.创建会话("发布自动");
        let 消息: Vec<对话消息> = (0..(检查点消息上限 + 5)).map(|i| 消息桩(i as u64)).collect();
        let 检查点 = 检查点桩(id, 1, "圣人", 1, 消息);
        存储.保存检查点(&检查点);

        let 读取 = 存储.读取检查点(id, 1).expect("应能读取检查点");
        assert_eq!(读取.消息.len(), 检查点消息上限, "消息快照应截断到上限");
        // 保留最新的：首条消息内容应为 "消息5"
        assert_eq!(读取.消息[0].内容.as_deref(), Some("消息5"));
    }

    /// 检查点：同会话同任务覆盖写，读取最新
    #[test]
    fn 检查点_覆盖写最新() {
        let 存储 = 驱动会话存储::新(None);
        let id = 存储.创建会话("发布自动");
        存储.保存检查点(&检查点桩(id, 1, "圣人", 1, vec![]));
        存储.保存检查点(&检查点桩(id, 1, "大罗金仙", 2, vec![]));

        let 读取 = 存储.读取检查点(id, 1).expect("应能读取检查点");
        assert_eq!(读取.角色, "大罗金仙", "覆盖写应保留最新检查点");
        assert_eq!(读取.轮次, 2);
    }
}
