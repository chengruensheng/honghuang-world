    /// 测试3：需求偏差追溯——需求要点未进入设计边界 → 根源=木
    #[test]
    fn 需求偏差_设计未覆盖需求_根源木() {
        let 器 = 追溯器::新();
        // 需求是「经济系统」，设计边界只覆盖「战斗」
        let 设计文档 = 设计(
            r#"{"边界定义":{"模块":"战斗系统"},"契约":[],"修改文件":[],"新建文件":["src/战斗.rs"],"依赖":[],"created_at":100}"#,
        );
        let 实现文档 = 加法实现("src/战斗.rs");
        let 包 = 器.追溯(
            uuid::Uuid::nil(),
            "做的不是想要的",
            Some(&设计文档),
            Some(&实现文档),
            "实现经济系统",
        );
        assert_eq!(包.根源层级, 五行层级::木);
        assert_eq!(包.错误类型, 错误类型::需求偏差);
        assert!(包.错误描述.contains("经济"), "描述应点名缺失的需求要点");
    }

    /// 测试3b：机器核验失败（编译错误）不得判需求偏差——真实证据走兜底土，禁止词面抢判
    #[test]
    fn 核验失败现象_不判需求偏差_兜底土() {
        let 器 = 追溯器::新();
        let 设计文档 = 完整设计("参数解析-府");
        let 包 = 器.追溯(
            uuid::Uuid::nil(),
            "机器核验未通过：编译失败（非零退出）。error: manifest path does not exist",
            Some(&设计文档),
            None,
            "用 Rust 新建一个库 crate，导出签名完全一致的函数 解析参数",
        );
        assert_eq!(包.根源层级, 五行层级::土, "编译失败现象应兜底土层");
        assert_eq!(包.错误类型, 错误类型::环境问题);
    }

    /// 测试3c：中英混排需求切词不跨语种边界——不再产生「用R/Ru」碎片伪缺失
    #[test]
    fn 需求偏差_中英混排切词不跨语种() {
        let 器 = 追溯器::新();
        // 设计边界完整复述了需求词面（含 Rust/crate/新建一个库/导出解析参数）
        let 设计文档 = 设计(
            r#"{"边界定义":{"说明":"用 Rust 新建一个库 crate 导出解析参数"},"契约":[],"修改文件":[],"新建文件":["参数解析-府"],"依赖":[],"created_at":100}"#,
        );
        let 包 = 器.追溯(
            uuid::Uuid::nil(),
            "需要澄清：需求范围不明确",
            Some(&设计文档),
            None,
            "用 Rust 新建一个库 crate：导出解析参数函数",
        );
        assert_eq!(包.根源层级, 五行层级::木, "现象含澄清字样应落需求偏差");
        assert!(
            !包.错误描述.contains("用R") && !包.错误描述.contains("t新"),
            "切词不得产生跨语种碎片：{}",
            包.错误描述
        );
        assert!(
            !包.错误描述.contains("设计未覆盖需求要点"),
            "设计已覆盖需求词面，不应报伪缺失：{}",
            包.错误描述
        );
    }

    /// 测试4：错误现象含需求字样但实现也越界时，越界规则优先 → 土
    #[test]
    fn 越界优先级_高于现象关键词() {
        let 器 = 追溯器::新();
        let 设计文档 = 完整设计("src/加法.rs");
        let 实现文档 = 加法实现("src/别的.rs");
        let 包 = 器.追溯(
            uuid::Uuid::nil(),
            "不符合需求",
            Some(&设计文档),
            Some(&实现文档),
            "实现加法函数",
        );
        assert_eq!(包.根源层级, 五行层级::土, "实现越界证据优先于现象关键词");
    }

    /// 测试5：判断实现与设计一致性——一致返回 true，越界返回 false
    #[test]
    fn 一致性判断_一致与越界() {
        let 器 = 追溯器::新();
        let 设计文档 = 完整设计("src/加法.rs");
        assert!(
            器.判断实现与设计一致性(&加法实现("src/加法.rs"), &设计文档),
            "变更文件在设计清单内应一致"
        );
        assert!(
            !器.判断实现与设计一致性(&加法实现("src/越界.rs"), &设计文档),
            "变更文件越界应不一致"
        );
    }

    /// 测试6：错误信息包字段完整（建议处理按根源层级给出）
    #[test]
    fn 错误信息包_字段与建议完整() {
        let 包 = 错误信息包::新(
            uuid::Uuid::new_v4(),
            五行层级::火,
            错误类型::设计缺陷,
            "契约不完整",
            vec!["src/设计.rs".into()],
        );
        assert_eq!(包.出错层级, 五行层级::金);
        assert_eq!(包.错误类型, 错误类型::设计缺陷);
        assert_eq!(包.错误类型.名(), "设计缺陷");
        assert_eq!(包.错误描述, "契约不完整");
        assert_eq!(包.相关产物, vec!["src/设计.rs"]);
        assert!(包.建议处理.contains("重新设计"), "设计缺陷建议指向重新设计");
    }

