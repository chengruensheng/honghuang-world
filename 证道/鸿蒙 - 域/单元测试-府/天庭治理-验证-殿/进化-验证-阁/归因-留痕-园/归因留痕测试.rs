//! 归因 - 留痕 - 园 · 归因留痕测试：失败条目归因为调整级别。

#[cfg(test)]
mod 测试 {
    use tianting_fu::{归因, 失败条目, 调整级别, 缺陷层};

    #[test]
    fn 设计层归因调流程() {
        let 条目 = 失败条目 {
            要求id: "r1".to_string(),
            阶段: "设计".to_string(),
            原因: "缺环节".to_string(),
            所在层: 缺陷层::设计层,
            次数: 1,
            时间: 0,
        };
        assert_eq!(归因(&条目), 调整级别::调流程);
    }

    #[test]
    fn 实现层多次失败调分工() {
        let 条目 = 失败条目 {
            要求id: "r1".to_string(),
            阶段: "实现".to_string(),
            原因: "反复失败".to_string(),
            所在层: 缺陷层::实现层,
            次数: 3,
            时间: 0,
        };
        assert_eq!(归因(&条目), 调整级别::调分工);
    }
}
