//! 模板 - 生成 - 园 · 模板生成测试：七类要求模板各出设计方案。

#[cfg(test)]
mod 测试 {
    use tianting_fu::{约束, 模板设计, 阶段, 要求书, 要求来源, 要求状态, 要求类别, 优先级};

    #[test]
    fn 七类模板各出方案() {
        for 类别 in [
            要求类别::功能,
            要求类别::性能,
            要求类别::美观,
            要求类别::优化,
            要求类别::维护,
            要求类别::新能力,
            要求类别::补基础,
        ] {
            let 要求 = 要求书 {
                id: "r1".to_string(),
                来源: 要求来源::界主,
                想法id: None,
                阶段: 阶段::甲,
                方向: "方向".to_string(),
                类别,
                验收标准: "判据".to_string(),
                约束: 约束 { 涉及路径: vec![], 不允许: vec![], 优先级: 优先级::中 },
                状态: 要求状态::待领,
                确认意见: None,
                验收: None,
                版本: None,
            };
            let 方案 = 模板设计(&要求);
            assert!(!方案.拆解.is_empty());
        }
    }
}
