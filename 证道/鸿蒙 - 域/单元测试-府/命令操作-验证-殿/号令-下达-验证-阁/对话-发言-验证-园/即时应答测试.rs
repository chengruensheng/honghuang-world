//! 对话 - 发言 - 验证 - 园 · 即时应答测试：对话发言 / 对话历史 基础契约。

#[cfg(test)]
mod 测试 {
    use mingling_fu::{对话历史, 对话发言};

    #[test]
    fn 对话发言_空串返回提示() {
        assert_eq!(对话发言(""), "请说点什么");
    }

    #[test]
    fn 对话发言_纯空白返回提示() {
        assert_eq!(对话发言("   \t\n  "), "请说点什么");
    }

    #[test]
    fn 对话发言_空字节首尾裁剪仍返回提示() {
        assert_eq!(对话发言("\n\r\t \t"), "请说点什么");
    }

    #[test]
    fn 对话历史_返回非空文本() {
        let 输出 = 对话历史();
        assert!(!输出.is_empty(), "对话历史不应返回空串");
        assert!(
            输出.starts_with("对话历史") || 输出 == "（无对话记录）",
            "对话历史应符合既定格式前缀，实际：{输出}"
        );
    }
}
