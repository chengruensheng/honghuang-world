//! 原子-入池-验证-园：号令-下达-殿「想法-投递阁/原子-入池-园」的错误边界与异常回归测试承载。
//! 调用 `mingling_fu` 公开的「沙箱_命令」API，覆盖非法字符串/空值/边界值三类 invariant。

pub use mingling_fu::沙箱_命令::{入池错误, 入池命令, 原子入池};

#[cfg(test)]
mod 测试 {
    use super::{入池错误, 入池命令, 原子入池};

    #[test]
    fn 非法字符串应返回非法参数错误() {
        let 输入 = "\0\u{0001}非法\u{FFFF}";
        let 结果 = 原子入池(输入);
        assert!(
            matches!(结果, Err(入池错误::非法参数(_))),
            "非法字符串应落入「非法参数」变体，实际：{结果:?}"
        );
    }

    #[test]
    fn 空值或缺省字段应返回缺省降级错误() {
        let 输入 = "";
        let 结果 = 原子入池(输入);
        assert!(
            matches!(结果, Err(入池错误::缺省降级(_))),
            "空值/缺省应落入「缺省降级」变体（Err 而非 Ok(None)），实际：{结果:?}"
        );
    }

    #[test]
    fn 边界值u64上限应返回超限错误() {
        let 命令 = 入池命令 {
            id: u64::MAX,
            容量上限: usize::MAX,
            内容: "边界值压测".to_string(),
        };
        let 结果 = 入池命令(命令);
        assert!(
            matches!(结果, Err(入池错误::超限(_))),
            "边界值应落入「超限」变体，实际：{结果:?}"
        );
    }
}
