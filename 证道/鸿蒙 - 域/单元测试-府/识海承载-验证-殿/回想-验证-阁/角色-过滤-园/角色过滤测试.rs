//! 角色-过滤-园 · 测试：按角色权限过滤格位集合（范畴白名单 + 私有隔离）。

#[cfg(test)]
mod 测试 {
    use shihai_fu::{可见格位, 可见工具, 格位, 范畴, 固化度, 共享度, 顺序档位};

    fn 造格位(名字: &str, 范畴: 范畴, 共享值: 共享度) -> 格位 {
        格位::新(名字, 范畴, "种子", "代码", 固化度::权, 共享值, 顺序档位::中间)
    }

    #[test]
    fn 界主见全部() {
        let 格位们 = vec![
            造格位("结构", 范畴::世界, 共享度::共享),
            造格位("底线", 范畴::自我, 共享度::私有),
        ];
        assert_eq!(可见格位("界主", &格位们).len(), 2);
    }

    #[test]
    fn 女娲按范畴白名单() {
        let 格位们 = vec![
            造格位("结构", 范畴::世界, 共享度::共享),
            造格位("身份", 范畴::自我, 共享度::共享),
            造格位("环节规则", 范畴::程序, 共享度::共享),
        ];
        // 女娲：目标/规则/世界 → 只看世界（结构），不看自我（身份）/程序（环节规则）
        let 可见 = 可见格位("女娲", &格位们);
        assert_eq!(可见.len(), 1);
        assert_eq!(可见[0].名字, "结构");
    }

    #[test]
    fn 多宝额外见程序() {
        let 格位们 = vec![
            造格位("结构", 范畴::世界, 共享度::共享),
            造格位("环节规则", 范畴::程序, 共享度::共享),
        ];
        assert_eq!(可见格位("多宝", &格位们).len(), 2);
    }

    #[test]
    fn 主政执行角色见全量工具() {
        assert_eq!(可见工具("多宝").len(), 10);
        assert_eq!(可见工具("鸿钧").len(), 10);
    }

    #[test]
    fn 设计审验角色只见只读工具() {
        let 工具们 = 可见工具("女娲");
        assert_eq!(工具们.len(), 6);
        assert!(工具们.iter().all(|名| 名 != "写文件" && 名 != "运行命令"));
        // 未知角色保守只读
        assert_eq!(可见工具("无名氏").len(), 6);
    }
}
