    /// 键值校验：空 key / 空 value / 超长 key 按分级返具体变体。
    /// 键上限按分级动态：永驻 64 / 短暂 32 / 单槽 16 / 直通 usize::MAX。
    #[test]
    fn 空key_返空键() {
        let mut 缓存 = 三级缓存::建分级容量(分级::短暂, 4).unwrap();
        let 错 = 断言_err(缓存.写键值校验(分级::短暂, "", "v"), "空 key");
        assert!(matches!(错, 缓存错误::空键));
    }

    #[test]
    fn 空value_返空值() {
        let mut 缓存 = 三级缓存::建分级容量(分级::短暂, 4).unwrap();
        let 错 = 断言_err(缓存.写键值校验(分级::短暂, "k", ""), "空 value");
        assert!(matches!(错, 缓存错误::空值));
    }

    #[test]
    fn 超长key_永驻_超64_返键过长() {
        // 永驻上限 64；65 字节触发 键过长。
        let mut 缓存 = 三级缓存::建分级容量(分级::永驻, 4).unwrap();
        let 长键 = "a".repeat(65);
        let 错 = 断言_err(缓存.写键值校验(分级::永驻, &长键, "v"), "永驻 超长 key");
        match 错 {
            缓存错误::键过长 { 长度, 上限 } => {
                assert_eq!(长度, 65);
                assert_eq!(上限, 64);
            }
            _ => panic!("期望 键过长，实际 {错:?}"),
        }
    }

    #[test]
