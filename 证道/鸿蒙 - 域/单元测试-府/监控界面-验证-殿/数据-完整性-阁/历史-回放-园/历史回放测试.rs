#![cfg(test)]
//! 数据完整性·历史回放：时间窗过滤正确性。
//! 依据：融合蓝图 §9.2 回放端点 + §6.3 数据完整性「回放按时间游标正确返回」。

use jiankong_fu::{任务树视图, 影响项, 时间线视图, 白箱事件};

/// 时间线视图：按 ts 倒序。
#[test]
fn 时间线视图_严格倒序() {
    let 事件 = vec![
        白箱事件::新(100, "源A", "a"),
        白箱事件::新(300, "源B", "b"),
        白箱事件::新(200, "源A", "c"),
        白箱事件::新(50, "源C", "d"),
    ];
    let 视图 = 时间线视图(&事件);
    assert_eq!(视图.len(), 4);
    assert_eq!(视图[0].ts, 300);
    assert_eq!(视图[1].ts, 200);
    assert_eq!(视图[2].ts, 100);
    assert_eq!(视图[3].ts, 50);
}

/// 任务树视图：按要求 id 聚合。
#[test]
fn 任务树_按要求聚合() {
    let 事件 = vec![
        白箱事件::新(100, "源", "a").追加影响(影响项::新("要求", "要求-1")),
        白箱事件::新(200, "源", "b").追加影响(影响项::新("要求", "要求-1")),
        白箱事件::新(300, "源", "c").追加影响(影响项::新("要求", "要求-2")),
        白箱事件::新(400, "源", "d"), // 无要求 → "未分组"
    ];
    let 索引 = 任务树视图(&事件);
    assert_eq!(索引.任务.len(), 3, "应有 3 个桶（要求-1/要求-2/未分组）");

    let r1 = 索引.任务.iter().find(|t| t.id == "要求-1").unwrap();
    assert_eq!(r1.事件数, 2);
    assert_eq!(r1.时间线, vec![100, 200]);

    let r2 = 索引.任务.iter().find(|t| t.id == "要求-2").unwrap();
    assert_eq!(r2.事件数, 1);

    let r3 = 索引.任务.iter().find(|t| t.id == "未分组").unwrap();
    assert_eq!(r3.事件数, 1);
}

/// 任务树视图：累计 token / 耗时汇总。
#[test]
fn 任务树_累计token汇总() {
    let mut e1 = 白箱事件::新(100, "源", "a").追加影响(影响项::新("要求", "R1"));
    e1.token.总计 = 1000;
    e1.耗时ms = 500;
    let mut e2 = 白箱事件::新(200, "源", "b").追加影响(影响项::新("要求", "R1"));
    e2.token.总计 = 2000;
    e2.耗时ms = 800;
    let 事件 = vec![e1, e2];
    let 索引 = 任务树视图(&事件);
    let r = 索引.任务.iter().find(|t| t.id == "R1").unwrap();
    assert_eq!(r.累计token, 3000);
    assert_eq!(r.累计耗时ms, 1300);
}

/// 时间窗过滤逻辑（与 SSE推送 同名测试呼应，证全字段）。
#[test]
fn 时间窗_闭区间过滤() {
    let 事件 = [
        白箱事件::新(100, "源", "a"),
        白箱事件::新(200, "源", "b"),
        白箱事件::新(300, "源", "c"),
        白箱事件::新(400, "源", "d"),
    ];
    let 过滤: Vec<u64> = 事件
        .iter()
        .filter(|e| e.ts >= 150 && e.ts <= 350)
        .map(|e| e.ts)
        .collect();
    assert_eq!(过滤, [200, 300]);
}

/// 时间窗边界：since=0 / until=0 表示不限。
#[test]
fn 时间窗_不限界() {
    let 事件 = [
        白箱事件::新(100, "源", "a"),
        白箱事件::新(u64::MAX, "源", "b"),
    ];
    // 不限界：since=0 与 until=0 都不过滤
    let since = 0u64;
    let until = 0u64;
    let 过滤: Vec<&白箱事件> = 事件
        .iter()
        .filter(|e| (since == 0 || e.ts >= since) && (until == 0 || e.ts <= until))
        .collect();
    assert_eq!(过滤.len(), 2);
}
