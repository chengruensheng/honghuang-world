//! 派发-落单-园 · 派发落单测试：验证落盘文本解析与路径校验。

#[cfg(test)]
mod 测试 {
    use daoshu_fu::解析落盘文本;

    #[test]
    fn 解析成对标记() {
        let 文本 = "<<<文件:乾坤/呈现-域/命令操作-府/入口.rs>>>\npub fn 入口() {}\n<<<结束>>>";
        let 文件们 = 解析落盘文本(文本).unwrap();
        assert_eq!(文件们.len(), 1);
        assert_eq!(文件们[0].路径, "乾坤/呈现-域/命令操作-府/入口.rs");
        assert!(文件们[0].内容.contains("pub fn 入口"));
    }

    #[test]
    fn 拦截占位符路径() {
        let 文本 = "<<<文件:乾坤/呈现-域/...>>>\n内容\n<<<结束>>>";
        assert!(解析落盘文本(文本).is_err());
    }

    #[test]
    fn 缺结束标记报错() {
        let 文本 = "<<<文件:乾坤/呈现-域/命令操作-府/入口.rs>>>\n内容";
        assert!(解析落盘文本(文本).is_err());
    }
}
