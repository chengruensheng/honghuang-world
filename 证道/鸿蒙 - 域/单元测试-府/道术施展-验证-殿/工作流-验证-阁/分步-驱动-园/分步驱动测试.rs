//! 分步-驱动-园 · 分步驱动测试：验证工作流级别对应的执行步骤清单。

#[cfg(test)]
mod 测试 {
    use daoshu_fu::{工作流级别, 级别步骤};

    #[test]
    fn 级别步骤递进() {
        assert_eq!(级别步骤(&工作流级别::问答).len(), 1);
        assert_eq!(级别步骤(&工作流级别::脚本).len(), 3);
        assert_eq!(级别步骤(&工作流级别::程序).len(), 4);
        assert_eq!(级别步骤(&工作流级别::复杂).len(), 5);
    }
}
