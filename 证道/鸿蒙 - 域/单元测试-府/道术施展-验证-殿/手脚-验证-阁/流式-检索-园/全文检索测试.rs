//! 全文检索测试：在临时目录验证命中文件列表与命中次数
//!
//! 设计要点：
//! 1. `全文检索` 内部读 `WORLD_WORKSPACE_ROOT` 决定扫描根；借助「隔离-互斥-园」的
//!    「临时工作区」夹具在测试作用域内临时改写该变量并全程持有全局共享锁，
//!    避免与并发测试串扰。
//! 2. 构造 3 个已知命中样本（A.rs、B.md 之外的 .rs 不算数）、1 个 0 命中文件，
//!    以及被跳过目录（`临时文件夹`），断言返回文本里：
//!    - 命中样本按命中次数倒序排列
//!    - 命中次数与"匹配行数"数字正确
//!    - 总命中数与命中文件数摘要正确
//!    - 被跳过目录的文件确实未出现在结果中
//! 3. 关键词空串应被函数判定为空，不产生输出文本。
//!
//! 注：本测试文件命名沿用园目录 snake_case 风格以压减 non_snake_case 告警。

use super::隔离设施::临时工作区;
use std::fs;
use 测试模块::测试模块;

fn 写文件(根: &std::path::Path, 相对: &str, 内容: &str) {
    let 路径 = 根.join(相对);
    if let Some(父) = 路径.parent() {
        fs::create_dir_all(父).expect("创建父目录失败");
    }
    fs::write(&路径, 内容).expect("写入测试文件失败");
}

/// 主场景：3 个命中样本 + 1 个 0 命中 + 1 个跳过目录，验证列表与计数。
#[test]
fn 全文检索_临时目录_返回正确命中列表与计数() {
    let (根, _锁) = 临时工作区("全文检索测试", "主场景");

    // A.rs：含 2 次「符文」（分两行）
    写文件(&根, "src/A.rs", "let x = 符文;\nlet y = 符文;\n");
    // B.rs：含 3 次「符文」
    写文件(&根, "src/B.rs", "// 符文\nfn f() { 符文(); 符文(); }\n");
    // C.rs：含 1 次「符文」
    写文件(&根, "src/C.rs", "let z = 符文;\n");
    // D.rs：完全不命中
    写文件(&根, "src/D.rs", "let other = something_else;\n");
    // 被跳过的目录
    写文件(&根, "临时文件夹/E.rs", "let 符文 = 1;\n");
    // 非 .rs/.toml，不应被扫描
    写文件(&根, "README.md", "符文也出现在这里\n");

    let 报告 = 全检_全文检索("符文");

    // 1) 三个命中文件均出现
    assert!(报告.contains("A.rs"), "报告应含 A.rs：\n{报告}");
    assert!(报告.contains("B.rs"), "报告应含 B.rs：\n{报告}");
    assert!(报告.contains("C.rs"), "报告应含 C.rs：\n{报告}");

    // 2) D.rs 不命中，不应出现
    assert!(!报告.contains("D.rs"), "D.rs 不应出现：\n{报告}");

    // 3) 被跳过的目录里的文件不应出现
    assert!(!报告.contains("E.rs"), "临时文件夹下文件不应被扫到：\n{报告}");

    // 4) 总命中次数：A(2)+B(3)+C(1) = 6
    assert!(报告.contains("总命中数：6"), "总命中数应为 6：\n{报告}");
    assert!(报告.contains("命中文件数：3"), "命中文件数应为 3：\n{报告}");

    // 5) 排序：B(3) > A(2) > C(1)，故 B 应在 A 之前、A 在 C 之前
    let 位_b = 报告.find("B.rs").expect("B 应出现");
    let 位_a = 报告.find("A.rs").expect("A 应出现");
    let 位_c = 报告.find("C.rs").expect("C 应出现");
    assert!(位_b < 位_a, "B 命中最多，应排在 A 前：\n{报告}");
    assert!(位_a < 位_c, "A 命中多于 C，应排在 C 前：\n{报告}");
}

/// 全无命中：返回文本应只含摘要（命中文件数 0、总命中数 0）。
#[test]
fn 全文检索_临时目录_全无命中时仅输出摘要() {
    let (根, _锁) = 临时工作区("全文检索测试", "全无命中");

    写文件(&根, "src/A.rs", "let x = 1;\n");
    写文件(&根, "src/B.rs", "// 普通注释\n");

    let 报告 = 全检_全文检索("符文");

    assert!(报告.contains("命中文件数：0"), "应为 0 命中：\n{报告}");
    assert!(报告.contains("总命中数：0"), "应为 0 总命中：\n{报告}");
    // 不应列出具体文件
    assert!(!报告.contains("A.rs"), "无命中时不应列文件：\n{报告}");
    assert!(!报告.contains("B.rs"), "无命中时不应列文件：\n{报告}");
}

/// 关键词为空：函数直接返回，无扫描。
#[test]
fn 全文检索_临时目录_关键词为空直接返回() {
    let (根, _锁) = 临时工作区("全文检索测试", "空关键词");
    写文件(&根, "src/A.rs", "let x = 1;\n");

    let 报告 = 全检_全文检索("");
    assert_eq!(报告, "", "空关键词应返回空串，实际：\n{报告}");
}