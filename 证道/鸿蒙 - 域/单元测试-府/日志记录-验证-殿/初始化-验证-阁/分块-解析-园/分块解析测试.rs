//! 分块-解析-园 · 分块解析测试：验证日志配置的默认值与级别解析回退。

#[cfg(test)]
mod 测试 {
    use rizhi_fu::{日志去向, 日志级别, 日志配置, 解析级别};

    #[test]
    fn 默认配置为信息级控制台() {
        let 配置 = 日志配置::default();
        assert_eq!(配置.级别, 日志级别::信息);
        assert_eq!(配置.去向, 日志去向::仅控制台);
    }

    #[test]
    fn 解析级别回退() {
        assert_eq!(解析级别("错误"), 日志级别::错误);
        assert_eq!(解析级别("debug"), 日志级别::调试);
        assert_eq!(解析级别("未知"), 日志级别::信息);
    }
}
