use serde::{Deserialize, Serialize};
use uuid::Uuid;
use tc_task::五行层级;

/// 错误类型：验收不通过时追溯出的错误归类
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Default)]
pub enum 错误类型 {
    /// 实现层产物与设计方案不一致（代码没按设计做）
    实现Bug,
    /// 设计层方案本身有逻辑矛盾/循环依赖/接口不合理
    设计缺陷,
    /// 设计层方案与需求描述不符（做的不是想要的）
    需求偏差,
    /// 依赖缺失/工具不可用/环境配置错
    环境问题,
    /// 多执行者产物冲突（同文件不同修改）
    冲突问题,
    /// 追溯器无法归类（保守兜底）
    #[default]
    未归类,
}

impl 错误类型 {
    pub fn 名(&self) -> &'static str {
        match self {
            错误类型::实现Bug => "实现Bug",
            错误类型::设计缺陷 => "设计缺陷",
            错误类型::需求偏差 => "需求偏差",
            错误类型::环境问题 => "环境问题",
            错误类型::冲突问题 => "冲突问题",
            错误类型::未归类 => "未归类",
        }
    }
}

/// 错误信息包：验收不通过时的完整诊断（出错任务/错误现象 → 根源层级 + 错误类型 + 建议）
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct 错误信息包 {
    /// 出错的（被验收）任务唯一标识
    pub 出错任务id: Uuid,
    /// 发现错误的层级（验收=金）
    pub 出错层级: 五行层级,
    /// 追溯出的错误根源层级（土=实现 / 火=设计 / 木=需求）
    pub 根源层级: 五行层级,
    pub 错误类型: 错误类型,
    pub 错误描述: String,
    /// 相关产物（文件路径，供定位）
    pub 相关产物: Vec<String>,
    /// 建议处理（简短一句话）
    pub 建议处理: String,
}

impl 错误信息包 {
    pub fn 新(
        出错任务id: Uuid,
        根源层级: 五行层级,
        错误类型: 错误类型,
        错误描述: impl Into<String>,
        相关产物: Vec<String>,
    ) -> Self {
        let 建议处理 = 建议处理(根源层级);
        错误信息包 {
            出错任务id,
            出错层级: 五行层级::金,
            根源层级,
            错误类型,
            错误描述: 错误描述.into(),
            相关产物,
            建议处理: 建议处理.to_string(),
        }
    }
}

fn 建议处理(根源层级: 五行层级) -> &'static str {
    match 根源层级 {
        五行层级::木 => "需求偏差/回退超限：由道祖澄清需求或重新评估任务可行性",
        五行层级::火 => "设计缺陷：由圣人重新设计后再实现",
        五行层级::土 => "实现 Bug：由大罗金仙按设计修复后再验收",
        五行层级::金 => "验收问题：补充验收检查项后重新验收",
        五行层级::水 => "清理问题：由太乙金仙修复扫尾项后重新清理",
    }
}
