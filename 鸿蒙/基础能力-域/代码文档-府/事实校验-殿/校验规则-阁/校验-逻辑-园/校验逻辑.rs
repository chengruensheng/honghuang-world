//! 事实校验：叙述文本里的符号引用必须能在事实图上溯源。
//!
//! 策略是「宁可漏报，不可误报」——只校验**符号引用形态**的 token（反引号包裹、
//! 不含空白与斜杠、不以连字符开头），规则的词与普通叙述文字不参与判定。
//! 本府不硬编码任何语言关键字：可采信的出处全部从事实集动态取得，故校验器
//! 与语言无关。
//!
//! 附 自检：没有自检的校验器无法证明自己真的在工作。

use hm_symext::{符号, 符号种类};

use crate::{判定, 自检结论, 文档事实, 校验结论};

/// 校验一篇叙述
pub fn 校验叙述(事实: &文档事实, 叙述: &str) -> 校验结论 {
    let 可采信 = 事实.可引用名();
    let 可疑: Vec<String> = 提取引用(叙述)
        .into_iter()
        .filter(|引用| !可采信.contains(引用))
        .collect();
    let 判定 = if 可疑.is_empty() {
        判定::通过
    } else {
        判定::疑似幻觉(可疑)
    };
    校验结论 {
        文件: 事实.文件.clone(),
        判定,
    }
}

/// 自检：正例（虚构引用必须被抓）与反例（事实中存在的名不得被抓）
pub fn 自检() -> 自检结论 {
    let 事实 = 自检事实();
    let 虚构 = 校验叙述(&事实, "本文件调用 `绝对不存在的符号名`。");
    let 真实 = 校验叙述(&事实, "本文件定义 `真实符号`。");

    match (&虚构.判定, &真实.判定) {
        (判定::疑似幻觉(项), 判定::通过) if !项.is_empty() => 自检结论 {
            通过: true,
            说明: format!("已拦截虚构引用「{}」，且未误报事实中的符号", 项.join("、")),
        },
        (判定::通过, _) => 自检结论 {
            通过: false,
            说明: "虚构引用未被拦截".to_string(),
        },
        (_, 判定::疑似幻觉(项)) => 自检结论 {
            通过: false,
            说明: format!("事实中存在的符号被误报：{}", 项.join("、")),
        },
        _ => 自检结论 {
            通过: false,
            说明: "自检未达预期".to_string(),
        },
    }
}

/// 提取叙述中的符号引用 token：反引号包裹
fn 提取引用(叙述: &str) -> Vec<String> {
    叙述
        .split('`')
        .skip(1)
        .step_by(2)
        .map(|片段| 片段.trim().to_string())
        .filter(|词| 形如符号引用(词))
        .collect()
}

/// 判定 token 是否呈符号引用形态（排除路径、文件名、命令行参数）
fn 形如符号引用(词: &str) -> bool {
    !词.is_empty()
        && !词.contains(char::is_whitespace)
        && !词.contains('/')
        && !词.contains('.')
        && !词.starts_with('-')
}

/// 自检用的事实样例
fn 自检事实() -> 文档事实 {
    文档事实 {
        文件: "自检/样例.rs".to_string(),
        坐标: Default::default(),
        来源语言: "自检".to_string(),
        定义: vec![符号 {
            id: "自检::真实符号".to_string(),
            种类: 符号种类::函数,
            名: "真实符号".to_string(),
            全名: "真实符号".to_string(),
            文件: "自检/样例.rs".to_string(),
            行: 1,
            可见性: "pub".to_string(),
            容器: None,
        }],
        出边: Vec::new(),
        入边: Vec::new(),
        悬空: Vec::new(),
    }
}
