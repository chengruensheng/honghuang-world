//! 叙述层：把事实投影成人读文本。
//!
//! 叙述器可插拔（`rules/可插拔规则.md` §一）：本园给出确定性的模板叙述器，
//! 以及复用 `hm-content` 的模型叙述器；两者都是真实实现变体，由上层按配置选择。
//!
//! 叙述只陈述事实中已有的内容——这是校验层能成立的前提：若叙述可以自由发挥，
//! 校验就无从比对。

use std::sync::Arc;

use hm_content_contract::内容生成器;
use hm_contract::Component;
use hm_error::Result;

use crate::{短名, 文档事实};

/// 叙述器契约
pub trait 叙述器: Component {
    /// 把一份事实投影成人读文本
    fn 叙述(&self, 事实: &文档事实) -> Result<String>;
}

/// 模板叙述器：确定性、离线、零成本；也是模型叙述器失败时的兜底
pub struct 模板叙述器;

impl Component for 模板叙述器 {
    fn name(&self) -> &'static str {
        "模板叙述器"
    }
}

impl 叙述器 for 模板叙述器 {
    fn 叙述(&self, 事实: &文档事实) -> Result<String> {
        let mut 文本 = String::new();
        写定义段(&mut 文本, 事实);
        写出边段(&mut 文本, 事实);
        写入边段(&mut 文本, 事实);
        写悬空段(&mut 文本, 事实);
        Ok(文本)
    }
}

/// 模型叙述器：把事实交给外部大模型转写成更易读的正文。
///
/// 只做「事实 → 提示词 → 文本」，不接入 LLM（用 `hm-content` 的内容生成器注入），
/// 也不做失败兜底（由编排层逐篇回落模板叙述器，见设计 §5.2 降级矩阵）。
pub struct 模型叙述器 {
    生成器: Arc<dyn 内容生成器>,
}

impl 模型叙述器 {
    pub fn 新(生成器: Arc<dyn 内容生成器>) -> Self {
        Self { 生成器 }
    }
}

impl Component for 模型叙述器 {
    fn name(&self) -> &'static str {
        "模型叙述器"
    }
}

impl 叙述器 for 模型叙述器 {
    fn 叙述(&self, 事实: &文档事实) -> Result<String> {
        Ok(剥离思考(&self.生成器.生成(构造提示词(事实))?))
    }
}

/// 剥离模型附带在正文里的思考块（`<think…>…</think…>`）。
///
/// 推理模型（如 MiniMax）会把推理过程写进 content 而非独立的 reasoning 字段，
/// 不剥离就会印进文档。闭标签缺失时按「思考未尽」处理，丢弃其后全部内容——
/// 宁可少一段，不可把推理过程当正文。
fn 剥离思考(文本: &str) -> String {
    const 起标: &str = "<think";
    const 闭标: &str = "</think";

    let mut 结果 = String::new();
    let mut 剩余 = 文本;
    while let Some(起) = 剩余.find(起标) {
        结果.push_str(&剩余[..起]);
        let 标签后 = match 剩余[起..].find('>') {
            Some(偏移) => 起 + 偏移 + 1,
            None => return 结果.trim().to_string(),
        };
        match 剩余[标签后..].find(闭标) {
            Some(偏移) => {
                let 闭标签后 = match 剩余[标签后 + 偏移..].find('>') {
                    Some(偏移2) => 标签后 + 偏移 + 偏移2 + 1,
                    None => return 结果.trim().to_string(),
                };
                剩余 = &剩余[闭标签后..];
            }
            None => return 结果.trim().to_string(),
        }
    }
    结果.push_str(剩余);
    结果.trim().to_string()
}

/// 构造模型提示词：任务 + 硬约束 + 事实清单 + 可引用名清单。
///
/// 事实清单直接复用模板叙述器的产出——同一份事实只应有一种文本化方式；
/// 各写一份会让模型见到的事实与兜底产物不一致。
///
/// 可引用名清单必须原样交给模型：模型不知道哪个名字真实存在，不给清单就只能
/// 凭训练知识补全，那正是幻觉的来源。清单与校验器同源（`文档事实::可引用名`），
/// 避免「清单允许、校验拒绝」的错位。
fn 构造提示词(事实: &文档事实) -> String {
    let mut 提示 = String::new();
    提示.push_str(
        "你是代码文档撰写者。下面给出一个源文件的**全部已知事实**（由静态分析得到的符号图），\
         请据此写一篇中文 Markdown 文档，把事实组织成易读的叙述。\n\n\
         ## 硬约束（违反即视为无效产出）\n\
         1. 只陈述下面事实中出现的内容。不推测业务意图、不解释设计动机、不引用外部知识。\n\
         2. 反引号只用于符号名，且该名字必须逐字出现在下方的「可引用名」清单里。\
         边类型、符号种类、文件名、路径、命令一律不要加反引号。\n\
         3. 不要输出代码围栏，不要写代码示例。\n\
         4. 输出四节，标题依次为「## 一、本文件定义」「## 二、对外依赖」「## 三、被引用」\
         「## 四、悬空引用」；每节先写一句概括本节的叙述文字，再列明细表格；某节无内容时写一句「无」。\n\
         5. 表格里的数值必须与事实一致，不得估算或改写。\n\
         6. 直接输出文档正文。不要输出思考过程，不要输出 <think> 之类的标签。\n\n\
         ## 事实清单\n\n",
    );
    let 清单 = 模板叙述器
        .叙述(事实)
        .unwrap_or_else(|_| "（事实清单生成失败）".to_string());
    提示.push_str(&清单);
    提示.push_str("\n## 可引用名\n\n下面的名字是唯一允许用反引号包裹的内容（每行一个，`::` 结尾的为完整路径，可只写末段）：\n\n```\n");
    for 名 in 事实.可引用名() {
        提示.push_str(&名);
        提示.push('\n');
    }
    提示.push_str("```\n");
    提示
}

fn 写定义段(文本: &mut String, 事实: &文档事实) {
    文本.push_str("## 一、本文件定义\n\n");
    if 事实.定义.is_empty() {
        文本.push_str("本文件未定义符号。\n\n");
        return;
    }
    文本.push_str(&format!("共 {} 个符号。\n\n", 事实.定义.len()));
    文本.push_str("| 种类 | 名 | 可见性 | 行 |\n|---|---|---|---|\n");
    for 符 in &事实.定义 {
        文本.push_str(&format!(
            "| {:?} | `{}` | {} | {} |\n",
            符.种类, 符.名, 符.可见性, 符.行
        ));
    }
    文本.push('\n');
}

fn 写出边段(文本: &mut String, 事实: &文档事实) {
    文本.push_str("## 二、对外依赖\n\n");
    if 事实.出边.is_empty() {
        文本.push_str("本文件未发出边。\n\n");
        return;
    }
    文本.push_str(&format!("共 {} 条。\n\n", 事实.出边.len()));
    文本.push_str("| 类型 | 本文件符号 | 目标 | 置信度 | 行 |\n|---|---|---|---|---|\n");
    for 边 in &事实.出边 {
        let 行 = 边
            .位置
            .as_ref()
            .map(|位| 位.行.to_string())
            .unwrap_or_else(|| "—".to_string());
        文本.push_str(&format!(
            "| {:?} | `{}` | `{}` | {:?} | {} |\n",
            边.类型,
            短名(&边.从),
            短名(&边.到),
            边.置信度,
            行
        ));
    }
    文本.push('\n');
}

fn 写入边段(文本: &mut String, 事实: &文档事实) {
    文本.push_str("## 三、被引用\n\n");
    if 事实.入边.is_empty() {
        文本.push_str("无其它符号引用本文件。\n\n");
        return;
    }
    文本.push_str(&format!("共 {} 条。\n\n", 事实.入边.len()));
    文本.push_str("| 类型 | 本文件符号 | 来源 | 置信度 |\n|---|---|---|---|\n");
    for 边 in &事实.入边 {
        文本.push_str(&format!(
            "| {:?} | `{}` | `{}` | {:?} |\n",
            边.类型,
            短名(&边.到),
            短名(&边.从),
            边.置信度
        ));
    }
    文本.push('\n');
}

fn 写悬空段(文本: &mut String, 事实: &文档事实) {
    文本.push_str("## 四、悬空引用\n\n");
    if 事实.悬空.is_empty() {
        文本.push_str("无悬空引用。\n\n");
        return;
    }
    文本.push_str(&format!(
        "共 {} 条（解析不到目标的引用，是幽灵引用的原始素材）。\n\n",
        事实.悬空.len()
    ));
    文本.push_str("| 类型 | 目标文本 | 置信度 |\n|---|---|---|\n");
    for 悬 in &事实.悬空 {
        文本.push_str(&format!(
            "| {:?} | `{}` | {:?} |\n",
            悬.类型, 悬.目标文本, 悬.置信度
        ));
    }
    文本.push('\n');
}
