//! 长河译制：旧接口方言 → 长河事件（唯一翻译点，随 v1 统一通道落地）。
//!
//! 三处方言来源：
//! 1. 驱动过程事件（思考/工具调用/工具结果/任务答复）→ 思考*/工具*/回复*；
//! 2. 驱动阶段事件（阶段完成/空闲/错误）→ 任务状态/运行结束/河错；
//! 3. 接待流帧（己言/回复增量/运行结束）由长河处理-阁直接产出（不经过此译制器，
//!    因接待流是后端一手构造，无需二次方言翻译）。
//!
//! 译制器有状态：维护「最近一次工具调用 id」游标，供工具结果配对（与 AG-UI 协议适配器同构）。

use qk_mirror::长河事件;
use crate::{驱动过程事件, 驱动阶段事件};

/// 长河译制器：把内部驱动事件翻译为长河事件序列（适配器映射，非破坏）。
pub struct 译制器 {
    最近工具调用id: Option<String>,
}

impl 译制器 {
    /// 新建译制器（游标为空）
    pub fn 新() -> Self {
        译制器 { 最近工具调用id: None }
    }

    /// 单条驱动过程事件 → 一条或多条长河事件（单条内部事件展开为三段式流）。
    ///
    /// 映射：思考→思考开始/增量/结束；工具调用→工具开始/参数/结束；
    /// 工具结果→工具结果（复用最近工具调用 id，孤立时按序号兜底）；
    /// 任务答复→回复开始/增量/结束。
    pub fn 过程事件(&mut self, 事件: &驱动过程事件, 会话id: u64) -> Vec<长河事件> {
        let 序号 = 事件.序号;
        match 事件.类型.as_str() {
            "思考" => {
                let id = format!("思-{会话id}-{序号}");
                vec![
                    长河事件::思考开始 { 消息id: id.clone() },
                    长河事件::思考增量 { 消息id: id.clone(), 文: 事件.内容.clone() },
                    长河事件::思考结束 { 消息id: id },
                ]
            }
            "工具调用" => {
                let id = format!("具-{会话id}-{序号}");
                self.最近工具调用id = Some(id.clone());
                vec![
                    长河事件::工具开始 { 调用id: id.clone(), 名称: 事件.工具名.clone() },
                    长河事件::工具参数 { 调用id: id.clone(), 片段: 事件.内容.clone() },
                    长河事件::工具结束 { 调用id: id },
                ]
            }
            "工具结果" => {
                let id = self
                    .最近工具调用id
                    .clone()
                    .unwrap_or_else(|| format!("具-{会话id}-{序号}"));
                vec![长河事件::工具结果 { 调用id: id, 文: 事件.内容.clone() }]
            }
            "任务答复" => {
                let id = format!("答-{会话id}-{序号}");
                vec![
                    长河事件::回复开始 { 消息id: id.clone(), 角色: "执行".into() },
                    长河事件::回复增量 { 消息id: id.clone(), 文: 事件.内容.clone() },
                    长河事件::回复结束 { 消息id: id },
                ]
            }
            _ => vec![],
        }
    }

    /// 单条驱动阶段事件 → 一条长河事件。
    ///
    /// 映射：阶段完成→任务状态；空闲→运行结束；错误→河错。
    pub fn 阶段事件(&self, 事件: &驱动阶段事件) -> Vec<长河事件> {
        match 事件.类型.as_str() {
            "阶段完成" => match (事件.任务id, 事件.新状态.as_ref()) {
                (Some(任务id), Some(新状态)) => vec![长河事件::任务状态 {
                    任务id,
                    状态: 新状态.clone(),
                }],
                _ => vec![],
            },
            "空闲" => vec![长河事件::运行结束 {
                阶段: qk_mirror::阶段::接待中.to_string(),
                任务id: None,
            }],
            "错误" => vec![长河事件::河错 {
                来源: "驱动".into(),
                文: 事件.消息.clone().unwrap_or_else(|| "驱动错误".into()),
            }],
            _ => vec![],
        }
    }
}

#[cfg(test)]
mod 译制验证 {
    use super::*;

    fn 过程(序号: u64, 类型: &str, 工具名: &str, 内容: &str) -> 驱动过程事件 {
        驱动过程事件 {
            序号,
            任务id: Some(1),
            角色: Some("大罗".into()),
            轮次: 0,
            类型: 类型.into(),
            工具名: 工具名.into(),
            内容: 内容.into(),
            时间: 0,
        }
    }

    #[test]
    fn 思考展开为三段式流() {
        let mut 译 = 译制器::新();
        let 事们 = 译.过程事件(&过程(1, "思考", "", "想一哈"), 7);
        assert_eq!(事们.len(), 3);
        assert!(matches!(事们[0], 长河事件::思考开始 { .. }));
        assert!(matches!(事们[1], 长河事件::思考增量 { .. }));
        assert!(matches!(事们[2], 长河事件::思考结束 { .. }));
    }

    #[test]
    fn 工具调用与结果配对同一调用id() {
        let mut 译 = 译制器::新();
        let 调用 = 译.过程事件(&过程(1, "工具调用", "读文件", "{\"路\":1}"), 7);
        let 调用id = match &调用[0] {
            长河事件::工具开始 { 调用id, .. } => 调用id.clone(),
            _ => panic!("应产生工具开始"),
        };
        let 结果 = 译.过程事件(&过程(2, "工具结果", "", "ok"), 7);
        match &结果[0] {
            长河事件::工具结果 { 调用id: id, 文 } => {
                assert_eq!(*id, 调用id);
                assert_eq!(文, "ok");
            }
            _ => panic!("应产生工具结果"),
        }
    }

    #[test]
    fn 阶段完成译制为任务状态_错误译制为河错() {
        let 译 = 译制器::新();
        let 完成 = 译.阶段事件(&驱动阶段事件 {
            序号: 1,
            类型: "阶段完成".into(),
            任务id: Some(9),
            角色: Some("圣人".into()),
            新状态: Some("已完成".into()),
            层级: None,
            消息: None,
            时间: 0,
        });
        assert_eq!(完成, vec![长河事件::任务状态 { 任务id: 9, 状态: "已完成".into() }]);

        let 错误 = 译.阶段事件(&驱动阶段事件 {
            序号: 2,
            类型: "错误".into(),
            任务id: None,
            角色: None,
            新状态: None,
            层级: None,
            消息: Some("崩了".into()),
            时间: 0,
        });
        assert!(matches!(错误[0], 长河事件::河错 { .. }));
    }
}
