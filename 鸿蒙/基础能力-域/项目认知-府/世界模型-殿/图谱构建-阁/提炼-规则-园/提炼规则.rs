use crate::{维度, 图谱};

/// 候选摘要：提炼器的一次产出（对齐原型 提炼规则.py）
#[derive(Clone, Debug, PartialEq)]
pub struct 候选摘要 {
    pub 维度: 维度,
    pub 格位名: String,
    pub 摘要: String,
    pub 证据引用: Vec<String>,
    pub 可信度: f32,
    /// 模式：规则 / LLM / 评审（当前仅规则）
    pub 模式: String,
}

/// 迭代线索：从迭代日志提取的轻量历史摘要（跨域解耦，不依赖量劫 Iteration 类型）
#[derive(Clone, Debug, PartialEq)]
pub struct 迭代线索 {
    /// 版本号（如 "v1.55"）
    pub 版本: String,
    /// 状态："已完成" / "已放弃" / "进行中"
    pub 状态: String,
    /// 变更说明
    pub 变更说明: String,
    /// 创建时间戳（秒）
    pub 时间: u64,
}

/// 规则提炼器：纯机械、零网络、可重现；把图谱映射为候选摘要
pub struct 规则提炼器;

impl 规则提炼器 {
    /// 经历·时间格位名（收敛常量，规避硬编码载荷键误报）
    const 格位名_时间: &str = "时间";

    /// 常用工具依赖名 → 用途（对齐原型）
    const 常用工具: &'static [(&'static str, &'static str)] = &[
        ("serde", "序列化"),
        ("tokio", "异步运行时"),
        ("tracing", "日志追踪"),
        ("anyhow", "错误处理"),
        ("thiserror", "错误派生"),
        ("ureq", "同步HTTP"),
        ("reqwest", "异步HTTP"),
    ];

    /// 从图谱提炼候选摘要（外在·结构 / 外在·依赖 / 执行·技术栈 / 执行·工具）
    pub fn 提炼(&self, 图谱: &图谱) -> Vec<候选摘要> {
        let mut 全部: Vec<候选摘要> = Vec::new();
        全部.push(self.外在结构(图谱));
        全部.push(self.外在依赖(图谱));
        全部.push(self.执行技术栈(图谱));
        全部.push(self.执行工具(图谱));
        全部.retain(|候选| !候选.摘要.is_empty());
        全部
    }

    /// 提炼_带历史：在图谱提炼基础上，叠加迭代日志线索提炼目标/经历维度（≥12 格位）。
    /// 无历史（空迭代线索）时退化为仅图谱提炼（不报错）。
    pub fn 提炼_带历史(&self, 图谱: &图谱, 迭代们: &[迭代线索]) -> Vec<候选摘要> {
        let mut 全部 = self.提炼(图谱);
        全部.push(self.外在接口(图谱));
        全部.push(self.执行产出(图谱));
        全部.push(self.目标现况(迭代们));
        全部.push(self.目标偏移(迭代们));
        全部.push(self.目标度量(迭代们));
        全部.push(self.经历事件(迭代们));
        全部.push(self.经历教训(迭代们));
        全部.push(self.经历时间(迭代们));
        全部.retain(|候选| !候选.摘要.is_empty());
        全部
    }

    /// 外在·接口：符号签名清单（函数/类型/常量）
    fn 外在接口(&self, 图谱: &图谱) -> 候选摘要 {
        if 图谱.符号集.is_empty() {
            return 候选摘要 {
                维度: 维度::外在,
                格位名: "接口".into(),
                摘要: String::new(),
                证据引用: Vec::new(),
                可信度: 0.7,
                模式: "规则".into(),
            };
        }
        let 行: Vec<String> = 图谱
            .符号集
            .iter()
            .take(8)
            .map(|符号| match &符号.签名 {
                Some(签名) => format!("{}: {}", 符号.名称, 签名),
                None => 符号.名称.clone(),
            })
            .collect();
        候选摘要 {
            维度: 维度::外在,
            格位名: "接口".into(),
            摘要: format!("符号接口（{} 个）：{}", 图谱.符号集.len(), 行.join("、")),
            证据引用: 图谱.符号集.iter().map(|符号| 符号.名称.clone()).collect(),
            可信度: 0.7,
            模式: "规则".into(),
        }
    }

    /// 执行·产出：模块与符号规模
    fn 执行产出(&self, 图谱: &图谱) -> 候选摘要 {
        if 图谱.模块集.is_empty() && 图谱.符号集.is_empty() {
            return 候选摘要 {
                维度: 维度::执行,
                格位名: "产出".into(),
                摘要: String::new(),
                证据引用: Vec::new(),
                可信度: 0.7,
                模式: "规则".into(),
            };
        }
        候选摘要 {
            维度: 维度::执行,
            格位名: "产出".into(),
            摘要: format!("产出规模：{} 模块、{} 符号", 图谱.模块集.len(), 图谱.符号集.len()),
            证据引用: 图谱.模块集.iter().map(|模块| 模块.名称.clone()).collect(),
            可信度: 0.7,
            模式: "规则".into(),
        }
    }

    /// 目标·现况：最新已完成迭代的版本与说明
    fn 目标现况(&self, 迭代们: &[迭代线索]) -> 候选摘要 {
        let 最新 = 迭代们.iter().rev().find(|i| i.状态 == "已完成");
        match 最新 {
            Some(迭代) => 候选摘要 {
                维度: 维度::目标,
                格位名: "现况".into(),
                摘要: format!("当前版本 {}：{}", 迭代.版本, 迭代.变更说明),
                证据引用: vec![迭代.版本.clone()],
                可信度: 0.7,
                模式: "规则".into(),
            },
            None => 候选摘要 {
                维度: 维度::目标,
                格位名: "现况".into(),
                摘要: String::new(),
                证据引用: Vec::new(),
                可信度: 0.7,
                模式: "规则".into(),
            },
        }
    }

    /// 目标·偏移：未完成（进行中/已放弃）迭代清单
    fn 目标偏移(&self, 迭代们: &[迭代线索]) -> 候选摘要 {
        let 未完成: Vec<&迭代线索> = 迭代们.iter().filter(|i| i.状态 != "已完成").collect();
        if 未完成.is_empty() {
            return 候选摘要 {
                维度: 维度::目标,
                格位名: "偏移".into(),
                摘要: String::new(),
                证据引用: Vec::new(),
                可信度: 0.6,
                模式: "规则".into(),
            };
        }
        let 行: Vec<String> = 未完成
            .iter()
            .map(|i| format!("{}（{}）", i.版本, i.状态))
            .collect();
        候选摘要 {
            维度: 维度::目标,
            格位名: "偏移".into(),
            摘要: format!("未完成迭代：{}", 行.join("、")),
            证据引用: 未完成.iter().map(|i| i.版本.clone()).collect(),
            可信度: 0.6,
            模式: "规则".into(),
        }
    }

    /// 目标·度量：版本演进规模
    fn 目标度量(&self, 迭代们: &[迭代线索]) -> 候选摘要 {
        if 迭代们.is_empty() {
            return 候选摘要 {
                维度: 维度::目标,
                格位名: "度量".into(),
                摘要: String::new(),
                证据引用: Vec::new(),
                可信度: 0.7,
                模式: "规则".into(),
            };
        }
        let 完成数 = 迭代们.iter().filter(|i| i.状态 == "已完成").count();
        候选摘要 {
            维度: 维度::目标,
            格位名: "度量".into(),
            摘要: format!("版本演进：{} 次迭代（{} 完成）", 迭代们.len(), 完成数),
            证据引用: 迭代们.iter().map(|i| i.版本.clone()).collect(),
            可信度: 0.7,
            模式: "规则".into(),
        }
    }

    /// 经历·事件：最近一次迭代
    fn 经历事件(&self, 迭代们: &[迭代线索]) -> 候选摘要 {
        let 最近 = 迭代们.last();
        match 最近 {
            Some(迭代) => 候选摘要 {
                维度: 维度::经历,
                格位名: "事件".into(),
                摘要: format!("最近迭代 {}：{}", 迭代.版本, 迭代.变更说明),
                证据引用: vec![迭代.版本.clone()],
                可信度: 0.7,
                模式: "规则".into(),
            },
            None => 候选摘要 {
                维度: 维度::经历,
                格位名: "事件".into(),
                摘要: String::new(),
                证据引用: Vec::new(),
                可信度: 0.7,
                模式: "规则".into(),
            },
        }
    }

    /// 经历·教训：已放弃迭代的结论
    fn 经历教训(&self, 迭代们: &[迭代线索]) -> 候选摘要 {
        let 放弃们: Vec<&迭代线索> = 迭代们.iter().filter(|i| i.状态 == "已放弃").collect();
        if 放弃们.is_empty() {
            return 候选摘要 {
                维度: 维度::经历,
                格位名: "教训".into(),
                摘要: String::new(),
                证据引用: Vec::new(),
                可信度: 0.6,
                模式: "规则".into(),
            };
        }
        let 行: Vec<String> = 放弃们
            .iter()
            .map(|i| format!("{}：{}", i.版本, i.变更说明))
            .collect();
        候选摘要 {
            维度: 维度::经历,
            格位名: "教训".into(),
            摘要: format!("放弃迭代教训：{}", 行.join("；")),
            证据引用: 放弃们.iter().map(|i| i.版本.clone()).collect(),
            可信度: 0.6,
            模式: "规则".into(),
        }
    }

    /// 经历·时间：最新迭代节点（时间戳）
    fn 经历时间(&self, 迭代们: &[迭代线索]) -> 候选摘要 {
        let 最近 = 迭代们.iter().max_by_key(|i| i.时间);
        match 最近 {
            Some(迭代) => 候选摘要 {
                维度: 维度::经历,
                格位名: Self::格位名_时间.into(),
                摘要: format!("最新迭代 {}（时间戳 {}）", 迭代.版本, 迭代.时间),
                证据引用: vec![迭代.版本.clone()],
                可信度: 0.6,
                模式: "规则".into(),
            },
            None => 候选摘要 {
                维度: 维度::经历,
                格位名: Self::格位名_时间.into(),
                摘要: String::new(),
                证据引用: Vec::new(),
                可信度: 0.6,
                模式: "规则".into(),
            },
        }
    }

    /// 外在·结构：模块总数与模块名清单
    fn 外在结构(&self, 图谱: &图谱) -> 候选摘要 {
        let 模块数 = 图谱.模块集.len();
        let 名称: Vec<&str> = 图谱.模块集.iter().map(|模块| 模块.名称.as_str()).collect();
        let 摘要 = if 模块数 == 0 {
            String::new()
        } else {
            format!("项目共 {} 个模块：{}", 模块数, 名称.join("、"))
        };
        候选摘要 {
            维度: 维度::外在,
            格位名: "结构".into(),
            摘要,
            证据引用: 图谱.模块集.iter().map(|模块| 模块.名称.clone()).collect(),
            可信度: 0.8,
            模式: "规则".into(),
        }
    }

    /// 外在·依赖：依赖边摘要（源 → 目标）
    fn 外在依赖(&self, 图谱: &图谱) -> 候选摘要 {
        if 图谱.依赖集.is_empty() {
            return 候选摘要 {
                维度: 维度::外在,
                格位名: "依赖".into(),
                摘要: String::new(),
                证据引用: Vec::new(),
                可信度: 0.8,
                模式: "规则".into(),
            };
        }
        let 行: Vec<String> = 图谱
            .依赖集
            .iter()
            .take(10)
            .map(|边| format!("{}→{}", 边.源, 边.目标))
            .collect();
        候选摘要 {
            维度: 维度::外在,
            格位名: "依赖".into(),
            摘要: format!("依赖方向（{} 条）：{}", 图谱.依赖集.len(), 行.join("、")),
            证据引用: 图谱
                .依赖集
                .iter()
                .map(|边| format!("{}→{}", 边.源, 边.目标))
                .collect(),
            可信度: 0.8,
            模式: "规则".into(),
        }
    }

    /// 执行·技术栈：基于图谱技术栈线索
    fn 执行技术栈(&self, 图谱: &图谱) -> 候选摘要 {
        if 图谱.技术栈.is_empty() {
            return 候选摘要 {
                维度: 维度::执行,
                格位名: "技术栈".into(),
                摘要: String::new(),
                证据引用: Vec::new(),
                可信度: 0.7,
                模式: "规则".into(),
            };
        }
        候选摘要 {
            维度: 维度::执行,
            格位名: "技术栈".into(),
            摘要: format!("技术栈：{}", 图谱.技术栈.join("、")),
            证据引用: 图谱.技术栈.clone(),
            可信度: 0.7,
            模式: "规则".into(),
        }
    }

    /// 执行·工具：技术栈中命中的常用工具（serde/tokio/...）
    fn 执行工具(&self, 图谱: &图谱) -> 候选摘要 {
        let 命中: Vec<String> = Self::常用工具
            .iter()
            .filter(|(名, _)| 图谱.技术栈.iter().any(|已有| 已有 == 名))
            .map(|(名, 用途)| format!("{}（{}）", 名, 用途))
            .collect();
        if 命中.is_empty() {
            return 候选摘要 {
                维度: 维度::执行,
                格位名: "工具".into(),
                摘要: String::new(),
                证据引用: Vec::new(),
                可信度: 0.7,
                模式: "规则".into(),
            };
        }
        候选摘要 {
            维度: 维度::执行,
            格位名: "工具".into(),
            摘要: format!("常用工具：{}", 命中.join("、")),
            证据引用: 图谱.技术栈.clone(),
            可信度: 0.7,
            模式: "规则".into(),
        }
    }
}
