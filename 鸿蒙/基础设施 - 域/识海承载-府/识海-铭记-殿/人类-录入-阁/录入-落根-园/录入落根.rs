//! 录入 - 落根 - 园：人类录入根记录（经格位校验）。

use crate::{固化度, 记录, 模型存储};

/// 人类录入根记录：格位必须存在且固化度 = 经（来源 = 人类）。
pub fn 录入根(存储: &模型存储, 格位名: &str, 内容: &str, 证据: &str) -> Result<(), String> {
    let 格位 = crate::找格位(格位名).ok_or_else(|| format!("格位不存在: {格位名}"))?;
    if 格位.固化度 != 固化度::经 {
        return Err(format!("格位「{格位名}」非经格位，不可落根"));
    }
    存储.写记录(&记录::新(格位名, 内容, 证据, "人类"))
}

#[cfg(test)]
mod 测试 {
    use super::*;

    #[test]
    fn 经格位可落根() {
        let 存储 = 模型存储::打开(std::env::temp_dir());
        assert!(录入根(&存储, "铁律·总纲", "不可破的约束", "人").is_ok());
    }

    #[test]
    fn 权格位不可落根() {
        let 存储 = 模型存储::打开(std::env::temp_dir());
        assert!(录入根(&存储, "任务", "内容", "人").is_err());
    }
}
