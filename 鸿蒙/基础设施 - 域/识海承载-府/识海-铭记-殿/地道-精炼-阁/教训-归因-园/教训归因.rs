//! 教训 - 归因 - 园：执行失败 → 唤 LLM 归因（为什么 + 下次规避）→ 教训格位；执行前读教训注入现状。
//!
//! 定位：地道闭环——失败归因写教训，下轮执行注入现状，经验跨轮复用。
//! 教训是 LLM 归因产物，可信度低于代码，注入现状仅供执行者参考，不做硬约束。

use crate::{记录, 模型存储};
use moxing_fu::{调用模型, 对话消息, 模型配置, 精简上限};
use rizhi_fu::info;

/// 教训格位名（对齐格位清单·经历范畴）。
pub const 教训格位: &str = "教训";

/// 归因教训：一次执行结束 → 唤 LLM 复盘归因 → 写「教训」格位（来源 LLM，证据 = 结果说明）。
/// 失败必归因（对症困难任务）；成功不归因（省 token，正样本价值低）。
pub fn 归因教训(
    存储: &模型存储,
    配置: &模型配置,
    任务目标: &str,
    状态: &str,
    说明: &str,
) -> Result<(), String> {
    let 提示 = format!(
        "你是一名项目复盘记录员。一次任务执行{状态}。请归因：执行{状态}的原因是什么、下次遇到同类任务怎么规避或复用。\
         精炼成一条 150 字以内的教训，直接给结论。\n\n【任务目标】{任务目标}\n【结果说明】{说明}"
    );
    let (回复, 用量) = 调用模型(配置, &[对话消息::用户(提示)], 精简上限)?;
    存储.写记录(&记录::新(教训格位, &回复, &format!("地道归因：{状态}"), "LLM"))?;
    info!(内容长度 = 回复.len(), 提示词 = 用量.提示词, "教训归因完成");
    Ok(())
}

/// 注入教训：读「教训」格位最近条数，格式化为现状边际文本（无教训时零开销返回空）。
pub fn 注入教训(存储: &模型存储, 条数: usize) -> Result<String, String> {
    let 记录们 = 存储.读格位(教训格位)?;
    let 近们: Vec<_> = 记录们.into_iter().rev().filter(|记录| !记录.失效).take(条数).collect();
    if 近们.is_empty() {
        return Ok(String::new());
    }
    let mut 文本 = String::from("【教训·地道注入】\n");
    for (序号, 记录) in 近们.iter().rev().enumerate() {
        文本.push_str(&format!("{}. {}\n", 序号 + 1, 记录.内容));
    }
    文本.push('\n');
    info!(条数 = 近们.len(), "教训已注入");
    Ok(文本)
}

#[cfg(test)]
mod 测试 {
    use super::*;

    fn 临时存储() -> 模型存储 {
        // 进程+线程+毫秒三重区分：workspace 并行测试时不同测试线程同毫秒会撞同一临时目录。
        let 线程 = format!("{:?}", std::thread::current().id());
        crate::模型存储::打开(std::env::temp_dir().join(format!(
            "教训测试-{}-{}-{}",
            std::process::id(),
            线程,
            crate::当前毫秒()
        )))
    }

    #[test]
    fn 注入教训_无记录返回空() {
        let 存储 = 临时存储();
        assert_eq!(注入教训(&存储, 3).unwrap(), "");
    }

    #[test]
    fn 注入教训_取最近条数() {
        let 存储 = 临时存储();
        存储.写记录(&记录::新(教训格位, "旧教训：别脑补路径", "测试", "LLM")).unwrap();
        存储.写记录(&记录::新(教训格位, "新教训：先读后写", "测试", "LLM")).unwrap();
        let 注入 = 注入教训(&存储, 1).unwrap();
        assert!(注入.contains("新教训：先读后写"), "应取最近一条：{注入}");
        assert!(!注入.contains("旧教训"), "不应含旧教训：{注入}");
        // 注回 2 条应都含
        let 全量 = 注入教训(&存储, 2).unwrap();
        assert!(全量.contains("旧教训") && 全量.contains("新教训"));
    }
}
