//! 播种 - 提示 - 模板：播种提示词模板与渲染，供播种复用。

/// 播种提示词模板：占位符 {种子} {素材} {印证}，播种统一复用。
const 播种提示模板: &str = concat!(
    "你是一名项目记忆采集员。请按「本质」在项目素材中提炼一条精炼记录。\n\n",
    "【本质】\n{种子}\n\n",
    "【素材】\n{素材}\n\n",
    "【代码印证清单】\n{印证}\n\n",
    "【输出要求】\n",
    "1. 用 1~3 句话概括「本质」对应的具体内容，不要只写标题、格位名或分类标签。\n",
    "2. 单独一行写「证据：」+ 从哪个文件 / 文档 / 符号推断。\n",
    "3. 若素材中确实找不到相关内容，只输出「不确定」三个字，不要编造。\n\n",
    "【输出示例】\n",
    "六层结构：维度→域→府→殿→阁→园，能力只在园落地；跨府引用止步 lib 根，跨维经鸿蒙中转。\n",
    "证据：层级结构-设计.md 第三、五、六节",
);

/// 渲染播种提示：占位符替换，印证为空时填「（无）」。
pub fn 渲染播种提示(种子: &str, 素材: &str, 印证: &str) -> String {
    播种提示模板
        .replace("{种子}", 种子)
        .replace("{素材}", 素材)
        .replace(
            "{印证}",
            if 印证.is_empty() {
                "（无）"
            } else {
                印证
            },
        )
}
