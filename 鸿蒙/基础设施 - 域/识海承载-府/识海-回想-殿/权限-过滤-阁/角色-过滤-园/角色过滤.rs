//! 角色 - 过滤 - 园：按角色权限过滤格位集合（范畴白名单 + 私有隔离）。

use crate::{共享度, 工具清单, 格位, 范畴};
use rizhi_fu::debug;

/// 按角色过滤可见格位：私有格位仅界主可见；其余按角色范畴白名单。
pub fn 可见格位(角色: &str, 格位们: &[格位]) -> Vec<格位> {
    let 结果 = 格位们
        .iter()
        .filter(|格位| 角色可见(角色, 格位))
        .cloned()
        .collect::<Vec<_>>();
    debug!(
        角色,
        可见数 = 结果.len(),
        总数 = 格位们.len(),
        "格位已按角色过滤"
    );
    结果
}

fn 角色可见(角色: &str, 格位: &格位) -> bool {
    if 格位.共享度 == 共享度::私有 && 角色 != "界主" {
        return false;
    }
    match 角色范畴(角色) {
        None => true,
        Some(范畴们) => 范畴们.contains(&格位.范畴),
    }
}

/// 角色范畴白名单：None = 全量（界主 / 鸿钧）。
fn 角色范畴(角色: &str) -> Option<Vec<范畴>> {
    match 角色 {
        "界主" | "鸿钧" => None,
        "女娲" => Some(vec![范畴::目标, 范畴::规则, 范畴::世界]),
        "多宝" => Some(vec![范畴::目标, 范畴::规则, 范畴::世界, 范畴::程序]),
        "准圣" => Some(vec![范畴::目标, 范畴::规则, 范畴::世界]),
        _ => None,
    }
}

/// 按角色过滤可见工具：主政/执行角色全量；设计/审验角色只读；未知角色保守只读。
pub fn 可见工具(角色: &str) -> Vec<String> {
    let 工具们 = match 角色 {
        "界主" | "鸿钧" | "天道" | "多宝" | "白泽" | "龟灵" | "玄天" => {
            工具清单::全部().工具们
        }
        _ => 只读工具(),
    };
    debug!(角色, 工具数 = 工具们.len(), "工具已按角色过滤");
    工具们
}

/// 只读工具：读文件 / 列目录 / 找文件 / 搜内容 / 读格位 / 查格位历史。
fn 只读工具() -> Vec<String> {
    [
        "读文件",
        "列举目录",
        "寻找文件",
        "搜索内容",
        "读格位",
        "查格位历史",
    ]
    .iter()
    .map(|名| 名.to_string())
    .collect()
}

/// 消息可见性过滤（生产化 1.5，设计稿 §1.5.5 拍板 6）：
/// 角色发言全员可见；界主发言非@仅鸿钧可见、@点名才带上该角色。
/// 返回该角色是否可见这条消息。
pub fn 消息可见(消息发送者: &str, 可见角色们: &[String], 角色: &str) -> bool {
    if 消息发送者 == "界主" {
        // 界主消息：可见集合 = {鸿钧} ∪ @提及；界主本人总可见。
        角色 == "界主" || 可见角色们.iter().any(|可见| 可见 == 角色)
    } else {
        // 角色发言：全员可见（世界内部透明工作群）。
        true
    }
}

#[cfg(test)]
mod 测试 {
    use super::消息可见;

    #[test]
    fn 界主消息_非点名仅鸿钧可见() {
        let 可见 = vec!["鸿钧".to_string()];
        assert!(消息可见("界主", &可见, "鸿钧"), "鸿钧应可见");
        assert!(!消息可见("界主", &可见, "女娲"), "非点名角色不可见界主消息");
        assert!(消息可见("界主", &可见, "界主"), "界主本人总可见");
    }

    #[test]
    fn 界主消息_点名直达该角色() {
        let 可见 = vec!["鸿钧".to_string(), "女娲".to_string()];
        assert!(消息可见("界主", &可见, "女娲"), "@女娲 点名后女娲可见");
        assert!(!消息可见("界主", &可见, "多宝"), "未点名角色仍不可见");
    }

    #[test]
    fn 角色发言_全员可见() {
        let 可见 = vec!["界主".to_string(), "鸿钧".to_string()];
        assert!(消息可见("女娲", &可见, "多宝"), "圣人发言全员可见");
        assert!(消息可见("多宝", &可见, "准圣"), "大罗发言全员可见");
    }
}
