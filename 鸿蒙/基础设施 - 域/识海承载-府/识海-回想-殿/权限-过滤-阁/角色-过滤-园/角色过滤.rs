//! 角色 - 过滤 - 园：按角色权限过滤格位集合（范畴白名单 + 私有隔离）。

use crate::{格位, 范畴, 共享度};

/// 按角色过滤可见格位：私有格位仅界主可见；其余按角色范畴白名单。
pub fn 可见格位(角色: &str, 格位们: &[格位]) -> Vec<格位> {
    格位们.iter().filter(|格位| 角色可见(角色, 格位)).cloned().collect()
}

fn 角色可见(角色: &str, 格位: &格位) -> bool {
    if 格位.共享度 == 共享度::私有 && 角色 != "界主" {
        return false;
    }
    match 角色范畴(角色) {
        None => true,
        Some(范畴们) => 范畴们.contains(&格位.范畴),
    }
}

/// 角色范畴白名单：None = 全量（界主 / 鸿钧）。
fn 角色范畴(角色: &str) -> Option<Vec<范畴>> {
    match 角色 {
        "界主" | "鸿钧" => None,
        "女娲" => Some(vec![范畴::目标, 范畴::规则, 范畴::世界]),
        "多宝" => Some(vec![范畴::目标, 范畴::规则, 范畴::世界, 范畴::程序]),
        "准圣" => Some(vec![范畴::目标, 范畴::规则, 范畴::世界]),
        _ => None,
    }
}

#[cfg(test)]
mod 测试 {
    use super::*;
    use crate::{格位, 范畴, 固化度, 共享度, 顺序档位};

    fn 造格位(名字: &str, 范畴: 范畴, 共享值: 共享度) -> 格位 {
        格位::新(名字, 范畴, "种子", "代码", 固化度::权, 共享值, 顺序档位::中间)
    }

    #[test]
    fn 界主见全部() {
        let 格位们 = vec![
            造格位("结构", 范畴::世界, 共享度::共享),
            造格位("底线", 范畴::自我, 共享度::私有),
        ];
        assert_eq!(可见格位("界主", &格位们).len(), 2);
    }

    #[test]
    fn 女娲按范畴白名单() {
        let 格位们 = vec![
            造格位("结构", 范畴::世界, 共享度::共享),
            造格位("身份", 范畴::自我, 共享度::共享),
            造格位("环节规则", 范畴::程序, 共享度::共享),
        ];
        // 女娲：目标/规则/世界 → 只看世界（结构），不看自我（身份）/程序（环节规则）
        let 可见 = 可见格位("女娲", &格位们);
        assert_eq!(可见.len(), 1);
        assert_eq!(可见[0].名字, "结构");
    }

    #[test]
    fn 多宝额外见程序() {
        let 格位们 = vec![
            造格位("结构", 范畴::世界, 共享度::共享),
            造格位("环节规则", 范畴::程序, 共享度::共享),
        ];
        assert_eq!(可见格位("多宝", &格位们).len(), 2);
    }
}
