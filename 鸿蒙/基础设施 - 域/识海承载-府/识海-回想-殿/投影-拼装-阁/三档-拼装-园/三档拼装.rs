    /// §14.19：铁律·总纲 带级别记录注入——临时天道最前（优先级高），失效记录被过滤。
    #[test]
    fn 元数据层化_铁律按级别注入且失效过滤() {
        use crate::规则级别;
        let 目录 = std::env::temp_dir().join(format!("三档拼装-级别-{}", std::process::id()));
        let 存储 = 模型存储::打开(&目录);
        let 铁律 = 格位::新(
            "铁律·总纲",
            范畴::规则,
            "最高准则",
            "人类",
            固化度::经,
            共享度::共享,
            顺序档位::中间,
        );
        // 大道项目（宪法）与 临时天道（任务级）各两条。
        // 临时天道用独立实体键"临时天道"（与守卫一致）：任务结束写失效标记后，
        // 实体键级失效判定可跳过该键全部旧记录（§14.19 清理语义）。
        存储
            .写记录(&记录::新带级别(
                "铁律·总纲",
                "全项目使用中文",
                "界主",
                "人类",
                规则级别::大道项目,
            ))
            .unwrap();
        let mut 临时1 = 记录::新带级别(
            "铁律·总纲",
            "本任务只改指定文件",
            "任务规则",
            "人类",
            规则级别::临时天道,
        );
        临时1.实体键 = "临时天道".to_string();
        存储.写记录(&临时1).unwrap();
        // 阶段1：大道项目（宪法）与 临时天道（任务级）两条有效记录。
        存储
            .写记录(&记录::新带级别(
                "铁律·总纲",
                "全项目使用中文",
                "界主",
                "人类",
                规则级别::大道项目,
            ))
            .unwrap();
        let mut 临时2 = 记录::新带级别(
            "铁律·总纲",
            "本任务只改指定文件",
            "任务规则",
            "人类",
            规则级别::临时天道,
        );
        临时2.实体键 = "临时天道".to_string();
        存储.写记录(&临时2).unwrap();

        let 背景 = 元数据层化(&存储, "多宝", std::slice::from_ref(&铁律), 100_000).unwrap();
        assert!(
            背景.contains("全项目使用中文"),
            "应注入大道项目规则：{背景}"
        );
        assert!(
            背景.contains("本任务只改指定文件"),
            "应注入临时天道规则：{背景}"
        );
        // 临时天道在最前（优先级高）：找两条规则的相对位置。
        let 临时位 = 背景.find("本任务只改指定文件").unwrap();
        let 大道位 = 背景.find("全项目使用中文").unwrap();
        assert!(临时位 < 大道位, "临时天道应在最前（优先级高）");

        // 阶段2：任务结束写失效标记（实体键=临时天道，与守卫一致）→ 后续注入过滤。
        let mut 失效 = 记录::新带级别(
            "铁律·总纲",
            "已清理的临时规则",
            "任务结束",
            "代码",
            规则级别::临时天道,
        );
        失效.失效 = true;
        失效.实体键 = "临时天道".to_string();
        存储.写记录(&失效).unwrap();
        let 背景后 = 元数据层化(&存储, "多宝", &[铁律], 100_000).unwrap();
        assert!(
            背景后.contains("全项目使用中文"),
            "清理临时天道不应影响大道项目：{背景后}"
        );
        assert!(
            !背景后.contains("已清理的临时规则"),
            "失效记录不应注入：{背景后}"
        );
        assert!(
            !背景后.contains("本任务只改指定文件"),
            "临时天道失效后不应再注入：{背景后}"
        );
        let _ = std::fs::remove_dir_all(&目录);
    }
