//! 插件注册表辅助功能——批量注册等。
//! 设计依据：层级结构-设计.md §五鸿蒙地基模型、§三边界模型。
//! 同府跨园经共同上级（入口）透出的符号中转，不深链插件接口园文件。

use crate::{府插件, 插件上下文};

/// 批量注册插件——按传入顺序逐个应用+注册，依赖未满足时提前失败。
///
/// 对每个插件先调`应用()`注册服务到服务表，再`注册()`入插件注册表。
/// 调用方须保证被依赖插件排在依赖方之前；按依赖顺序调用`应用()`，
/// 依赖插件的服务先注册，被依赖方可在`应用()`中经`ctx.查找服务()`查找依赖服务。
/// `应用()`失败则插件不注册（初始化失败不应入注册表）。
pub fn 批量注册(
    上下文: &mut 插件上下文, 插件们: Vec<Box<dyn 府插件>>
) -> Result<(), String> {
    for 插件 in 插件们 {
        插件.应用(上下文).map_err(|e| e.to_string())?;
        上下文.注册(插件)?;
    }
    Ok(())
}
