//! 插件注册表辅助功能——批量注册等。
//! 设计依据：层级结构-设计.md §五鸿蒙地基模型、§三边界模型。
//! 同府跨园经共同上级（入口）透出的符号中转，不深链插件接口园文件。

use crate::{府插件, 插件上下文};

/// 批量注册插件——按传入顺序逐个注册，依赖未满足时提前失败。
///
/// 调用方须保证被依赖插件排在依赖方之前；注册时由插件上下文逐一检查依赖。
pub fn 批量注册(
    上下文: &mut 插件上下文, 插件们: Vec<Box<dyn 府插件>>
) -> Result<(), String> {
    for 插件 in 插件们 {
        上下文.注册(插件)?;
    }
    Ok(())
}
