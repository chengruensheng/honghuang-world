//! 归因 - 留痕 - 园：进化环采集、归因、留痕。

use crate::类型_定义_殿::{失败条目, 调整级别, 进化记录, 缺陷层};
use rizhi_fu::debug;

/// 归因：失败条目 → 调整级别。
pub fn 归因(条目: &失败条目) -> 调整级别 {
    let 级别 = if 条目.所在层 == 缺陷层::设计层 {
        调整级别::调流程
    } else if 条目.次数 >= 2 {
        调整级别::调分工
    } else {
        调整级别::调提示词
    };
    debug!(要求id = %条目.要求id, 级别 = ?级别, "进化归因完成");
    级别
}

/// 留痕：生成一条进化记录。
pub fn 留痕(id: &str, 级别: 调整级别, 触发原因: &str, 前后对比: &str, 时间: u64) -> 进化记录 {
    // 事件流：进化留痕（append-only 事实源，进化环每留痕一条）。
    let 流 = shihai_fu::事件流::在工作区(&shihai_fu::工作区::定位());
    let _ = 流.追加事件(shihai_fu::事件类型::进化留痕, serde_json::json!({
        "进化id": id,
        "级别": format!("{:?}", 级别),
        "触发原因": 触发原因,
    }));
    进化记录 {
        id: id.to_string(),
        级别,
        触发原因: 触发原因.to_string(),
        前后对比: 前后对比.to_string(),
        效果回执: None,
        时间,
    }
}
