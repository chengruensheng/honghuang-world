//! 归因 - 留痕 - 园：进化环采集、归因、留痕。

use crate::类型_定义_殿::{失败条目, 调整级别, 进化记录, 缺陷层};

/// 归因：失败条目 → 调整级别。
pub fn 归因(条目: &失败条目) -> 调整级别 {
    if 条目.所在层 == 缺陷层::设计层 {
        调整级别::调流程
    } else if 条目.次数 >= 2 {
        调整级别::调分工
    } else {
        调整级别::调提示词
    }
}

/// 留痕：生成一条进化记录。
pub fn 留痕(id: &str, 级别: 调整级别, 触发原因: &str, 前后对比: &str, 时间: u64) -> 进化记录 {
    进化记录 {
        id: id.to_string(),
        级别,
        触发原因: 触发原因.to_string(),
        前后对比: 前后对比.to_string(),
        效果回执: None,
        时间,
    }
}

#[cfg(test)]
mod 测试 {
    use super::*;

    #[test]
    fn 设计层归因调流程() {
        let 条目 = 失败条目 {
            要求id: "r1".to_string(),
            阶段: "设计".to_string(),
            原因: "缺环节".to_string(),
            所在层: 缺陷层::设计层,
            次数: 1,
            时间: 0,
        };
        assert_eq!(归因(&条目), 调整级别::调流程);
    }

    #[test]
    fn 实现层多次失败调分工() {
        let 条目 = 失败条目 {
            要求id: "r1".to_string(),
            阶段: "实现".to_string(),
            原因: "反复失败".to_string(),
            所在层: 缺陷层::实现层,
            次数: 3,
            时间: 0,
        };
        assert_eq!(归因(&条目), 调整级别::调分工);
    }
}
