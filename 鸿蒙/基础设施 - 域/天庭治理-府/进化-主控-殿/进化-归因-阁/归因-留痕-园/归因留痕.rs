//! 归因 - 留痕 - 园：进化环采集、归因、留痕。

use crate::类型_定义_殿::{失败条目, 缺陷层, 调整级别, 进化记录};
use rizhi_fu::debug;

/// 归因：失败条目 → 调整级别。
pub fn 归因(条目: &失败条目) -> 调整级别 {
    let 级别 = if 条目.所在层 == 缺陷层::设计层 {
        调整级别::调流程
    } else if 条目.次数 >= 2 {
        调整级别::调分工
    } else {
        调整级别::调提示词
    };
    debug!(要求id = %条目.要求id, 级别 = ?级别, "进化归因完成");
    级别
}

/// 留痕：生成一条进化记录。
pub fn 留痕(
    id: &str, 级别: 调整级别, 触发原因: &str, 前后对比: &str, 时间: u64
) -> 进化记录 {
    // 事件流：进化留痕（append-only 事实源，进化环每留痕一条）。
    let 流 = shihai_fu::事件流::在工作区(&shihai_fu::工作区::定位());
    流.追加事件静默(
        shihai_fu::事件类型::进化留痕,
        serde_json::json!({
            "进化id": id,
            "级别": format!("{:?}", 级别),
            "触发原因": 触发原因,
        }),
    );
    进化记录 {
        id: id.to_string(),
        级别,
        触发原因: 触发原因.to_string(),
        前后对比: 前后对比.to_string(),
        效果回执: None,
        时间,
    }
}

#[cfg(test)]
mod 测试 {
    use super::*;

    fn 构造条目(层: 缺陷层, 次数: u32) -> 失败条目 {
        失败条目 {
            要求id: "r1".to_string(),
            阶段: "测试".to_string(),
            原因: "测试".to_string(),
            所在层: 层,
            次数,
            时间: 0,
        }
    }

    #[test]
    fn 设计层归因调流程() {
        let 条目 = 构造条目(缺陷层::设计层, 5);
        assert_eq!(归因(&条目), 调整级别::调流程);
    }

    #[test]
    fn 设计层单次仍调流程() {
        let 条目 = 构造条目(缺陷层::设计层, 1);
        assert_eq!(归因(&条目), 调整级别::调流程);
    }

    #[test]
    fn 实现层恰好两次调分工() {
        let 条目 = 构造条目(缺陷层::实现层, 2);
        assert_eq!(归因(&条目), 调整级别::调分工);
    }

    #[test]
    fn 实现层单次失败调提示词() {
        let 条目 = 构造条目(缺陷层::实现层, 1);
        assert_eq!(归因(&条目), 调整级别::调提示词);
    }

    #[test]
    fn 实现层零次失败调提示词() {
        let 条目 = 构造条目(缺陷层::实现层, 0);
        assert_eq!(归因(&条目), 调整级别::调提示词);
    }

    /// 设计层优先级最高：即便次数再多也归因为调流程。
    #[test]
    fn 设计层次数大于二仍调流程() {
        let 条目 = 构造条目(缺陷层::设计层, 10);
        assert_eq!(归因(&条目), 调整级别::调流程);
    }

    /// 留痕 正确填充所有公开字段（id / 级别 / 触发原因 / 前后对比 / 时间）。
    #[test]
    fn 留痕填充所有字段() {
        let 记录 = 留痕("ev-001", 调整级别::调流程, "原因A", "前后对比A", 1234);
        assert_eq!(记录.id, "ev-001");
        assert_eq!(记录.级别, 调整级别::调流程);
        assert_eq!(记录.触发原因, "原因A");
        assert_eq!(记录.前后对比, "前后对比A");
        assert_eq!(记录.时间, 1234);
    }

    /// 留痕 效果回执 字段默认应为空（留痕时尚未回流）。
    #[test]
    fn 留痕效果回执默认为空() {
        let 记录 = 留痕("ev-002", 调整级别::调分工, "r", "c", 0);
        assert!(记录.效果回执.is_none());
    }

    /// 留痕 多次调用生成相互独立的 进化记录。
    #[test]
    fn 留痕多次调用独立() {
        let r1 = 留痕("id-1", 调整级别::调提示词, "a", "b", 1);
        let r2 = 留痕("id-2", 调整级别::调流程, "c", "d", 2);
        assert_eq!(r1.id, "id-1");
        assert_eq!(r2.id, "id-2");
        assert_eq!(r1.级别, 调整级别::调提示词);
        assert_eq!(r2.级别, 调整级别::调流程);
        assert_eq!(r1.时间, 1);
        assert_eq!(r2.时间, 2);
    }

    /// 留痕 字符串字段按所有权拷贝，互不影响。
    #[test]
    fn 留痕字符串字段独立拷贝() {
        let 原触发 = "原触发".to_string();
        let 原对比 = "原对比".to_string();
        let 记录 = 留痕("id-3", 调整级别::调分工, &原触发, &原对比, 9);
        assert_eq!(记录.触发原因, "原触发");
        assert_eq!(记录.前后对比, "原对比");
        assert_eq!(原触发, "原触发");
        assert_eq!(原对比, "原对比");
    }
}
