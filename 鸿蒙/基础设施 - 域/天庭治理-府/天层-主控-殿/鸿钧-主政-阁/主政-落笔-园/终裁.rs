/// 项目结构摘要（问题15）：读依赖图结构树 + workspace members，渲染为文本注入准圣/鸿钧提示词。
///
/// 治「准圣/鸿钧不知项目全貌、凭局部产物推断架构」——注入项目结构树与 workspace 成员清单，
/// 让审验方从整体结构判断产物归属合理性、模块接入是否符合六层落点（维度/域/府/殿/阁/园）。
///
/// 两段：
/// - 【结构树】：从 `shihai_fu::依赖图::加载自工作区` 读结构树，递归渲染为缩进文本（每层 2 空格）。
/// - 【workspace members】：从根 Cargo.toml 读 workspace members（含 `-府"` 的行即成员，
///   适配单行/多行 members，与 建档.rs 同口径）。
///
/// 预算：总上限 2000 字符，超则截断标注。读失败/无结构返回占位（不阻断审验）。
fn 项目结构摘要() -> String {
    const 总上限: usize = 2_000;
    let 工作区 = shihai_fu::工作区::定位();

    // 结构树：从依赖图读，递归渲染为缩进文本。
    let 结构树段 = match shihai_fu::依赖图::加载自工作区(&工作区) {
        Ok(图) => 渲染结构树(&图.结构树),
        Err(_) => "（无结构树）".to_string(),
    };

    // workspace members：从根 Cargo.toml 读（含 `-府"` 的行即成员，与 建档.rs 同口径）。
    let members段 = std::fs::read_to_string(工作区.根路径().join("Cargo.toml"))
        .map(|内容| {
            let 成员们: Vec<String> = 内容
                .lines()
                .filter(|行| 行.contains("-府\""))
                .map(|行| {
                    行.trim()
                        .trim_start_matches('"')
                        .trim_end_matches(',')
                        .trim_end_matches('"')
                        .to_string()
                })
                .collect();
            if 成员们.is_empty() {
                "（无 workspace members）".to_string()
            } else {
                成员们.join("、")
            }
        })
        .unwrap_or_else(|_| "（读 Cargo.toml 失败）".to_string());

    let 合并 = format!(
        "【结构树】\n{树}\n【workspace members】\n{members}",
        树 = 结构树段,
        members = members段
    );
    if 合并.chars().count() > 总上限 {
        let mut 截断: String = 合并.chars().take(总上限).collect();
        截断.push_str("…（项目结构摘要截断）");
        return 截断;
    }
    合并
}

/// 递归渲染结构节点为缩进文本（每层 2 空格，根节点不缩进）。
fn 渲染结构树(节点: &shihai_fu::结构节点) -> String {
    let mut 输出 = String::new();
    渲染结构树_递归(节点, 0, &mut 输出);
    if 输出.is_empty() {
        return "（空结构树）".to_string();
    }
    输出
}

/// 结构树递归渲染内部函数：深度控制缩进，子节点逐级下探。
fn 渲染结构树_递归(节点: &shihai_fu::结构节点, 深度: usize, 输出: &mut String) {
    if !节点.名字.is_empty() {
        for _ in 0..深度 {
            输出.push_str("  ");
        }
        输出.push_str(&节点.名字);
        输出.push('\n');
    }
    for 子 in &节点.子节点 {
        渲染结构树_递归(子, 深度 + 1, 输出);
    }
}

/// 单准圣审验：模型一次调用 → 该维度意见。
///
/// `项目结构`：由调用方（六准圣审验）预计算一次传入，避免每个准圣线程重复读依赖图与
/// Cargo.toml。内容为 `项目结构摘要()` 的产出（结构树 + workspace members）。
fn 单准圣审验(
    要求书: &要求书,
    产物们: &[产物条目],
    维度: &准圣维度,
    配置: &模型配置,
    项目结构: &str,
    规则: &str,
) -> Result<(准圣意见, 用量), String> {
    // A 体系（2026-08-19）：按当前准圣维度过滤产物——前端准圣只看 .html/.css/.js 等，
    // 后端只看 .rs 库代码，测试只看 tests/ 或含 #[test] 的 .rs。每个准圣只审自己类别的产物。
    let 类别产物们: Vec<产物条目> = 产物们
        .iter()
        .filter(|p| 准圣维度::按产物类别选(p) == *维度)
        .cloned()
        .collect();
    let 产物清单 = 类别产物们
        .iter()
        .map(|p| {
            format!(
                "- {} ({}字节, {}, 变化类型={})",
                p.路径, p.字节数, p.类别, p.变化类型
            )
        })
        .collect::<Vec<_>>()
        .join("\n");
    let 涉及 = if 要求书.约束.涉及路径.is_empty() {
        "（无）".to_string()
    } else {
        要求书.约束.涉及路径.join(", ")
    };
    let 涉及现状 = 涉及路径现状(&要求书.约束.涉及路径);
    let 内容摘要 = 产物内容摘要(&类别产物们);
    let 原文摘录 = 产物原文摘录(&类别产物们);
    // 审验标准（让世界自审）：细则·解读 格位的「准圣审验标准清单」逐条核对。
    // 缺失时注入占位提示（不阻断审验）。
    let 审验标准 = 读审验标准()
        .unwrap_or_else(|| "（无审验标准清单——按各维度职司与要求验收标准审验）".to_string());

    let 提示 = format!(
        "{规则}你是{dim}\n\n{role}\n\n【审验标准清单】（逐条核对，任一违反即打回并指明违反条目）\n{stdlist}\n\n【要求方向】{dir}\n【验收标准】{std}\n【涉及路径】{path}\n【涉及现状】\n{cur}\n【产物清单】\n{prod}\n【产物内容摘要】（机械提取自产物真实文件，可据此核对实现细节，不必假设无法读取文件）\n{sum}\n【产物原文摘录】（机械读自产物真实文件、预算内截断；请以真实内容为准核对实现细节，勿仅凭字节数/符号推断）\n{raw}\n\n【项目结构】（依赖图结构树 + workspace members，供判断产物归属与模块接入合理性）\n{struct}\n\n【现实事实】（执行层已机械验证，勿以假设推翻）\n{fact}\n\n请基于以上事实独立审验，仅输出 JSON（无 Markdown、无解释、无 think）：\n{{\"结论\":\"通过|打回\",\"评分\":0-100,\"关键问题\":\"一句话\",\"改进建议\":[\"建议1\",\"建议2\"]}}\n\n判定原则：\n- 通过：你的维度内未发现阻断性问题，可改进但不影响本轮交付。\n- 打回：你的维度内存在必须修复的阻断性问题，包括违反【审验标准清单】中属于你维度的条目。\n- 产物清单为空时（设计稿 §11.2 规则 5/7：现状已达标无需产物的语义裁决）：\n  - 要求方向属审验/核查类（含 审验/核对/检查/验证/达标/核查 措辞）、要求书允许「已达标则不写文件」、且涉及路径文件均存在非空 → 判「通过」（评分 60-85，按实际核验程度给分）。\n  - 要求方向属实现/新增/开发类且无产物 → 判「打回」。\n  - 涉及路径文件缺失或为空 → 判「打回」。\n- 改进建议最多 3 条；无则输出空数组。\n\n输出纪律：允许先思考（think），但 **think 结束后必须紧接输出上方 JSON 对象**——若你的思考链很长，请控制 think 长度，务必给 JSON 留足输出空间；只有 JSON 才算有效审验，think 单独输出视为审验失败。",
        规则 = 规则,
        dim = 维度.名称(),
        role = 维度.角色提示(),
        stdlist = 审验标准,
        dir = 要求书.方向,
        std = 要求书.验收标准,
        path = 涉及,
        cur = 涉及现状,
        prod = 产物清单,
        sum = 内容摘要,
        raw = 原文摘录,
        struct = 项目结构,
        fact = 现实事实,
    );

    // 输出上限：准圣是带长 think 的推理模型（MiniMax-M3 实测 think 可消耗数千 token），
    // 精简上限 4096 下 think 后无空间输出 JSON → 被截断成 think-only（要求-65 实证）。
    // 提至 常规上限 16384：max_tokens 只是上限不强制用完，实际输出仍短，成本影响极小；
    // 但给 think + JSON 足够空间，从源头消除 think-only 截断。
    // 维度耗时实测：模型调用前后记 Instant，供验收性能量化与慢维度定位（并发下各维度独立计时）。
    let 调用起点 = std::time::Instant::now();
    let (回复, 用量) = 调用模型(配置, &[对话消息::用户(提示)], moxing_fu::常规上限)?;
    let 维度耗时秒 = 调用起点.elapsed().as_secs_f64();
    let 干净 = 提取对象(&回复).map_err(|错误| format!("准圣审验解析失败: {错误}"))?;
    let 解析: serde_json::Value =
        serde_json::from_str(&干净).map_err(|错误| format!("准圣审验解析失败: {错误}"))?;
    let 结论 = match 解析["结论"].as_str() {
        Some("通过") => 验收结论::通过,
        _ => 验收结论::打回,
    };
    let 评分 = 解析["评分"].as_u64().unwrap_or(50).min(100) as u8;
    let 关键问题 = 解析["关键问题"].as_str().unwrap_or("").to_string();
    let 改进建议 = 解析["改进建议"]
        .as_array()
        .map(|项们| {
            项们
                .iter()
                .filter_map(|项| 项.as_str().map(|s| s.to_string()))
                .take(3)
                .collect::<Vec<_>>()
        })
        .unwrap_or_default();

    Ok((
        准圣意见 {
            维度: 维度.clone(),
            结论,
            评分,
            关键问题,
            改进建议,
            耗时秒: 维度耗时秒,
        },
        用量,
    ))
}

