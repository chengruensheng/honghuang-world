//! 终裁·产物校验：机械前置门槛与路径相符检查。
//!
//! 由 终裁/裁决.rs（终裁裁决_无名）与 终裁/裁决.rs（规则兜底）调用，
//! 做产物路径越界、路径偏离涉及范围、空洞产物等机械硬性校验。

use crate::类型_定义_殿::*;
use moxing_fu::用量;
use rizhi_fu::warn;

use super::终裁回执;

/// 机械前置门槛：仅做绝对硬性检查。
/// 通过 → 返回 None 进入准圣审验；不通过 → 返回 Some(打回终裁) 立即终结。
///
/// `涉及文件` 用于产物路径匹配检查（治 M3 写错位置假阳性）：产物必须落在涉及路径指定
/// 的位置。涉及文件为空时跳过本检查（审验/核查类任务无涉及路径，设计稿 §11.2 规则 5）。
pub(super) fn 机械前置门槛(
    要求id: &str,
    产物们: &[产物条目],
    耗时秒: f64,
    失败说明: Option<&str>,
    涉及文件: &[String],
) -> Option<终裁回执> {
    // 1. 编译失败：产物不可信，直接打回。
    if let Some(说明) = 失败说明 {
        warn!(要求 = 要求id, "终裁打回：编译失败");
        return Some(终裁回执 {
            验收: 验收回执 {
                要求id: 要求id.to_string(),
                结论: 验收结论::打回,
                验收意见: Some(说明.to_string()),
                产物: vec![],
                耗时秒,
            },
            准圣意见们: vec![],
            终裁依据: "编译失败，产物不可信".to_string(),
            用量: 用量::default(),
        });
    }

    // 2. 无产物：不在此拦截——执行成功但无产物属于「现状已达标无需改动」的语义裁决，
    //    按设计稿 §11.2 规则 5 交六准圣 LLM 判断（机械门槛只防三硬伤）。
    //    执行失败且无产物已由上一分支（编译失败/失败说明）拦截，此处不会误放行空转。
    debug_assert!(失败说明.is_none(), "失败说明应已在上方分支处理");

    // 3. 路径越界：产物路径必须是工作区内的相对路径，不得含 .. 或为绝对路径。
    //    本质：任何项目的通用安全护栏，防产物逃逸涉及范围、写到工作区之外。
    let 根 = shihai_fu::工作区::定位();
    let 有越界 = 产物们.iter().any(|产物| {
        let 路径 = 产物.路径.replace('\\', "/");
        // 绝对路径：以 / 开头，或首段为盘符（如 C:）。
        if 路径.starts_with('/') {
            return true;
        }
        let 段们: Vec<&str> = 路径.split('/').collect();
        if 段们.first().is_some_and(|段| 段.ends_with(':')) {
            return true;
        }
        // 上跳段：.. 逃逸工作区。
        段们.contains(&"..")
    });
    if 有越界 {
        warn!(要求 = 要求id, "终裁打回：产物路径越界");
        return Some(终裁回执 {
            验收: 验收回执 {
                要求id: 要求id.to_string(),
                结论: 验收结论::打回,
                验收意见: Some(
                    "实现层：产物路径越界（含 .. 或绝对路径，逃逸工作区）".to_string(),
                ),
                产物: vec![],
                耗时秒,
            },
            准圣意见们: vec![],
            终裁依据: "产物路径越界".to_string(),
            用量: 用量::default(),
        });
    }

    // 4. 产物路径匹配涉及范围：产物必须落在涉及路径指定的位置（治 M3 写错位置假阳性，
    //    如「鸿蒙/基础设施-域/」缺空格写成「鸿蒙/基础设施 - 域/」）。涉及文件为空时跳过
    //    （审验/核查类任务无涉及路径）；产物为空时跳过（无产物走准圣判断，设计稿 §11.2 规则 5）。
    //    复用 `路径相符`：统一分隔符、不区分大小写、包含匹配。
    if !涉及文件.is_empty() && !产物们.is_empty() && !路径相符(涉及文件, 产物们) {
        warn!(要求 = 要求id, "终裁打回：产物路径偏离涉及范围");
        return Some(终裁回执 {
            验收: 验收回执 {
                要求id: 要求id.to_string(),
                结论: 验收结论::打回,
                验收意见: Some(
                    "实现层：产物路径偏离涉及范围（产物未落在涉及路径指定的位置）".to_string(),
                ),
                产物: vec![],
                耗时秒,
            },
            准圣意见们: vec![],
            终裁依据: "产物路径偏离涉及范围".to_string(),
            用量: 用量::default(),
        });
    }

    // 5. 空洞产物：产物必须真实存在且非空（防空文件静默破坏）。
    let 有空洞 = 产物们.iter().any(|产物| {
        let 绝对 = 根.根路径().join(&产物.路径);
        std::fs::metadata(&绝对)
            .map(|元| 元.len() == 0)
            .unwrap_or(true)
    });
    if 有空洞 {
        warn!(要求 = 要求id, "终裁打回：空洞产物");
        return Some(终裁回执 {
            验收: 验收回执 {
                要求id: 要求id.to_string(),
                结论: 验收结论::打回,
                验收意见: Some("实现层：产物为空文件或不存在".to_string()),
                产物: vec![],
                耗时秒,
            },
            准圣意见们: vec![],
            终裁依据: "空洞产物".to_string(),
            用量: 用量::default(),
        });
    }

    None
}

/// 路径相符检查（统一分隔符、不区分大小写）。
/// 涉及文件为空时一律通过（兜底产物清单）。
pub(super) fn 路径相符(涉及文件: &[String], 产物们: &[产物条目]) -> bool {
    if 涉及文件.is_empty() {
        return true;
    }
    let 规整涉及: Vec<String> = 涉及文件
        .iter()
        .map(|f| f.replace('\\', "/").to_lowercase())
        .collect();
    产物们.iter().any(|产物| {
        let 产物路径 = 产物.路径.replace('\\', "/").to_lowercase();
        规整涉及
            .iter()
            .any(|项| 产物路径 == *项 || 产物路径.contains(项.as_str()))
    })
}
