/// 六准圣分维独立审验（A 体系 2026-08-19）：按**产物类别**去重选准圣并发审验——
/// 每个产物只过 1 个对应类别的准圣（不再 6 维全跑）。多产物跨类别 → 多个准圣并发。
/// 每个准圣只看自己类别的产物（前端准圣只看 .html/.css/.js 等，后端只看 .rs 库代码，测试只看 tests/）。
///
/// 并发安全：各工作线程内先 进入观测(验收, 要求id)（线程本地上下文，模型调用按此关联
/// 要求id 与角色），单准圣审验 其余逻辑纯读共享引用（要求书/类别产物们/配置均 Sync）。
///
/// 继承制（A 体系）：6 类别准圣（前端/后端/文档/测试/性能/配置）按产物扩展名+路径分派；
/// 通用业务 兜底（无匹配类别时启用）。完全替代旧 6 通用维度（业务/数据/性能/安全/异常/UX）。
pub fn 六准圣审验(
    要求书: &要求书,
    产物们: &[产物条目],
    配置: &模型配置,
) -> (Vec<准圣意见>, 用量) {
    let 要求id = 要求书.id.clone();
    // 项目结构摘要预计算一次（读依赖图 + Cargo.toml），避免每个准圣线程重复 IO。
    // 各线程 clone 字符串副本传入 单准圣审验，不争用共享资源。
    let 项目结构 = super::摘要::项目结构摘要();
    // 可操作规则预获取一次（§4.2 规则7）：从 细则·解读 格位读链头最新规则文本，
    // 注入各准圣提示词首行。空串不注入（格位无有效记录时不影响现有行为）。
    let 规则 = 读可操作规则();
    // A 体系：按产物类别去重选准圣（每个产物 → 1 个准圣；多产物跨类别 → 多准圣并发）。
    // 复用 准圣维度::按产物类别选（A 改动 1 已实现）。
    let 类别_产物们: std::collections::BTreeMap<准圣维度, Vec<产物条目>> = {
        let mut map: std::collections::BTreeMap<准圣维度, Vec<产物条目>> =
            std::collections::BTreeMap::new();
        for 产物 in 产物们 {
            map.entry(准圣维度::按产物类别选(产物))
                .or_default()
                .push(产物.clone());
        }
        map
    };
    let 结果们: Vec<Result<(准圣意见, 用量), String>> = std::thread::scope(|作用域| {
        let 句柄们: Vec<_> = 类别_产物们
            .iter()
            .map(|(维度, 类别产物们)| {
                let 要求id = 要求id.clone();
                let 类别产物们 = 类别产物们.clone();
                let 项目结构 = 项目结构.clone();
                let 规则 = 规则.clone();
                作用域.spawn(move || {
                    // 线程本地验收观测上下文：模型调用的 记请求/记回复 按此关联 要求id+验收角色。
                    let _观测守卫 = 进入观测(观测角色::验收, None, Some(要求id), None);
                    单准圣审验(要求书, &类别产物们, 维度, 配置, &项目结构, &规则)
                })
            })
            .collect();
        句柄们
            .into_iter()
            .map(|句柄| {
                句柄
                    .join()
                    .unwrap_or_else(|_| Err("准圣审验线程异常".to_string()))
            })
            .collect()
    });
    let mut 意见们 = Vec::with_capacity(类别_产物们.len());
    let mut 累计用量 = 用量::default();
    for (维度, 结果) in 类别_产物们.keys().zip(结果们) {
        match 结果 {
            Ok((意见, 用量)) => {
                info!(
                    要求 = %要求书.id, 维度 = 维度.名称(),
                    结论 = ?意见.结论, 评分 = 意见.评分,
                    "准圣审验完成"
                );
                累计用量.加(&用量);
                意见们.push(意见);
            }
            Err(错误) => {
                // 审验失败（网络/解析偶发）重试一次：要求-63 实测 4/6 准圣偶发
                // "key must be a string" 解析失败，但观测证明其模型回复均合法——重试大概率成功。
                warn!(
                    要求 = %要求书.id, 维度 = 维度.名称(),
                    错误 = %错误, "准圣审验失败，重试一次"
                );
                let 类别产物们 = &类别_产物们[维度];
                match 单准圣审验(要求书, 类别产物们, 维度, 配置, &项目结构, &规则)
                {
                    Ok((意见, 用量)) => {
                        info!(
                            要求 = %要求书.id, 维度 = 维度.名称(),
                            结论 = ?意见.结论, 评分 = 意见.评分, 重试 = true,
                            "准圣审验完成（重试成功）"
                        );
                        累计用量.加(&用量);
                        意见们.push(意见);
                    }
                    Err(重试错误) => {
                        // 重试仍失败（多为模型只输出 think 无 JSON，要求-65 实测）：该维度弃权——
                        // 不 push 打回意见（审验失败≠发现问题，打回会误导鸿钧当阻断性问题）。
                        warn!(
                            要求 = %要求书.id, 维度 = 维度.名称(),
                            错误 = %重试错误, "准圣审验重试仍失败，该维度弃权"
                        );
                    }
                }
            }
        }
    }
    (意见们, 累计用量)
}

/// 六准圣意见 reducer：纯代码数据清洗（去重 + 剔残缺），让鸿钧聚焦矛盾裁决而非数据清洗。
///
/// 对齐 §14.20 数据清洗 reducer 应用点 3。两步：
/// 1. **去重**：同维度重复意见只留第一条（六准圣审验已按类别去重，此处双保险——
///    并发重试可能产生重复维度意见，去重保险）。
/// 2. **剔残缺**：打回但关键问题为空的残缺意见剔除（打回但没说原因，转为弃权不 push）。
///    通过意见关键问题为空是正常的（通过无需说明原因），不剔。
///
/// 标矛盾不需要额外标记：鸿钧终裁已有通过数/总数判断矛盾逻辑，reducer 只保证输入鸿钧
/// 的意见是干净的。
pub(super) fn 准圣意见reducer(意见们: Vec<准圣意见>) -> Vec<准圣意见> {
    let mut 已见维度: std::collections::HashSet<准圣维度> = std::collections::HashSet::new();
    let mut 干净们 = Vec::with_capacity(意见们.len());
    for 意见 in 意见们 {
        // 去重：同维度只留第一条
        if !已见维度.insert(意见.维度.clone()) {
            continue;
        }
        // 剔残缺：打回但关键问题为空 → 残缺打回意见，转弃权不 push
        if 意见.结论 == 验收结论::打回 && 意见.关键问题.trim().is_empty() {
            continue;
        }
        干净们.push(意见);
    }
    干净们
}

/// 鸿钧终裁：综合六准圣意见 → 最终结论。
/// - 6 准圣一致通过 → 通过
/// - 6 准圣一致打回 → 打回
/// - 争议 → 调用鸿钧 LLM 综合判断
pub(super) fn 鸿钧终裁(
    要求书: &要求书,
    产物们: &[产物条目],
    意见们: &[准圣意见],
    配置: &模型配置,
) -> Result<(验收结论, String, 用量), String> {
    // 白箱观测：终裁是鸿钧动作（栈顶覆盖验收档；无争议时无 LLM 调用，仅机械结论）。
    let _观测守卫 = 进入观测(观测角色::鸿钧, None, Some(要求书.id.clone()), None);
    let 通过数 = 意见们.iter().filter(|o| o.结论 == 验收结论::通过).count();
    let 总数 = 意见们.len();
    if 通过数 == 总数 && 总数 > 0 {
        return Ok((
            验收结论::通过,
            "审验准圣一致通过".to_string(),
            用量::default(),
        ));
    }
    if 通过数 == 0 && 总数 > 0 {
        return Ok((
            验收结论::打回,
            "六准圣一致打回".to_string(),
            用量::default(),
        ));
    }

    // 争议：调用鸿钧综合判断
    let 意见文本 = 意见们
        .iter()
        .map(|o| {
            format!(
                "{}: {:?} (评分 {}) - {}",
                o.维度.名称(),
                o.结论,
                o.评分,
                o.关键问题
            )
        })
        .collect::<Vec<_>>()
        .join("\n");
    let 产物清单 = 产物们
        .iter()
        .map(|p| format!("- {} ({}字节, 变化类型={})", p.路径, p.字节数, p.变化类型))
        .collect::<Vec<_>>()
        .join("\n");
    let 内容摘要 = super::摘要::产物内容摘要(产物们);
    let 原文摘录 = super::摘要::产物原文摘录(产物们);
    // 项目结构摘要（问题15）：注入结构树 + workspace members，供鸿钧从整体架构判断争议。
    let 项目结构 = super::摘要::项目结构摘要();
    // 可操作规则（§4.2 规则7）：从 细则·解读 格位读链头最新规则文本，注入提示词首行。
    let 规则 = 读可操作规则();

    let 提示 = format!(
        "{规则}你是鸿钧道祖，负责验收终裁。\n六准圣意见存在争议（{pass}/{total} 通过），请综合判断。\n\n【要求方向】{dir}\n【验收标准】{std}\n\n【六准圣意见】\n{opinion}\n\n【产物清单】\n{prod}\n【产物内容摘要】（机械提取自产物真实文件）\n{sum}\n【产物原文摘录】（机械读自产物真实文件、预算内截断；争议裁决请以真实内容为准）\n{raw}\n\n【项目结构】（依赖图结构树 + workspace members，供判断产物归属与模块接入合理性）\n{struct}\n\n【现实事实】（执行层已机械验证，勿以假设推翻）\n{fact}\n\n仅输出 JSON：\n{{\"结论\":\"通过|打回\",\"依据\":\"一句话综合理由\"}}\n\n判定原则：\n- 打回：至少 1 个准圣的打回意见为阻断性（接口契约错/编译/孤儿/涉及文件缺失）。\n- 通过：所有打回意见仅为改进建议、非阻断性。\n- 审验型要求且产物为空、要求书允许「已达标则不写文件」、涉及路径文件均存在非空时，「产物缺失」不作为阻断性（设计稿 §11.2 规则 7）。",
        规则 = 规则,
        pass = 通过数,
        total = 总数,
        dir = 要求书.方向,
        std = 要求书.验收标准,
        opinion = 意见文本,
        prod = 产物清单,
        sum = 内容摘要,
        raw = 原文摘录,
        struct = 项目结构,
        fact = 现实事实,
    );

    let (回复, 用量) = moxing_fu::调用模型(配置, &[对话消息::用户(提示)], 常规上限)?;
    let 干净 = 提取对象(&回复).map_err(|错误| format!("鸿钧终裁解析失败: {错误}"))?;
    let 解析: serde_json::Value =
        serde_json::from_str(&干净).map_err(|错误| format!("鸿钧终裁解析失败: {错误}"))?;
    let 结论 = match 解析["结论"].as_str() {
        Some("通过") => 验收结论::通过,
        _ => 验收结论::打回,
    };
    let 依据 = 解析["依据"].as_str().unwrap_or("").to_string();
    Ok((结论, 依据, 用量))
}

/// 综合六准圣打回意见为一句话验收意见（仅打回时返回）。
pub(super) fn 综合意见文本(
    意见们: &[准圣意见],
    结论: &验收结论,
    依据: &str,
) -> Option<String> {
    if *结论 == 验收结论::通过 {
        return None;
    }
    let 打回项们: Vec<&准圣意见> = 意见们.iter().filter(|o| o.结论 == 验收结论::打回).collect();
    if 打回项们.is_empty() {
        return Some(依据.to_string());
    }
    let 关键问题 = 打回项们
        .iter()
        .map(|o| format!("{}: {}", o.维度.名称(), o.关键问题))
        .collect::<Vec<_>>()
        .join("；");
    Some(format!("准圣打回：{关键问题}"))
}
