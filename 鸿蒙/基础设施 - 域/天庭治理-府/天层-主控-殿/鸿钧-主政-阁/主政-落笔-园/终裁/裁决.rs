//! 终裁·裁决：终裁主入口、规则兜底、验收事件。
//!
//! 三段流程的入口与降级路径：① 机械前置门槛（产物校验.rs）→ ② 六准圣审验（审验.rs）
//! → ③ 鸿钧终裁（审验.rs）。无 LLM 配置或无要求书时降级走本模块的规则兜底。

use crate::类型_定义_殿::*;
use jiance_fu::{观测角色, 进入观测};
use moxing_fu::{模型配置, 用量};
use rizhi_fu::{error, info, warn};
use shijian_fu::全局总线;

use super::super::模块树::接入模块树;
use super::终裁回执;

/// 规则兜底（无 LLM 配置时）：路径相符 + 模块接入。
/// 保留旧机械裁决语义，使现有 验收裁决(无要求书) 测试继续通过。
pub(super) fn 规则兜底(
    要求id: &str,
    产物们: &[产物条目],
    耗时秒: f64,
    涉及文件: &[String],
) -> 终裁回执 {
    let 路径_ok = super::产物校验::路径相符(涉及文件, 产物们);
    // 无产物保守打回：降级兜底无 LLM 语义能力，无法判断「现状已达标无需产物」——
    // 该语义裁决（设计稿 §11.2 规则 5）只属于六准圣 LLM，降级时不确定即打回。
    if 产物们.is_empty() {
        warn!(要求 = 要求id, "终裁打回：无产物（降级兜底保守）");
        return 终裁回执 {
            验收: 验收回执 {
                要求id: 要求id.to_string(),
                结论: 验收结论::打回,
                验收意见: Some("实现层：无产物（降级兜底无 LLM 语义判断）".to_string()),
                产物: vec![],
                耗时秒,
            },
            准圣意见们: vec![],
            终裁依据: "无产物，降级兜底保守打回".to_string(),
            用量: 用量::default(),
        };
    }
    let 根 = shihai_fu::工作区::定位();
    let 有孤儿 = 产物们
        .iter()
        .any(|产物| !接入模块树(根.根路径(), &产物.路径));
    let 结论 = if 路径_ok && !有孤儿 {
        验收结论::通过
    } else {
        验收结论::打回
    };
    let 意见 = if 结论 == 验收结论::打回 {
        Some(if 有孤儿 {
            "实现层：产物未接入模块树".to_string()
        } else {
            "实现层：产物路径偏离涉及范围".to_string()
        })
    } else {
        None
    };
    info!(要求 = 要求id, 结论 = ?结论, "规则兜底裁决");
    终裁回执 {
        验收: 验收回执 {
            要求id: 要求id.to_string(),
            结论,
            验收意见: 意见,
            产物: 产物们.to_vec(),
            耗时秒,
        },
        准圣意见们: vec![],
        终裁依据: "无LLM配置，走规则兜底".to_string(),
        用量: 用量::default(),
    }
}

/// 终裁主入口（完整三段，要求书版）。
///
/// 流程：① 机械前置门槛 → ② 六准圣 LLM 审验 → ③ 鸿钧终裁。
/// 无 LLM 配置或无要求书时自动降级为规则兜底。
pub fn 终裁裁决(
    要求书: &要求书,
    产物们: &[产物条目],
    耗时秒: f64,
    涉及文件: &[String],
    失败说明: Option<&str>,
    配置: Option<&模型配置>,
) -> 终裁回执 {
    终裁裁决_无名(
        &要求书.id,
        Some(要求书),
        产物们,
        耗时秒,
        涉及文件,
        失败说明,
        配置,
    )
}

/// 终裁主入口（无名版，允许无要求书——兼容旧 验收裁决 签名）。
///
/// 流程：① 机械前置门槛 → ② 六准圣 LLM 审验 → ③ 鸿钧终裁。
/// 无 LLM 配置或无要求书时自动降级为规则兜底。
pub fn 终裁裁决_无名(
    要求id: &str,
    要求书: Option<&要求书>,
    产物们: &[产物条目],
    耗时秒: f64,
    涉及文件: &[String],
    失败说明: Option<&str>,
    配置: Option<&模型配置>,
) -> 终裁回执 {
    // 白箱观测：验收阶段进入验收角色（栈顶覆盖主政的鸿钧档；无要求书时退化为空要求）。
    let _观测守卫 = 进入观测(观测角色::验收, None, Some(要求id.to_string()), None);
    // ① 机械前置门槛
    if let Some(打回) =
        super::产物校验::机械前置门槛(要求id, 产物们, 耗时秒, 失败说明, 涉及文件)
    {
        return 打回;
    }

    // ② 降级判定：无 LLM 配置或无要求书 → 规则兜底（兼容旧测试签名）
    let (要求书, 配置) = match (要求书, 配置) {
        (Some(书), Some(配)) => (书, 配),
        _ => return 规则兜底(要求id, 产物们, 耗时秒, 涉及文件),
    };

    // ③ 六准圣分维独立审验
    let (意见们, 用量1) = super::审验::六准圣审验(要求书, 产物们, 配置);

    // ③.1 六准圣意见 reducer：纯代码数据清洗（去重 + 剔残缺），
    // 让鸿钧聚焦矛盾裁决而非数据清洗。对齐 §14.20 数据清洗 reducer 应用点 3。
    let 意见们 = super::审验::准圣意见reducer(意见们);

    // ③.5 全弃权兜底：所有准圣审验失败（模型只输出 think 无 JSON 等）→ 无审验信息，
    // 直接规则兜底（避免空意见走鸿钧争议 LLM 白烧调用）。
    if 意见们.is_empty() {
        warn!(要求 = %要求书.id, "六准圣全部弃权（审验失败），回退规则兜底");
        return 规则兜底(要求id, 产物们, 耗时秒, 涉及文件);
    }

    // ④ 鸿钧终裁
    let (终裁结论, 终裁依据, 用量2) =
        match super::审验::鸿钧终裁(要求书, 产物们, &意见们, 配置) {
            Ok(t) => t,
            Err(错误) => {
                error!(要求 = %要求书.id, 错误 = %错误, "鸿钧终裁失败，回退规则兜底");
                return 规则兜底(要求id, 产物们, 耗时秒, 涉及文件);
            }
        };

    // ⑤ 累计用量 + 构造终裁回执
    let mut 用量 = 用量1;
    用量.加(&用量2);

    let 意见文本 = super::审验::综合意见文本(&意见们, &终裁结论, &终裁依据);

    info!(
        要求 = %要求书.id,
        结论 = ?终裁结论,
        准圣通过 = 意见们.iter().filter(|o| o.结论 == 验收结论::通过).count(),
        准圣总数 = 意见们.len(),
        "终裁完成"
    );

    // 事件总线（阶段 2 轻事件化）：验收裁决完成通知——可观测扩展点，
    // 监听器可挂钩审计/新审验维度/汇报，不改变既有命令式流程（对齐 dsh 事件域「验收」）。
    全局总线().通知(
        "验收/裁决",
        &mut Box::new(验收事件 {
            要求id: 要求id.to_string(),
            结论: 终裁结论.clone(),
            终裁依据: 终裁依据.clone(),
            准圣通过: 意见们.iter().filter(|o| o.结论 == 验收结论::通过).count(),
            准圣总数: 意见们.len(),
        }),
    );

    终裁回执 {
        验收: 验收回执 {
            要求id: 要求id.to_string(),
            结论: 终裁结论,
            验收意见: 意见文本,
            产物: 产物们.to_vec(),
            耗时秒,
        },
        准圣意见们: 意见们,
        终裁依据,
        用量,
    }
}

/// 验收裁决事件载荷：事件总线「验收/裁决」通知的载荷（阶段 2 轭事件化）。
/// 监听器 downcast 到本类型取裁决结果（审计/新策略/汇报挂钩用）。
#[derive(Clone, Debug)]
pub struct 验收事件 {
    pub 要求id: String,
    pub 结论: 验收结论,
    pub 终裁依据: String,
    pub 准圣通过: usize,
    pub 准圣总数: usize,
}
