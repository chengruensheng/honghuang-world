/// 化为要求：来源 + 方向 + 类别 + 验收标准 → 要求书。
/// clippy too_many_arguments：字段直传构造函数，拆分参数结构体需连带全部调用点（号令/世界运行）
/// 改造，收益低于成本，故允许。
#[allow(clippy::too_many_arguments)]
pub fn 化为要求(
    id: &str,
    来源: 要求来源,
    阶段: 阶段,
    方向: &str,
    类别: 要求类别,
    验收标准: &str,
    优先级: 优先级,
    涉及路径: Vec<String>,
) -> 要求书 {
    要求书 {
        id: id.to_string(),
        来源,
        想法id: None,
        阶段,
        方向: 方向.to_string(),
        类别,
        验收标准: 验收标准.to_string(),
        约束: 约束 {
            涉及路径,
            不允许: vec![],
            优先级,
        },
        状态: 要求状态::待领,
        确认意见: None,
        验收: None,
        版本: None,
    }
}

/// 解析想法：模型一次调用，把想法内容结构化为要求书（带项目记忆背景）。
pub fn 解析想法(
    id: &str,
    想法内容: &str,
    背景: &str,
    配置: &模型配置,
) -> Result<(要求书, 用量), String> {
    let 背景 = if 背景.is_empty() {
        "（无项目记忆）"
    } else {
        背景
    };
    // 可操作规则（§4.2 规则7）：从 细则·解读 格位读链头最新规则文本，注入提示词首行。
    // 空串不注入（格位无有效记录时不影响现有行为）。
    let 工作区 = shihai_fu::工作区::定位();
    let 存储 = shihai_fu::模型存储::打开(工作区.格位目录());
    let 规则 = shihai_fu::注入规则(&存储, "细则·解读");
    let 提示 = format!("{规则}{}", 渲染要求提审提示(背景, 想法内容));
    let (回复, 用量) = 调用模型(配置, &[对话消息::用户(提示)], moxing_fu::常规上限)?;
    let 干净 = 提取对象(&回复).map_err(|错误| format!("解析想法失败: {错误}"))?;
    let 解析: serde_json::Value =
        serde_json::from_str(&干净).map_err(|错误| format!("解析想法失败: {错误}"))?;
    let 方向 = 解析["方向"].as_str().unwrap_or("未命名").to_string();
    let 类别 = 解析["类别"].as_str().unwrap_or("功能").to_string();
    let 验收标准 = 解析["验收标准"].as_str().unwrap_or("").to_string();
    // 涉及路径 = 模型提取 + 想法文本兜底提取（设计稿 §4.2 涉及路径净化第 6 条：
    // 界主写明的路径是最高权威落点约束，无论模型是否提取都并入，防止「禁臆造→空数组→落点失控」）。
    let mut 合并 = 解析["涉及路径"]
        .as_array()
        .map(|项们| {
            项们
                .iter()
                .filter_map(|项| 项.as_str().map(|路径| 路径.to_string()))
                .collect::<Vec<_>>()
        })
        .unwrap_or_default();
    for 路径 in 兜底提取路径(想法内容) {
        if !合并.iter().any(|已有| 已有 == &路径) {
            合并.push(路径);
        }
    }
    let 涉及路径 = 净化涉及路径(合并);
    // 联动补全：命令类任务（方向含「命令」）自动并入命令接线文件，
    // 防 LLM 只捕 1 个涉及文件导致现状装配缺命令表/入口、验收误判「产物路径偏离涉及范围」（设计稿 §12 P0-2）。
    let 涉及路径 = 补命令联动路径(&方向, 涉及路径);
    info!(id, 方向 = %方向, 涉及路径数 = 涉及路径.len(), 提示词 = 用量.提示词, 缓存命中 = 用量.缓存命中, "想法已解析为要求");
    info!(id, 涉及路径 = ?涉及路径, "要求涉及路径明细（含命令联动补全）");
    Ok((
        化为要求(
            id,
            要求来源::界主,
            阶段::甲,
            &方向,
            解析类别(&类别),
            &验收标准,
            优先级::中,
            涉及路径,
        ),
        用量,
    ))
}

/// 类别字符串 → 枚举。
pub fn 解析类别(类别: &str) -> 要求类别 {
    match 类别 {
        "性能" => 要求类别::性能,
        "美观" => 要求类别::美观,
        "优化" => 要求类别::优化,
        "维护" => 要求类别::维护,
        "新能力" => 要求类别::新能力,
        "补基础" => 要求类别::补基础,
        _ => 要求类别::功能,
    }
}

/// 合法产物文件扩展名（§14.15 配置化）：从装配配置读取（`.上下文/装配.json` 的 `合法产物扩展名` 字段，
/// 默认 13 种）。数据驱动——新增文件类型改配置不改代码；涉及路径净化与兜底提取共用，防两处漂移。
fn 合法文件扩展名() -> Vec<String> {
    peizhi_fu::读装配().合法产物扩展名
}

/// 净化 LLM 返回的「涉及路径」列表：拒绝非路径/符号名/含 `..` 的越界路径。
/// 判定规则：①非空；②不含 `..`/`.` 独立段；③以 装配配置的合法产物扩展名 结尾（文件）或末段以 -园/-阁/-殿/-府 结尾，或末段以「域」结尾且含连字符（结构目录）；
/// ④首段为已知维度；⑤段名仅含汉字/字母/数字/下划线/连字符/空格/句点（句点仅用于文件名扩展名）；⑥去重。
/// 域目录命名有两种格式（呈现-域 / 基础设施 - 域），用 ends_with('域') && contains('-') 统一覆盖（2026-08-21 补）。
/// 需求-拆分-园复用同一套约束，保证子要求落点与要求化一致。
pub fn 净化涉及路径(原始: Vec<String>) -> Vec<String> {
    let 扩展名们 = 合法文件扩展名();
    let mut 已见 = std::collections::HashSet::new();
    let mut 结果 = Vec::new();
    for 项 in 原始 {
        let 路径 = 项.trim().replace('\\', "/");
        if 路径.is_empty() {
            continue;
        }
        let 段们: Vec<&str> = 路径.split('/').collect();
        if 段们.iter().any(|段| *段 == ".." || *段 == ".") {
            warn!(原始 = %项, "涉及路径含 '..' 或 '.'，已剔除");
            continue;
        }
        // 路径形态：① 合法产物文件路径（装配配置扩展名）；② 结构目录路径（末段以 -园/-阁/-殿/-府 结尾，
        // 覆盖「新建园目录」类任务的落点——2026-08-17 实测：目录路径被剔除后涉及路径空，执行者落点失控乱闯）。
        let 是产物文件 = 扩展名们.iter().any(|扩展名| 路径.ends_with(扩展名));
        let 是结构目录 = 段们.last().is_some_and(|末段| {
            末段.ends_with("-园")
                || 末段.ends_with("-阁")
                || 末段.ends_with("-殿")
                || 末段.ends_with("-府")
                || (末段.ends_with('域') && 末段.contains('-'))
        });
        if !是产物文件 && !是结构目录 {
            warn!(原始 = %项, "涉及路径非合法产物文件或结构目录，已剔除");
            continue;
        }
        let 首段 = 段们.first().copied().unwrap_or("");
        if !已知维度.contains(&首段) {
            warn!(原始 = %项, 首段, "涉及路径首段非已知维度，已剔除");
            continue;
        }
        let 段合法 = 段们.iter().all(|段| {
            !段.is_empty()
                && 段.chars().all(|字| {
                    字.is_alphanumeric()
                        || matches!(字, '_' | '-' | ' ' | '.')
                        || ('\u{4e00}'..='\u{9fff}').contains(&字)
                })
        });
        if !段合法 {
            warn!(原始 = %项, "涉及路径段名含非法字符，已剔除");
            continue;
        }
        if 已见.insert(路径.clone()) {
            结果.push(路径);
        }
    }
    结果
}

/// 命令类任务联动补全：方向含「命令」时，把命令接线文件并入涉及路径（去重）。
/// 覆盖「新命令/新文件」场景 LLM 只捕 1 个涉及文件的缺口（设计稿 §12 P0-2）。
fn 补命令联动路径(方向: &str, 涉及路径: Vec<String>) -> Vec<String> {
    if !方向.contains("命令") {
        return 涉及路径;
    }
    let mut 结果 = 涉及路径;
    for 接线 in shihai_fu::依赖图::命令接线文件 {
        if !结果.iter().any(|路径| 路径 == 接线) {
            结果.push(接线.to_string());
        }
    }
    结果
}

/// 界主路径兜底提取（设计稿 §4.2 涉及路径净化第 6 条）：
/// 机械扫描想法文本中「已知维度名 + `/` 起至 合法产物扩展名 止」的连续路径片段，
/// 无论 LLM 是否提取都并入涉及路径——界主写明的路径是最权威落点约束，不是「臆造」。
/// §14.15 配置化：扩展名表从装配配置读取（默认 .rs/.md/.json 等），覆盖文档/配置/脚本类任务落点。
fn 兜底提取路径(文本: &str) -> Vec<String> {
    let 扩展名们 = 合法文件扩展名();
    let 字符: Vec<char> = 文本.chars().collect();
    let mut 结果 = Vec::new();
    let mut 起点 = 0;
    while 起点 < 字符.len() {
        let 剩余: String = 字符[起点..].iter().collect();
        let 命中 = 已知维度.iter().find(|维度| 剩余.starts_with(**维度));
        match 命中 {
            Some(维度) => {
                let 维度长 = 维度.chars().count();
                let 紧跟斜杠 = 起点 + 维度长 < 字符.len() && 字符[起点 + 维度长] == '/';
                if 紧跟斜杠 {
                    // 字符空间内找首个 `.` + 合法扩展名（勿用 String::find——其返回字节偏移，含汉字路径会越界）。
                    let 相对 = (0..字符.len() - 起点).find(|&i| {
                        if 字符[起点 + i] != '.' {
                            return false;
                        }
                        // 从 `.` 起匹配任一扩展名（如 .md 2 字符、.rs 2 字符、.yaml 4 字符）。
                        let 剩余段: String = 字符[起点 + i..].iter().collect();
                        扩展名们
                            .iter()
                            .any(|扩展名| 剩余段.starts_with(扩展名.as_str()))
                    });
                    if let Some(相对) = 相对 {
                        // 扩展名长度：从 `.` 位置起算，取最长匹配（如 .yaml 5 字符含点）。
                        let 剩余段: String = 字符[起点 + 相对..].iter().collect();
                        let 扩展名长 = 扩展名们
                            .iter()
                            .filter(|扩展名| 剩余段.starts_with(扩展名.as_str()))
                            .map(|扩展名| 扩展名.chars().count())
                            .max()
                            .unwrap_or(3);
                        let 结束 = 起点 + 相对 + 扩展名长;
                        结果.push(
                            字符[起点..结束]
                                .iter()
                                .collect::<String>()
                                .replace('\\', "/"),
                        );
                        起点 = 结束;
                        continue;
                    }
                }
                起点 += 维度长;
            }
            None => 起点 += 1,
        }
    }
    结果
}

