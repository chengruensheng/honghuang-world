    /// §14.15 配置化：装配.json 配置自定义扩展名 → 净化放行该类型（数据驱动，改配置不改代码）。
    #[test]
    fn 净化涉及路径_装配配置自定义扩展名生效() {
        let _锁 = crate::工作区测试锁
            .lock()
            .unwrap_or_else(|毒| 毒.into_inner());
        let 根 = std::env::temp_dir().join(format!("要求化-扩展名-{}", std::process::id()));
        let 上下文 = 根.join(".上下文");
        std::fs::create_dir_all(&上下文).unwrap();
        let 装配 = serde_json::json!({
            "阶段": "乙",
            "启用扩展": [],
            "模型提供者": "http",
            "角色册路径": "",
            "合法产物扩展名": [".rs", ".md", ".vue"]
        });
        std::fs::write(上下文.join("装配.json"), 装配.to_string()).unwrap();
        std::env::set_var("WORLD_WORKSPACE_ROOT", &根);
        let 结果 = 净化涉及路径(vec!["鸿蒙/基础设施 - 域/事件总线-府/组件.vue".to_string()]);
        std::env::remove_var("WORLD_WORKSPACE_ROOT");
        let _ = std::fs::remove_dir_all(&根);
        assert!(
            结果.iter().any(|路径| 路径.ends_with(".vue")),
            "装配配置的 .vue 应放行：{结果:?}"
        );
    }
