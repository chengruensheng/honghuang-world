//! 要求 - 提审 - 模板：解析想法提示词模板与渲染。

/// 要求提审提示词模板：占位符 {背景} {想法}。
const 要求提审模板: &str = concat!(
    "项目记忆背景：\n{背景}\n\n",
    "把下面的想法结构化为一个开发要求，只输出 JSON：",
    "{\"方向\":\"一句话目标\",\"类别\":\"功能|性能|美观|优化|维护|新能力|补基础\",\"验收标准\":\"可核对的完成判据\",\"涉及路径\":[\"要改的符号名或文件相对路径，可为空\"]}\n",
    "涉及路径 只允许以下两种：1）项目记忆背景里【结构】【文件】中真实出现的相对路径（如 鸿蒙/基础设施 - 域/道术施展-府/任务-调度-殿/任务-派遣-阁/工具-循环-园/工具循环.rs）；2）背景里真实存在的符号名。严禁凭想法内容臆造不存在的殿/阁/园目录或路径；无法确定时给空数组，不要编。\n",
    "特殊规则：若想法文本中界主已显式写明某个 .rs 相对路径，该路径必须优先原样提取进 涉及路径（界主写明的路径是最权威约束，不属于臆造）。\n",
    "想法：{想法}",
);

/// 渲染要求提审提示：占位符替换。
pub fn 渲染要求提审提示(背景: &str, 想法: &str) -> String {
    要求提审模板.replace("{背景}", 背景).replace("{想法}", 想法)
}
