//! 需求 - 拆分 - 园：鸿钧主政收到想法后先做拆分决策。
//!
//! 拆分决策是 LLM 的事：模型判断该想法是「单一可交付要求」还是「多个可独立验收的小要求」，
//! 拆则产出每个子要求的方向/类别/验收标准/涉及路径。
//! 调用失败/解析失败/不可拆一律回退「不拆」（机械兜底，不阻塞投递，由主政一轮走单要求）。
//! 编排是智能体的事：拆分后的逐个串行执行由 `世界运行.rs::主政一轮` 完成（设计稿 §11.2 规则 10）。

use crate::净化涉及路径;
use moxing_fu::{对话消息, 模型配置, 精简上限, 调用模型};
use rizhi_fu::{info, warn};

/// 子要求（功能级想法拆分出的最小可独立验收单元）。
#[derive(Clone, Debug, PartialEq)]
pub struct 子要求 {
    pub 方向: String,
    pub 类别: String,
    pub 验收标准: String,
    pub 涉及路径: Vec<String>,
}

impl 子要求 {
    /// 合成子想法文本：方向 + 验收标准 + 涉及路径。
    /// 涉及路径明文写入，供 解析想法 的界主文本兜底提取并入（不依赖模型二次提取）。
    pub fn 合成文本(&self, 序号: usize) -> String {
        let mut 文本 = format!("【子要求{序号}】{}", self.方向);
        if !self.验收标准.is_empty() {
            文本.push_str(&format!("。验收标准：{}", self.验收标准));
        }
        if !self.涉及路径.is_empty() {
            文本.push_str(&format!("。涉及路径：{}", self.涉及路径.join("、")));
        }
        文本
    }
}

/// 拆分决策：不拆（单要求）或拆（多个子要求）。
#[derive(Clone, Debug, PartialEq)]
pub enum 拆分决策 {
    不拆,
    拆分(Vec<子要求>),
}

/// 上限保护：防止模型过度拆分导致串行轮数与预算失控。
pub const 最大子要求数: usize = 4;

/// 需求拆分决策：鸿钧主政先请 LLM 判断拆/不拆，拆则产出子要求清单。
/// 任何失败（调用/提取/解析/子要求为空）回退 不拆，不阻塞投递。
pub fn 需求拆分决策(想法内容: &str, 背景: &str, 配置: &模型配置) -> 拆分决策 {
    let 提示 = format!(
        "你是鸿钧主政，天层最高主政。界主投递了一个想法，你先判断它是「单一可交付要求」还是「应拆成多个可独立验收的小要求」。\n\
         判断标准：\n\
         - 单点改动、单文件落点、一次可验收 → 不拆。\n\
         - 功能级想法：涉及多文件/多园殿、跨阶段、可分步交付 → 拆成 2-4 个小要求，\n\
           每个小要求独立走「要求→设计→实现→验收→定档」全链串行执行，粒度以「一次实现能独立通过验收」为准，宁拆小步勿一锅烩。\n\
         只输出一个 JSON 对象，不要多余文字：\n\
         {{\"拆分\": true 或 false, \"子要求\": [{{\"方向\":\"…\",\"类别\":\"功能|性能|美观|优化|维护|新能力|补基础\",\"验收标准\":\"…\",\"涉及路径\":[\"鸿蒙/…/xxx.rs\"]}}]}}\n\
         不拆时 \"子要求\" 为空数组。涉及路径必须是世界真实存在的府殿阁园路径。\n\n\
         【项目记忆背景】\n{背景}\n\n\
         【界主想法】\n{想法内容}"
    );
    match 调用模型(配置, &[对话消息::用户(提示)], 精简上限) {
        Ok((回复, 用量)) => {
            let 决策 = 解析拆分决策(&回复);
            match &决策 {
                拆分决策::拆分(子要求们) => {
                    info!(
                        子要求数 = 子要求们.len(),
                        提示词 = 用量.提示词,
                        缓存命中 = 用量.缓存命中,
                        "需求拆分决策：拆分"
                    );
                    for 子 in 子要求们 {
                        info!(方向 = %子.方向, 涉及路径数 = 子.涉及路径.len(), "子要求清单");
                    }
                }
                拆分决策::不拆 => info!(
                    提示词 = 用量.提示词,
                    缓存命中 = 用量.缓存命中,
                    "需求拆分决策：不拆"
                ),
            }
            决策
        }
        Err(错误) => {
            warn!(错误 = %错误, "需求拆分决策调用失败，回退单要求");
            拆分决策::不拆
        }
    }
}

/// 解析拆分决策 JSON：围栏包裹/纯 JSON 均可；任何不合法字段回退 不拆。
/// 子要求的方向为空则跳过；全部为空/无子要求回退 不拆；超上限截断。
fn 解析拆分决策(回复: &str) -> 拆分决策 {
    let 起 = match 回复.find('{') {
        Some(起) => 起,
        None => return 拆分决策::不拆,
    };
    let 止 = match 回复.rfind('}') {
        Some(止) => 止,
        None => return 拆分决策::不拆,
    };
    if 止 <= 起 {
        return 拆分决策::不拆;
    }
    let 值: serde_json::Value = match serde_json::from_str(&回复[起..=止]) {
        Ok(值) => 值,
        Err(_) => return 拆分决策::不拆,
    };
    if !值["拆分"].as_bool().unwrap_or(false) {
        return 拆分决策::不拆;
    }
    let 项们 = match 值["子要求"].as_array() {
        Some(项们) => 项们,
        None => return 拆分决策::不拆,
    };
    let mut 结果 = Vec::new();
    for 项 in 项们 {
        let 方向 = 项["方向"].as_str().unwrap_or("").trim().to_string();
        if 方向.is_empty() {
            continue;
        }
        let 类别 = 项["类别"].as_str().unwrap_or("功能").trim().to_string();
        let 验收标准 = 项["验收标准"].as_str().unwrap_or("").trim().to_string();
        let 涉及路径: Vec<String> = 项["涉及路径"]
            .as_array()
            .map(|路径们| {
                路径们
                    .iter()
                    .filter_map(|路径| 路径.as_str().map(|路径| 路径.to_string()))
                    .collect::<Vec<_>>()
            })
            .unwrap_or_default();
        // 涉及路径过净化，防 LLM 混入非法/越界路径（与 要求化 同一套约束）。
        结果.push(子要求 {
            方向,
            类别,
            验收标准,
            涉及路径: 净化涉及路径(涉及路径),
        });
    }
    if 结果.is_empty() {
        return 拆分决策::不拆;
    }
    if 结果.len() > 最大子要求数 {
        warn!(原数 = 结果.len(), 上限 = 最大子要求数, "子要求超上限，截断");
        结果.truncate(最大子要求数);
    }
    拆分决策::拆分(结果)
}

#[cfg(test)]
mod 测试 {
    use super::{子要求, 拆分决策, 最大子要求数, 解析拆分决策};

    #[test]
    fn 不拆时子要求为空() {
        let 回复 = r#"{"拆分": false, "子要求": []}"#;
        assert_eq!(解析拆分决策(回复), 拆分决策::不拆);
    }

    #[test]
    fn 标准拆分解析() {
        let 回复 = r#"{"拆分": true, "子要求": [{"方向": "补历法单元测试", "类别": "维护", "验收标准": "cargo test 通过", "涉及路径": ["鸿蒙/基础设施 - 域/天庭治理-府/观览-查询-殿/流式-历法-园/流式历法.rs"]}, {"方向": "接入命令表", "类别": "功能", "验收标准": "命令可执行", "涉及路径": ["乾坤/呈现-域/命令操作-府/命令-解析-殿/兜底-分发-园/兜底分发.rs"]}]}"#;
        let 决策 = 解析拆分决策(回复);
        match 决策 {
            拆分决策::拆分(子要求们) => {
                assert_eq!(子要求们.len(), 2);
                assert_eq!(子要求们[0].方向, "补历法单元测试");
                assert_eq!(子要求们[0].类别, "维护");
                assert_eq!(子要求们[0].涉及路径.len(), 1);
            }
            拆分决策::不拆 => panic!("应拆分为多子要求"),
        }
    }

    #[test]
    fn 围栏包裹也能解析() {
        let 回复 = "```json\n{\"拆分\": true, \"子要求\": [{\"方向\": \"加固边界\"}]}\n```";
        match 解析拆分决策(回复) {
            拆分决策::拆分(子要求们) => assert_eq!(子要求们.len(), 1),
            拆分决策::不拆 => panic!("应容忍围栏"),
        }
    }

    #[test]
    fn 非_json或缺子要求回退不拆() {
        assert_eq!(解析拆分决策("不是JSON"), 拆分决策::不拆);
        assert_eq!(解析拆分决策(r#"{"拆分": true}"#), 拆分决策::不拆);
        assert_eq!(
            解析拆分决策(r#"{"拆分": true, "子要求": [{"类别": "功能"}]}"#),
            拆分决策::不拆,
            "方向为空应回退不拆"
        );
    }

    #[test]
    fn 子要求超上限截断() {
        let 项们 = (1..=6)
            .map(|序号| format!("{{\"方向\":\"子要求{序号}\"}}"))
            .collect::<Vec<_>>()
            .join(",");
        let 回复 = format!(r#"{{"拆分": true, "子要求": [{项们}]}}"#);
        match 解析拆分决策(&回复) {
            拆分决策::拆分(子要求们) => assert_eq!(子要求们.len(), 最大子要求数),
            拆分决策::不拆 => panic!("应截断而非回退"),
        }
    }

    #[test]
    fn 合成文本含方向验收标准与涉及路径() {
        let 子 = 子要求 {
            方向: "补历法单元测试".to_string(),
            类别: "维护".to_string(),
            验收标准: "cargo test 通过".to_string(),
            涉及路径: vec![
                "鸿蒙/基础设施 - 域/天庭治理-府/观览-查询-殿/流式-历法-园/流式历法.rs".to_string(),
            ],
        };
        let 文本 = 子.合成文本(1);
        assert!(文本.contains("子要求1"), "应含序号：{文本}");
        assert!(文本.contains("补历法单元测试"), "应含方向：{文本}");
        assert!(
            文本.contains("验收标准：cargo test 通过"),
            "应含验收标准：{文本}"
        );
        assert!(文本.contains("涉及路径：鸿蒙/"), "应含涉及路径：{文本}");
    }

    #[test]
    fn 无涉及路径时合成文本不含路径段() {
        let 子 = 子要求 {
            方向: "加固边界".to_string(),
            类别: "功能".to_string(),
            验收标准: String::new(),
            涉及路径: vec![],
        };
        let 文本 = 子.合成文本(2);
        assert!(文本.contains("子要求2"));
        assert!(!文本.contains("涉及路径"), "无路径不应拼路径段：{文本}");
        assert!(!文本.contains("验收标准"), "空验收标准不应拼段：{文本}");
    }
}
