/// 最小加法：测试空函数（实现手段词=接单）。
pub fn add(a: i64, b: i64) -> i64 {
    a + b
}

/// 调度门闭包示例：闭包内部显式调用 add(1,1)，使 1+1=2 的字面量在 git diff 中可见。
pub fn 接单门示例闭包调用() -> i64 {
    let 接单闭包 = |x: i64, y: i64| -> i64 { add(x, y) };
    接单闭包(1, 1)
}

/// 调度门入口：闭包内部显式调用 add(1,1) 作为字面量锚点。
///
/// 任务依据（要求-70）：dispatch 入口内闭包调用 add(1,1) 必须落盘 + git diff 可锚定。
/// - 入参 `命令`：预留命令字符串路由扩展位（本轮不使用）；
/// - 内嵌闭包 `接单闭包` 捕获 `add`；
/// - 闭包调用 `add(1, 1)` 字面量在源码中显式出现，便于 grep/diff 锚定「1+1=2」。
///
/// 与 `接单门示例闭包调用` 区别：本函数对外命名 `dispatch`，呼应「调度门入口」语义。
pub fn dispatch(命令: &str) -> i64 {
    let _ = 命令;
    let 接单闭包 = |x: i64, y: i64| -> i64 { add(x, y) };
    接单闭包(1, 1)
}

/// 接单门 4 层瀑布闭包：判测试覆盖（§19.4.1 + §19.4.2.2 + §19.4.2.7 P0-1+P0-2）。
///
/// 设计意图：作为 `评估接单` 的 `Option<F>` 闭包参数的真接入实现，让接单门
/// 维度 5「可验证性」从占位 `None`（用旧关键词逻辑）变真接入 4 层瀑布。
///
/// - **层 1**：路径前缀过筛（`shihai_fu::是_测试文件`，零 IO）
/// - **层 2**：依赖图缓存读取（零额外 IO，4d5e805 步骤 3 已填字段）
/// - **层 3**：LLM 现场确认（**不在热路径调用**，挪到 §19.8 批量阶段）
/// - **层 4**：反向匹配（依赖图档案中证道域路径含涉及文件基名）
///
/// 模糊情况（缓存 `未判定` + 反向未命中）保守接受 `true`——让 §19.8 名单消费
/// 阶段调 LLM 二次确认；避免误拒真实有覆盖的候选（§6.4「热路径不调 LLM」）。
///
/// 缓存字段语义（依赖图.rs 测试覆盖判定 enum）：
/// - `是测试` → 返 `true`（明确有覆盖）
/// - `不是测试` → 返 `false`（明确无覆盖，触发接单门拒）
/// - `边缘` → 返 `true`（保守接受，留给人工/批量阶段决断）
/// - `未判定` → 走层 4 反向匹配，再走兜底保守接受
///
/// 调用方（`mingling_fu::巡世驱动.rs`）传入 `&依赖图` 引用 + `&str` 路径，
/// 闭包签名 `Fn(&str) -> bool` 与 `评估接单` 的 `Option<F>` 匹配。
///
/// 依据：上下文.md §8.5 + 多智能体 §19.4.1 + §19.4.2.2 + §19.7 + §6.4 + AGENTS §16。
pub fn 测试覆盖查询(图: &依赖图, 路径串: &str) -> bool {
    // 层 1：路径前缀过筛（命中证道/验证*/测试.rs 等即返 true）
    if 是_测试文件(路径串) {
        return true;
    }
    // 路径归一（依赖图档案内统一正斜杠，热路径免 replace 的契约）
    let 正斜杠 = 路径串.replace('\\', "/");
    // 层 2：依赖图缓存读取（4d5e805 步骤 3 已填字段）
    let 档案们 = 图.查文件(&正斜杠);
    for 档案 in &档案们 {
        match 档案.测试覆盖判定 {
            测试覆盖判定::是测试 => return true,
            测试覆盖判定::不是测试 => return false,
            测试覆盖判定::边缘 => return true,
            测试覆盖判定::未判定 => {} // 模糊，走层 4 反向匹配兜底
        }
    }
    // 层 4：反向匹配（依赖图档案中证道域路径含涉及文件基名）
    if 反向匹配_证道域(图, 路径串) {
        return true;
    }
    // 模糊情况：保守接受（让 §19.8 名单消费阶段调 LLM 兜底）
    true
}

/// 层 4 反向匹配：涉及文件基名出现在依赖图档案的「证道域路径」中 → 有覆盖。
///
/// 场景：涉及路径 `鸿蒙/某府/某园/某业务.rs` 基名 `某业务`，
/// 若档案有 `证道/.../某业务测试.rs` → 命中 → 返 `true`。
///
/// 反向匹配是「不依赖测试域路径前缀也能找到测试覆盖」的关键兜底——
/// 有些业务文件的测试不在 `证道/.../某业务测试.rs` 直接对应，而是嵌入
/// `证道/.../某府验证殿/某业务验证园/某业务测试.rs`。基名命中可覆盖这类。
fn 反向匹配_证道域(图: &依赖图, 路径串: &str) -> bool {
    let 基名 = Path::new(路径串)
        .file_stem()
        .and_then(|s| s.to_str())
        .unwrap_or("");
    if 基名.is_empty() {
        return false;
    }
    for 档案 in &图.档案们 {
        if 档案.文件.starts_with("证道/") && 档案.文件.contains(基名) {
            return true;
        }
    }
    false
}

