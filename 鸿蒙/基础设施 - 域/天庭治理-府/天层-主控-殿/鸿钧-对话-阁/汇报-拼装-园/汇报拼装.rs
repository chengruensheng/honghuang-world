//! 汇报-拼装-园：把任务回执/世界状态拼成给界主看的答复文本。
//! 只拼事实（回执字段/状态字段），不编造；阶段 1 先服务「发布任务」的结果汇报。

use crate::主政回执;
use crate::类型_定义_殿::验收结论;

/// 主政回执 → 界主可读摘要（与「想法 投递」命令的结果呈现同源，供对话汇报复用）。
pub fn 摘要主政回执(回执: &主政回执) -> String {
    let 明细 = 回执
        .回执们
        .iter()
        .map(|回执| format!("{} {:?}", 回执.验收.要求id, 回执.验收.结论))
        .collect::<Vec<_>>()
        .join("；");
    let 产物数: usize = 回执.回执们.iter().map(|回执| 回执.验收.产物.len()).sum();
    let 耗时秒: f64 = 回执.回执们.iter().map(|回执| 回执.验收.耗时秒).sum();
    let 结论 = match 回执.结论 {
        验收结论::通过 => "通过",
        验收结论::打回 => "打回",
    };
    format!(
        "任务完成\n子要求：{} 个\n定档：{} 个\n结论：{}\n明细：{}\n产物：{} 件\n耗时：{:.2} 秒",
        回执.子要求数, 回执.定档数, 结论, 明细, 产物数, 耗时秒
    )
}

#[cfg(test)]
mod 测试 {
    use super::*;
    use crate::{产物条目, 终裁回执, 验收回执};

    #[test]
    fn 摘要_空回执不崩() {
        let 回执 = 主政回执 {
            结论: 验收结论::通过,
            回执们: vec![],
            子要求数: 0,
            定档数: 0,
        };
        let 文本 = 摘要主政回执(&回执);
        assert!(文本.contains("通过"));
        assert!(文本.contains("0 件"));
    }

    #[test]
    fn 摘要_带产物明细() {
        let 回执 = 主政回执 {
            结论: 验收结论::打回,
            回执们: vec![终裁回执 {
                验收: 验收回执 {
                    要求id: "要求-4".to_string(),
                    结论: 验收结论::打回,
                    验收意见: Some("编译失败".to_string()),
                    产物: vec![产物条目 {
                        路径: "a.rs".to_string(),
                        类别: "代码".to_string(),
                        字节数: 1,
                        变化类型: "新增".to_string(),
                    }],
                    耗时秒: 1.5,
                },
                准圣意见们: vec![],
                终裁依据: "编译失败，产物不可信".to_string(),
                用量: moxing_fu::用量::default(),
            }],
            子要求数: 1,
            定档数: 0,
        };
        let 文本 = 摘要主政回执(&回执);
        assert!(文本.contains("要求-4 打回"));
        assert!(文本.contains("1 件"));
        assert!(文本.contains("1.50"));
    }
}
