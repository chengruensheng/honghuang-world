//! 模板 - 生成 - 园：按类别模板生成设计方案（甲阶段用模板）。

use crate::类型_定义_殿::{拆解项, 设计方案, 要求书, 要求类别};

/// 模板设计：按类别套模板，产出设计方案 + 拆解项。
pub fn 模板设计(要求: &要求书) -> 设计方案 {
    let (设计, 工作流) = match 要求.类别 {
        要求类别::功能 => ("实现该功能，落位对应府殿阁园，写码 + 自证", "L3_program"),
        要求类别::补基础 => ("补齐基础能力，先骨架后逻辑", "L3_program"),
        要求类别::性能 => ("定位瓶颈，优化热路径", "L2_script"),
        要求类别::美观 => ("调整呈现与样式", "L2_script"),
        要求类别::维护 => ("修复问题，补测试", "L2_script"),
        要求类别::新能力 => ("新增能力，按六层规范落园", "L4_complex"),
        _ => ("优化调整", "L2_script"),
    };

    设计方案 {
        要求id: 要求.id.clone(),
        设计: format!("{设计}。验收标准：{}", 要求.验收标准),
        拆解: vec![拆解项 {
            目标: 要求.方向.clone(),
            执行层角色: vec!["duobao".to_string()],
            工作流: 工作流.to_string(),
        }],
        自评: format!("本设计通过「{设计}」满足验收标准"),
    }
}

#[cfg(test)]
mod 测试 {
    use super::*;
    use crate::类型_定义_殿::{优先级, 约束, 阶段, 要求来源, 要求状态};

    #[test]
    fn 七类模板各出方案() {
        for 类别 in [
            要求类别::功能,
            要求类别::性能,
            要求类别::美观,
            要求类别::优化,
            要求类别::维护,
            要求类别::新能力,
            要求类别::补基础,
        ] {
            let 要求 = 要求书 {
                id: "r1".to_string(),
                来源: 要求来源::界主,
                想法id: None,
                阶段: 阶段::甲,
                方向: "方向".to_string(),
                类别,
                验收标准: "判据".to_string(),
                约束: 约束 { 涉及路径: vec![], 不允许: vec![], 优先级: 优先级::中 },
                状态: 要求状态::待领,
                确认意见: None,
                验收: None,
                版本: None,
            };
            let 方案 = 模板设计(&要求);
            assert!(!方案.拆解.is_empty());
        }
    }
}
