//! 模板 - 生成 - 园：按类别模板生成设计方案（甲阶段用模板）；LLM 级设计（乙阶段）由模型主导、模板兜底。

use crate::类型_定义_殿::{拆解项, 设计方案, 要求书, 要求类别};
use moxing_fu::{调用模型, 对话消息, 模型配置, 精简上限, 常规上限};
use rizhi_fu::{info, warn};

/// 模板设计：按类别套模板，产出设计方案 + 拆解项。
pub fn 模板设计(要求: &要求书) -> 设计方案 {
    let (设计, 工作流) = match 要求.类别 {
        要求类别::功能 => ("实现该功能，落位对应府殿阁园，写码 + 自证", "L3_program"),
        要求类别::补基础 => ("补齐基础能力，先骨架后逻辑", "L3_program"),
        要求类别::性能 => ("定位瓶颈，优化热路径", "L2_script"),
        要求类别::美观 => ("调整呈现与样式", "L2_script"),
        要求类别::维护 => ("修复问题，补测试", "L2_script"),
        要求类别::新能力 => ("新增能力，按六层规范落园", "L4_complex"),
        _ => ("优化调整", "L2_script"),
    };
    info!(要求id = %要求.id, 类别 = ?要求.类别, "模板设计完成");

    设计方案 {
        要求id: 要求.id.clone(),
        设计: format!("{设计}。验收标准：{}", 要求.验收标准),
        拆解: vec![拆解项 {
            目标: 要求.方向.clone(),
            执行层角色: vec!["duobao".to_string()],
            工作流: 工作流.to_string(),
        }],
        自评: format!("本设计通过「{设计}」满足验收标准"),
    }
}

/// 模型设计（设计稿 §12 P2-9）：提示模型按 方向/类别/验收标准/涉及路径
/// 产出设计方案 JSON（设计 + 拆解 + 自评），解析失败或字段缺失回退模板设计。
pub fn 模型设计(要求: &要求书, 配置: &模型配置) -> 设计方案 {
    let 提示 = format!(
        "你是世界设计主笔。根据要求产出设计方案，只输出一个 JSON 对象，不要多余文字。\n\
         JSON 结构：{{\"设计\":\"设计思路（落位府殿阁园、先做什么后做什么、验收怎么自证）\",\
         \"拆解\":[{{\"目标\":\"子任务目标\",\"执行层角色\":[\"duobao\"],\"工作流\":\"L2_script|L3_program|L4_complex\"}}],\
         \"自评\":\"设计为何满足验收标准\"}}\n\
         硬约束：拆解不超过 3 个子任务，每个子任务必须独立可完成，涉及路径互不重叠。\n\n\
         【要求id】{id}\n【方向】{方向}\n【类别】{类别:?}\n【验收标准】{验收标准}",
        id = 要求.id,
        方向 = 要求.方向,
        类别 = 要求.类别,
        验收标准 = 要求.验收标准
    );
    match 调用模型(配置, &[对话消息::用户(提示)], 精简上限) {
        Ok((回复, 用量)) => match 解析设计方案(&要求.id, &回复) {
            Some(方案) => {
                info!(要求id = %要求.id, 拆解数 = 方案.拆解.len(), 提示词 = 用量.提示词, "LLM设计完成");
                方案
            }
            None => {
                warn!(要求id = %要求.id, 回复长度 = 回复.len(), "LLM设计解析失败，回退模板");
                模板设计(要求)
            }
        },
        Err(错误) => {
            warn!(要求id = %要求.id, 错误 = %错误, "LLM设计调用失败，回退模板");
            模板设计(要求)
        }
    }
}

/// 评审意见：一个角度对设计稿的独立评审。
struct 评审意见 {
    角度: &'static str,
    有意见: bool,
    意见: String,
}

/// 四维评审角度（设计稿 §18.3）：各审一维，独立 LLM 调用，防单人设计盲区。
const 四维角度: [(&str, &str); 4] = [
    ("老子", "核心逻辑/边界/抽象是否成立"),
    ("元始", "异常路径/错误处理是否完备"),
    ("通天", "接口/性能/并发是否合理"),
    ("后土", "数据流/状态/持久化是否一致"),
];

/// 圣人工作群评审（设计稿 §18.3）：主笔发稿 → 四维分角度评审 → 意见收敛。
/// 本质：多人分角度审设计稿，意见收敛后定稿；主笔单人设计有盲区，四维各补专业知识。
/// 收敛上限 2 轮：评审 → 有意见则综合改稿 → 再评，直到全部一致收敛或达上限。
pub fn 圣人工作群设计(要求: &要求书, 配置: &模型配置) -> 设计方案 {
    let mut 稿 = 模型设计(要求, 配置);
    for 轮 in 0..2 {
        let 意见们 = 四维评审(要求, &稿, 配置);
        let 有意见们: Vec<&评审意见> = 意见们.iter().filter(|意见| 意见.有意见).collect();
        if 有意见们.is_empty() {
            info!(要求id = %要求.id, 轮, "设计评审全部意见一致收敛");
            return 稿;
        }
        let 意见文本 = 有意见们
            .iter()
            .map(|意见| format!("【{}】{}", 意见.角度, 意见.意见))
            .collect::<Vec<_>>()
            .join("\n");
        info!(要求id = %要求.id, 轮, 意见数 = 有意见们.len(), "设计评审有意见，综合改稿");
        稿 = 改稿(要求, &稿, &意见文本, 配置);
    }
    warn!(要求id = %要求.id, "设计评审达上限未完全收敛，采用最新稿");
    稿
}

/// 四维分角度评审：每个角度独立一次 LLM 调用，产出评审意见。
fn 四维评审(要求: &要求书, 方案: &设计方案, 配置: &模型配置) -> Vec<评审意见> {
    四维角度
        .iter()
        .map(|(角度, 关注点)| {
            let 提示 = format!(
                "你是{角度}（世界设计评审）。从「{关注点}」角度评审下列设计方案，\
                 只输出 JSON 对象，不要多余文字。\n\
                 JSON 结构：{{\"有意见\":true|false,\"意见\":\"具体意见（无意见则空）\"}}\n\n\
                 【方向】{方向}\n【设计】{设计}\n【拆解】{拆解:?}",
                角度 = 角度,
                关注点 = 关注点,
                方向 = 要求.方向,
                设计 = 方案.设计,
                拆解 = 方案.拆解
            );
            match 调用模型(配置, &[对话消息::用户(提示)], 精简上限) {
                Ok((回复, _)) => 解析评审意见(角度, &回复),
                Err(_) => 评审意见 { 角度, 有意见: false, 意见: String::new() },
            }
        })
        .collect()
}

/// 综合意见改稿：把各角度评审意见注入主笔，重新出稿；失败回退现稿。
fn 改稿(要求: &要求书, 现稿: &设计方案, 意见文本: &str, 配置: &模型配置) -> 设计方案 {
    let 提示 = format!(
        "你是世界设计主笔。根据评审意见修改设计方案，只输出一个 JSON 对象，不要多余文字。\n\
         JSON 结构：{{\"设计\":\"设计思路\",\"拆解\":[{{\"目标\":\"子任务目标\",\"执行层角色\":[\"duobao\"],\"工作流\":\"L2_script|L3_program|L4_complex\"}}],\"自评\":\"...\"}}\n\
         硬约束：拆解不超过 3 个子任务，每个子任务必须独立可完成，涉及路径互不重叠。\n\n\
         【方向】{方向}\n【现稿】{设计}\n【拆解】{拆解:?}\n【评审意见】\n{意见}",
        方向 = 要求.方向,
        设计 = 现稿.设计,
        拆解 = 现稿.拆解,
        意见 = 意见文本
    );
    match 调用模型(配置, &[对话消息::用户(提示)], 常规上限) {
        Ok((回复, _)) => 解析设计方案(&要求.id, &回复).unwrap_or_else(|| 现稿.clone()),
        Err(_) => 现稿.clone(),
    }
}

/// 解析评审意见 JSON；解析失败或缺字段按「无意见」处理（不阻断收敛）。
fn 解析评审意见(角度: &'static str, 回复: &str) -> 评审意见 {
    let (起, 止) = match (回复.find('{'), 回复.rfind('}')) {
        (Some(起), Some(止)) if 止 > 起 => (起, 止),
        _ => return 评审意见 { 角度, 有意见: false, 意见: String::new() },
    };
    let 值: serde_json::Value = match serde_json::from_str(&回复[起..=止]) {
        Ok(值) => 值,
        Err(_) => return 评审意见 { 角度, 有意见: false, 意见: String::new() },
    };
    let 有意见 = 值["有意见"].as_bool().unwrap_or(false);
    let 意见 = 值["意见"].as_str().unwrap_or("").trim().to_string();
    // 声明有意见但未给具体意见，视为无意见（避免空意见触发无效改稿）。
    if 有意见 && 意见.is_empty() {
        return 评审意见 { 角度, 有意见: false, 意见: String::new() };
    }
    评审意见 { 角度, 有意见, 意见 }
}

/// 从 LLM 回复提取设计方案 JSON 并校验字段；任一缺失即 None（回退模板）。
fn 解析设计方案(要求id: &str, 回复: &str) -> Option<设计方案> {
    let 起 = 回复.find('{')?;
    let 止 = 回复.rfind('}')?;
    if 止 <= 起 {
        return None;
    }
    let 值: serde_json::Value = serde_json::from_str(&回复[起..=止]).ok()?;
    let 设计 = 值["设计"].as_str()?.trim().to_string();
    let 自评 = 值["自评"].as_str().unwrap_or("").trim().to_string();
    let mut 拆解 = Vec::new();
    for 项 in 值["拆解"].as_array()? {
        let 目标 = 项["目标"].as_str()?.trim().to_string();
        let 工作流 = 项["工作流"].as_str().unwrap_or("L2_script").trim().to_string();
        拆解.push(拆解项 {
            目标,
            执行层角色: vec!["duobao".to_string()],
            工作流,
        });
    }
    // 硬约束：拆解数上限 3（提示词软约束 + 此处硬截断，防过度拆分致执行时间爆炸）。
    拆解.truncate(3);
    if 设计.is_empty() || 拆解.is_empty() {
        return None;
    }
    Some(设计方案 {
        要求id: 要求id.to_string(),
        设计,
        拆解,
        自评,
    })
}

#[cfg(test)]
mod 测试 {
    use super::{解析设计方案, 解析评审意见};

    #[test]
    fn 解析评审意见_有意见() {
        let 意见 = 解析评审意见("老子", r#"{"有意见":true,"意见":"拆解粒度太粗"}"#);
        assert!(意见.有意见);
        assert_eq!(意见.意见, "拆解粒度太粗");
    }

    #[test]
    fn 解析评审意见_无意见或空意见或非JSON按无意见() {
        // 明确无意见。
        let 无 = 解析评审意见("元始", r#"{"有意见":false,"意见":""}"#);
        assert!(!无.有意见);
        // 声明有意见但空意见 → 按无意见（避免空意见触发无效改稿）。
        let 空 = 解析评审意见("通天", r#"{"有意见":true,"意见":""}"#);
        assert!(!空.有意见);
        // 非 JSON → 按无意见（不阻断收敛）。
        let 乱 = 解析评审意见("后土", "只有一句话");
        assert!(!乱.有意见);
    }

    #[test]
    fn 解析标准设计方案() {
        let 回复 = r#"{"设计":"落位天庭治理-府，先声明后派发","拆解":[{"目标":"加字段","执行层角色":["duobao"],"工作流":"L3_program"}],"自评":"满足验收"}"#;
        let 方案 = 解析设计方案("要求-1", 回复).expect("应解析成功");
        assert_eq!(方案.要求id, "要求-1");
        assert_eq!(方案.拆解.len(), 1);
        assert_eq!(方案.拆解[0].工作流, "L3_program");
    }

    #[test]
    fn 围栏包裹的回复也能解析() {
        let 回复 = "```json\n{\"设计\":\"先读后写\",\"拆解\":[{\"目标\":\"读现状\"}],\"自评\":\"ok\"}\n```";
        let 方案 = 解析设计方案("要求-2", 回复).expect("应容忍围栏");
        assert_eq!(方案.设计, "先读后写");
    }

    #[test]
    fn 缺拆解或非JSON回退None() {
        assert!(解析设计方案("要求-3", "设计只有一句话").is_none(), "非 JSON 应 None");
        assert!(解析设计方案("要求-4", "{\"设计\":\"x\"}").is_none(), "缺拆解应 None");
    }

    #[test]
    fn 解析设计方案_拆解数超3截断() {
        let 回复 = r#"{"设计":"x","拆解":[{"目标":"1"},{"目标":"2"},{"目标":"3"},{"目标":"4"},{"目标":"5"}],"自评":"ok"}"#;
        let 方案 = 解析设计方案("要求-5", 回复).expect("应解析成功");
        assert_eq!(方案.拆解.len(), 3, "拆解数应硬截断到 3，防过度拆分");
    }
}
