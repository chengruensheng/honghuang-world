//! 派发 - 落单 - 园：把拆解项派发为执行任务，落单道术施展-府执行。

use crate::类型_定义_殿::{拆解项, 设计方案};
use daoshu_fu::{执行任务, 工作流级别};

/// 把拆解项转成道术施展-府的执行任务。
pub fn 转执行任务(项: &拆解项) -> 执行任务 {
    执行任务 {
        目标: 项.目标.clone(),
        工作流: 解析工作流(&项.工作流),
        角色们: 项.执行层角色.clone(),
    }
}

/// 把设计方案拆解成执行任务清单。
pub fn 拆解为任务(方案: &设计方案) -> Vec<执行任务> {
    方案.拆解.iter().map(转执行任务).collect()
}

/// 工作流标识 → 枚举。
pub fn 解析工作流(标识: &str) -> 工作流级别 {
    match 标识 {
        "L1_qa" => 工作流级别::问答,
        "L2_script" => 工作流级别::脚本,
        "L3_program" => 工作流级别::程序,
        "L4_complex" => 工作流级别::复杂,
        _ => 工作流级别::脚本,
    }
}

#[cfg(test)]
mod 测试 {
    use super::*;

    #[test]
    fn 拆解为任务_测试() {
        let 方案 = 设计方案 {
            要求id: "r1".to_string(),
            设计: "设计".to_string(),
            拆解: vec![拆解项 {
                目标: "写个函数".to_string(),
                执行层角色: vec!["duobao".to_string()],
                工作流: "L2_script".to_string(),
            }],
            自评: "自评".to_string(),
        };
        let 任务们 = 拆解为任务(&方案);
        assert_eq!(任务们.len(), 1);
        assert_eq!(任务们[0].目标, "写个函数");
        assert_eq!(任务们[0].工作流, 工作流级别::脚本);
    }
}
