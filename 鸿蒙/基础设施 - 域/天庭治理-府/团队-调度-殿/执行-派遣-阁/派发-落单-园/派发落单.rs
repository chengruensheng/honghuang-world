//! 派发 - 落单 - 园：把拆解项派发为执行任务，落单道术施展-府执行。

use crate::类型_定义_殿::{拆解项, 设计方案};
use daoshu_fu::{工作流级别, 执行任务};
use rizhi_fu::debug;

/// 把拆解项转成道术施展-府的执行任务。
pub fn 转执行任务(项: &拆解项) -> 执行任务 {
    执行任务 {
        目标: 项.目标.clone(),
        工作流: 解析工作流(&项.工作流),
        角色们: 项.执行层角色.clone(),
    }
}

/// 把设计方案拆解成执行任务清单。
pub fn 拆解为任务(方案: &设计方案) -> Vec<执行任务> {
    let 任务们 = 方案.拆解.iter().map(转执行任务).collect::<Vec<_>>();
    debug!(任务数 = 任务们.len(), "方案已拆解为任务");
    任务们
}

/// 工作流标识 → 枚举。
pub fn 解析工作流(标识: &str) -> 工作流级别 {
    let 级别 = match 标识 {
        "L1_qa" => 工作流级别::问答,
        "L2_script" => 工作流级别::脚本,
        "L3_program" => 工作流级别::程序,
        "L4_complex" => 工作流级别::复杂,
        _ => 工作流级别::脚本,
    };
    debug!(标识 = %标识, 级别 = ?级别, "工作流已解析");
    级别
}
