/// 落点护栏：涉及路径为空且非审验/核查类 → 拒绝放行（防模型乱闯烧预算）。
/// 审验/核查类任务（审验/核对/检查/验证/达标/核查 措辞）允许无路径——交付物是结论而非文件。
fn 落点护栏(方向: &str, 涉及路径: &[String]) -> Result<(), String> {
    let 是审验类 = ["审验", "核对", "检查", "验证", "达标", "核查"]
        .iter()
        .any(|词| 方向.contains(词));
    if 涉及路径.is_empty() && !是审验类 {
        return Err(
            "涉及路径为空：任务落点不明。请在想法中写明涉及路径（文件路径或 园/阁/殿 目录），如「乾坤/呈现-域/命令操作-府/观览-查询-殿/世界-观览-阁/流式-时刻-园/流式时刻.rs」。审验/核查类任务（只查不改）可免路径。"
                .to_string(),
        );
    }
    Ok(())
}

/// 追加要求到要求.jsonl（首次入池：要求由「解析想法」产出，状态机起点 = 待领）。
/// 落盘队列无原 id 追加接口：读全部 → 追加新项 → 写临时文件 → 原子改名（防半写损坏）。
/// 持进程级排他锁贯穿读改写（2026-08-17 轮8 体检：守护回填与界主登记并发会互相覆盖）。
fn 追加要求(要求: &要求书) -> Result<(), String> {
    let 队列路径 = 状态目录().join("要求.jsonl");
    let (mut 项们, 锁) = 读改写队列::<要求书>(&队列路径)?;
    // 防止同 id 重复追加（重入运行一轮 / 想法被多次投递）：已存在则覆盖旧状态，不重复入队。
    let mut 已存在 = false;
    for 项 in 项们.iter_mut() {
        if 项.id == 要求.id {
            *项 = 要求.clone();
            已存在 = true;
            break;
        }
    }
    if !已存在 {
        项们.push(要求.clone());
    }
    持久化要求们(&队列路径, &项们)?;
    drop(锁);
    // 事件流：要求入池（append-only 事实源）。
    let 流 = shihai_fu::事件流::在工作区(&shihai_fu::工作区::定位());
    let _ = 流.追加事件(shihai_fu::事件类型::要求入池, serde_json::json!({
        "要求id": 要求.id,
        "方向": 要求.方向,
        "状态": format!("{:?}", 要求.状态),
        "已存在": 已存在,
    }));
    info!(要求id = %要求.id, 状态 = ?要求.状态, 已存在, "要求已入池");
    Ok(())
}

/// 下一个要求序号：读要求.jsonl 现有最大序号 +1（全局递增，防并发任务线 id 撞车；设计稿 §1.5.5 拍板 7）。
fn 下一个要求序号() -> Result<u64, String> {
    let 队列 = crate::落盘队列::<要求书>::打开(状态目录().join("要求.jsonl"));
    let 全部 = 队列.读全部().map_err(|错误| format!("读要求队列失败: {错误}"))?;
    let 最大 = 全部
        .iter()
        .filter_map(|要求| 要求.id.strip_prefix("要求-").and_then(|尾| 尾.parse::<u64>().ok()))
        .max()
        .unwrap_or(0);
    Ok(最大 + 1)
}

/// 持进程级排他锁读队列文件（复合「读→改→写」用：锁贯穿到调用方持久化后释放）。
/// 返回 (全部项, 排他锁)；调用方改完项们后调 持久化XX们 再 drop 锁（勿在持锁期间调队列方法防重入死锁）。
fn 读改写队列<T: serde::Serialize + serde::de::DeserializeOwned>(路径: &std::path::Path) -> Result<(Vec<T>, crate::排他锁), String> {
    let 队列 = crate::落盘队列::<T>::打开(路径);
    let 锁 = 队列.排他().map_err(|错误| format!("拿队列排他锁失败: {错误}"))?;
    let 内容 = std::fs::read_to_string(路径).map_err(|错误| format!("读队列失败: {错误}"))?;
    let 项们 = 内容
        .lines()
        .filter(|行| !行.trim().is_empty())
        .map(|行| serde_json::from_str::<T>(行).map_err(|错误| format!("解析队列项失败: {错误}")))
        .collect::<Result<Vec<T>, String>>()?;
    Ok((项们, 锁))
}

/// 推进要求状态机：按要求 id 找到目标 → 校验迁移合法 → 改状态 → 原子落盘。
/// 校验失败打 warn 不阻断（甲阶段自动推进；非法迁移以现状为准）。
fn 推进要求状态(要求id: &str, 目标: 要求状态) -> Result<(), String> {
    let 队列路径 = 状态目录().join("要求.jsonl");
    let (mut 项们, 锁) = 读改写队列::<要求书>(&队列路径)?;
    let mut 命中 = false;
    for 项 in 项们.iter_mut() {
        if 项.id == 要求id {
            // 非法迁移告警但不阻断（甲阶段流水线自动推进），保持状态机迁移可视。
            if !crate::合法迁移(&项.状态).contains(&目标) && 项.状态 != 目标 {
                warn!(要求id, 当前 = ?项.状态, 目标 = ?目标, "状态机非法迁移，仍落盘");
            }
            项.状态 = 目标.clone();
            命中 = true;
            break;
        }
    }
    if !命中 {
        warn!(要求id, 目标 = ?目标, "推进要求状态未命中（要求未持久化）");
        return Ok(());
    }
    持久化要求们(&队列路径, &项们)?;
    drop(锁);
    // 事件流：要求状态推进（append-only 事实源）。
    let 流 = shihai_fu::事件流::在工作区(&shihai_fu::工作区::定位());
    let _ = 流.追加事件(shihai_fu::事件类型::要求状态推进, serde_json::json!({
        "要求id": 要求id,
        "状态": format!("{:?}", 目标),
    }));
    info!(要求id, 状态 = ?目标, "要求状态已推进");
    Ok(())
}

/// 要求列表原子落盘：写临时文件再 rename，避免半写损坏 jsonl。
fn 持久化要求们(队列路径: &std::path::Path, 项们: &[要求书]) -> Result<(), String> {
    let mut 行们 = Vec::with_capacity(项们.len());
    for 项 in 项们 {
        let 行 = serde_json::to_string(项).map_err(|错误| format!("序列化要求失败: {错误}"))?;
        行们.push(行);
    }
    let 内容 = if 行们.is_empty() { String::new() } else { format!("{}\n", 行们.join("\n")) };
    let 临时路径 = 队列路径.with_extension("jsonl.tmp");
    std::fs::write(&临时路径, &内容).map_err(|错误| format!("写临时文件失败: {错误}"))?;
    std::fs::rename(&临时路径, 队列路径).map_err(|错误| format!("原子改名失败: {错误}"))?;
    Ok(())
}

/// 主政回执：主政一轮（想法级）的汇总结果。
pub struct 主政回执 {
    /// 想法级结论：全部子要求通过 → 通过；任一打回/失败 → 打回。
    pub 结论: 验收结论,
    /// 每个子要求/单要求的完整终裁回执（供验收.jsonl 落盘明细）。
    pub 回执们: Vec<终裁回执>,
    /// 子要求数（不拆时为 1）。
    pub 子要求数: usize,
    /// 定档数（验收通过且已定档的子要求数）。
    pub 定档数: usize,
}

/// 主政一轮：鸿钧主政编排入口。
/// 先请 LLM 做需求拆分决策（设计稿 §11.2 规则 10：拆分决策是 LLM 的事、编排是智能体的事），
/// 不拆走原单要求；拆则逐个子要求串行走全链，每个子要求独立验收/定档/打回撤销，
/// 打回不拖累其余子要求。想法级结论聚合：全部通过 → 通过；任一打回/失败 → 打回。
/// 要求 id 全局递增（设计稿 §1.5.5 拍板 7：多任务线并发的追溯前提）。
pub fn 主政一轮(
    想法: &想法,
    配置: &模型配置,
    存储: &shihai_fu::模型存储,
    调度: &任务调度,
) -> Result<主政回执, String> {
    let 起始序号 = 下一个要求序号()?;
    let 背景 = shihai_fu::元数据层化(存储, "多宝", &shihai_fu::全部格位(), 3_000).unwrap_or_default();
    // 事件流：想法投递（append-only 事实源，想法级一条）。
    let 流 = shihai_fu::事件流::在工作区(&shihai_fu::工作区::定位());
    let _ = 流.追加事件(shihai_fu::事件类型::想法投递, serde_json::json!({
        "想法id": 想法.id,
        "内容": 想法.内容,
    }));
    let 决策 = crate::需求拆分决策(&想法.内容, &背景, 配置);
    match 决策 {
        crate::拆分决策::不拆 => {
            let 要求id = format!("要求-{起始序号}");
            let 回执 = 运行一轮(想法, &要求id, 配置, 存储, 调度)?;
            let 定档数 = if 回执.验收.结论 == 验收结论::通过 { 1 } else { 0 };
            info!(要求id = %回执.验收.要求id, 结论 = ?回执.验收.结论, "主政一轮完成（单要求）");
            Ok(主政回执 { 结论: 回执.验收.结论.clone(), 回执们: vec![回执], 子要求数: 1, 定档数 })
        }
        crate::拆分决策::拆分(子要求们) => {
            let 数 = 子要求们.len();
            let mut 回执们 = Vec::with_capacity(数);
            let mut 定档数 = 0usize;
            for (序号, 子) in 子要求们.iter().enumerate() {
                let 子想法 = 想法 {
                    id: format!("{}-子{}", 想法.id, 序号 + 1),
                    内容: 子.合成文本(序号 + 1),
                    ..想法.clone()
                };
                let 要求id = format!("要求-{}", 起始序号 + 序号 as u64);
                match 运行一轮(&子想法, &要求id, 配置, 存储, 调度) {
                    Ok(回执) => {
                        if 回执.验收.结论 == 验收结论::通过 {
                            定档数 += 1;
                        }
                        回执们.push(回执);
                    }
                    // 子要求执行失败：不阻断后续子要求；想法级记为打回，并落一条失败回执供追溯。
                    Err(错误) => {
                        warn!(要求id = %要求id, 错误 = %错误, "子要求执行失败，想法级记为打回");
                        回执们.push(终裁回执 {
                            验收: 验收回执 {
                                要求id: 要求id.clone(),
                                结论: 验收结论::打回,
                                验收意见: Some(format!("子要求执行失败：{错误}")),
                                产物: vec![],
                                耗时秒: 0.0,
                            },
                            准圣意见们: vec![],
                            终裁依据: format!("执行失败：{错误}"),
                            用量: moxing_fu::用量::default(),
                        });
                    }
                }
            }
            let 结论 = if 定档数 == 数 { 验收结论::通过 } else { 验收结论::打回 };
            info!(子要求数 = 数, 定档数, 结论 = ?结论, "主政一轮完成（拆分）");
            Ok(主政回执 { 结论, 回执们, 子要求数: 数, 定档数 })
        }
    }
}

/// 运行一轮：把一个想法走完「要求 → 设计 → 实现 → 验收 → 定档」。
/// 返回完整终裁回执（含六准圣意见与鸿钧终裁依据），供验收.jsonl 落盘明细。
pub fn 运行一轮(
    想法: &想法,
    要求id: &str,
    配置: &模型配置,
    存储: &shihai_fu::模型存储,
    调度: &任务调度,
) -> Result<终裁回执, String> {
    // 元数据层化初始背景（设计稿 §4.2 规则3 第 1 件）：首屏只拼最前+最后档（首因+近因），
    // 按 3000 字符预算（与 Python 模拟最优参数一致）；中间档不直接喂，在首屏末尾注脚列出名字供模型按需调用 读格位 展开。
    // 较原 100k 字符全量拼装：节省约 97% 首屏 token，且让模型养成"按需展开"的习惯。
    let 背景 = shihai_fu::元数据层化(存储, "多宝", &shihai_fu::全部格位(), 3_000).unwrap_or_default();
    let 工作区 = shihai_fu::工作区::定位();
    let mut 图 = shihai_fu::依赖图::加载自工作区(&工作区).unwrap_or_default();
    // 人类格位临时代偿（设计稿 §4.2 规则5）：来源=人类的格位（初心/铁律/标准/架构/细则等）
    // 在人类未录时，用 LLM 探索项目生成临时内容落格位，让首屏投影携带真实项目通则。
    // 放在背景投影之后：本次已按旧空摘要投影，任务执行期间模型可用 读格位 展开新内容，
    // 下一次任务首屏即带全新内容（临时代偿失败仅记警告，不阻断主流程）。
    if let Err(说明) = shihai_fu::临时代偿(存储, 配置, 工作区.根路径(), &图) {
        warn!(说明 = %说明, "人类格位临时代偿失败（继续执行）");
    }
    // 提审背景补全结构树：府级清单不足以定位目标文件，把府→殿→阁→园 全树喂给要求提审，
    // 让「涉及路径」能解析出真实存在的目标文件路径（否则现状装配缺目标文件，执行者只能瞎探索）。
    let 全树 = 图.下探(&[]);
    let 提审背景 = if 全树.is_empty() {
        背景.clone()
    } else {
        format!("{背景}\n\n【结构树（府→殿→阁→园 全量）】\n{全树}")
    };
    let (要求, 解析用量) = crate::解析想法(要求id, &想法.内容, &提审背景, 配置)?;
    let mut 总用量 = 解析用量;
    // 落点护栏：涉及路径为空且非审验/核查类 → 拒绝放行（防模型乱闯烧预算）。
    // 2026-08-17 实测：补测试任务因涉及路径空，模型 19 轮绕圈烧 53 万 token 后失败。
    if let Err(错误) = 落点护栏(&要求.方向, &要求.约束.涉及路径) {
        warn!(要求id = %要求.id, 方向 = %要求.方向, "落点护栏拒绝放行");
        return Err(错误);
    }
    // 状态机起点：待领 → 立刻入池到要求.jsonl，让「事项列表 要求」能实时看到该要求。
    let 想法id = Some(想法.id.clone());
    let mut 入池要求 = 要求.clone();
    入池要求.想法id = 想法id;
    入池要求.状态 = 要求状态::待领;
    if let Err(错误) = 追加要求(&入池要求) {
        error!(要求id = %入池要求.id, "要求入池失败：{错误}");
        return Err(format!("要求入池失败：{错误}"));
    }

    // 依赖图滞后防御：若涉及路径对应文件全是本轮新建的（旧依赖图档案不含），先扫一次重建再查相关文件。
    // 重建后图替换旧图，下游「查相关文件 / 补全同阁 / 下探 / 查文件」全部走新图，验收裁决不再误判「产物路径偏离涉及范围」。
    // 用「查涉及文件」（精确匹配涉及路径，无兜底）判空：避免「查相关文件」兜底接线文件干扰判断。
    // 只对含 .rs 的涉及路径触发扫描——结构目录路径（新建园/阁落点）依赖图不含，触发全量扫描会卡数分钟（2026-08-17 实测）。
    let 精确 = 图.查涉及文件(&要求.约束.涉及路径);
    let 有rs路径 = 要求.约束.涉及路径.iter().any(|路径| 路径.ends_with(".rs"));
    if 精确.is_empty() && 有rs路径 && !要求.约束.涉及路径.is_empty() {
        info!("涉及路径在依赖图中无匹配，触发代码扫描重建依赖图");
        if let Err(说明) = shihai_fu::扫描(存储, 工作区.根路径()) {
            warn!(说明 = %说明, "依赖图重建失败，继续用旧图");
        }
        图 = shihai_fu::依赖图::加载自工作区(&工作区).unwrap_or_default();
    }

    // 设计上呈：分级设计（设计稿 §1.5.5 拍板 2：简单任务单轮商讨 / 复杂任务圣人工作群多轮商讨），模板兜底。
    let 方案 = crate::分级设计(&要求, 配置);
    // 事件流：设计上呈（append-only 事实源）。
    let 流 = shihai_fu::事件流::在工作区(&工作区);
    let _ = 流.追加事件(shihai_fu::事件类型::设计上呈, serde_json::json!({
        "要求id": 要求.id,
        "拆解数": 方案.拆解.len(),
    }));
    // 节点汇报（生产化 1.1）：设计完成 → 鸿钧落一条对话记录（界主「对话 历史」可见）。
    crate::落对话记录(
        "鸿钧",
        &format!("任务汇报：要求 {} 设计完成（圣人商讨已收敛，拆解 {} 项，即将开始实现）", 要求.id, 方案.拆解.len()),
        &["界主".to_string(), "鸿钧".to_string()],
    );

    // 状态机推进：待领 → 设计中（设计方案已构造，机械校验通过前不进入待确认）。
    if let Err(错误) = 推进要求状态(&要求.id, 要求状态::设计中) {
        warn!(要求id = %要求.id, 错误 = %错误, "推进「设计中」失败");
    }

    if crate::确认设计(&方案) == 验收结论::打回 {
        return Err("设计被打回".to_string());
    }

    // 状态机推进：设计中 → 待确认 → 已确认（甲阶段流水线：设计自动确认，无人工确认节点）。
    if let Err(错误) = 推进要求状态(&要求.id, 要求状态::待确认) {
        warn!(要求id = %要求.id, 错误 = %错误, "推进「待确认」失败");
    }
    if let Err(错误) = 推进要求状态(&要求.id, 要求状态::已确认) {
        warn!(要求id = %要求.id, 错误 = %错误, "推进「已确认」失败");
    }
    if let Err(错误) = 推进要求状态(&要求.id, 要求状态::待实现) {
        warn!(要求id = %要求.id, 错误 = %错误, "推进「待实现」失败");
    }

    // 依赖图精确读现状：涉及路径 → 波及文件（匹配空时兜底命令接线文件）→ 只读这些。
    let 相关文件 = 图.查相关文件(&要求.约束.涉及路径);
    // 同阁补全：目标文件所在阁的兄弟园一并纳入（如 工具循环.rs ↔ 执行提示.rs ↔ 派发落单.rs），
    // 现状缺兄弟文件是执行者反复探索、不收敛的主因之一。
    let 相关文件 = 图.补全同阁(&相关文件);
    let 根 = 工作区.根路径();
    // P2：结构按需下探，把殿/阁/园层级补全喂给执行者；涉及路径匹配府，匹配不到兜底全府树。
    let 结构下探 = 图.下探(&要求.约束.涉及路径);
    info!(涉及路径数 = 要求.约束.涉及路径.len(), 相关文件数 = 相关文件.len(), 结构下探长度 = 结构下探.len(), "现状已备");
    info!(涉及路径 = ?要求.约束.涉及路径, 相关文件 = ?相关文件, "现状装配明细");
    let mut 现状 = String::new();
    let mut 已用字符 = 0usize;
    if !结构下探.is_empty() {
        现状.push_str("【结构下探（府→殿→阁→园）】\n");
        现状.push_str(&结构下探);
        现状.push_str("\n\n");
        已用字符 += 结构下探.chars().count();
    }
    for 文件 in &相关文件 {
        // 五层信息：文件层给签名清单摘要（复用 符号档案.签名），符号层给完整定义体（M4 配方，防签名幻觉）。
        // 符号数超阈值时只给摘要，完整定义提示用 读文件 工具按需读取——避免超大文件全文撑爆上下文。
        // 涉及路径内的文件已在现状给出完整内容：明确标注禁止再读，压缩探索轮数（实测 16 轮中探索占 10 轮）。
        let 是涉及 = 要求.约束.涉及路径.iter().any(|路径| {
            文件 == 路径
                || 文件.starts_with(&format!("{路径}/"))
                || 文件.starts_with(&format!("{路径}\\"))
        });
        let 禁止再读 = if 是涉及 { "（已在现状给出，禁止再用 读文件 读取）" } else { "" };
        let 档案们 = 图.查文件(文件);
        let 摘要们: Vec<&str> = 档案们
            .iter()
            .filter(|档案| !档案.签名.is_empty())
            .map(|档案| 档案.签名.as_str())
            .collect();
        let 定义们: Vec<String> = 档案们
            .iter()
            .filter(|档案| !档案.代码.is_empty())
            .map(|档案| 档案.代码.clone())
            .collect();
        if 定义们.is_empty() && 摘要们.is_empty() {
            // 符号未入库（扫描缺漏）时兜底读全文。
            let 绝对 = 根.join(文件);
            match 读文件(绝对.to_str().unwrap_or("")) {
                Ok(内容) => 现状.push_str(&format!("【文件：{文件}】{禁止再读}\n{内容}\n\n")),
                Err(_) => 现状.push_str(&format!("【文件：{文件}】{禁止再读}\n（读取失败或不存在）\n\n")),
            }
            continue;
        }
        let 定义字符: usize = 定义们.join("\n\n").chars().count();
        // 现状总量预算：涉及路径内文件（禁止再读，不给定义模型没法写）永远给完整定义；
        // 其余文件在总预算内给定义，超限只给签名清单 + 按需读提示。
        let 超限 = 已用字符 + 定义字符 > 现状_预算_字符;
        let 给定义 = 摘要们.len() <= 摘要阈值 && (是涉及 || !超限);
        现状.push_str(&format!("【文件：{文件}】{禁止再读}符号清单（{} 个）：\n{}\n", 摘要们.len(), 摘要们.join("\n")));
        已用字符 += 摘要们.join("\n").chars().count();
        if 给定义 {
            现状.push_str(&format!("目标符号完整定义：\n{}\n\n", 定义们.join("\n\n")));
            已用字符 += 定义字符;
        } else {
            // 超限或符号过多：只给签名，完整定义提示按需读（不标禁止再读，模型可自行读取）。
            现状.push_str(&format!(
                "该文件符号较多或现状预算受限，目标符号之外的完整定义请用 读文件 工具读取「{文件}」再落盘。\n\n"
            ));
        }
    }
    // 教训注入：上轮失败经验（地道归因写入）跨轮复用——本轮执行前垫进现状，边际文本只对症困难任务。
    if let Ok(教训) = shihai_fu::注入教训(存储, 3) {
        if !教训.is_empty() {
            现状.push_str(&教训);
        }
    }
    // 图谱契约投影（设计稿 §4.2 规则6）：库根导出签名（实现层知道 打开存储/状态目录 在哪）+ 
    // 核心类型契约（记录/版本记录 定义）+ 测试样例参照（照抄项目既有 #[cfg(test)] 惯例）。
    // 治愈「实现层凭记忆写签名/自造测试结构」的编译失败类（比对拼实测四类错误）。
    let 图谱契约 = 图.查库根导出(&要求.约束.涉及路径);
    let 测试样例 = 图.查测试样例(&要求.约束.涉及路径);
    if !图谱契约.is_empty() || !测试样例.is_empty() {
        现状.push_str("【图谱契约·项目惯例】\n");
        现状.push_str(&图谱契约);
        现状.push_str(&测试样例);
        现状.push('\n');
    }

    // 打回自动重投（设计稿 §11.2 规则 11）：验收打回 = 实现不可信 → 鸿钧主政自动把
    // 「六准圣意见+终裁依据+缺陷层」带回实现层重投（上限 最大重试次数），不再等界主再次投递。
    // 重投前先按 规则 9 撤销本轮产物清盘；重投预算独立（每次 派遣执行 独立 32 轮/90 万 token）；
    // 重投成功正常定档，重试耗尽才落 待实现。
    const 最大重试次数: usize = 2;
    let mut 打回意见们: Vec<String> = Vec::new();
    let mut 尝试 = 0usize;
    loop {
        // 重投执行现状：上次打回意见注入现状末尾，供实现层模型对症修正。
        let 执行现状 = if 尝试 > 0 && !打回意见们.is_empty() {
            format!("{现状}\n\n【上次打回意见（自动重投，第 {尝试} 次）】\n{}", 打回意见们.join("\n"))
        } else {
            现状.clone()
        };
        let 任务们 = crate::拆解为任务(&方案);
        // 状态机推进：待实现 → 实现中（任务开始执行；重投前已回 待实现，迁移合法）。
        if let Err(错误) = 推进要求状态(&要求.id, 要求状态::实现中) {
            warn!(要求id = %要求.id, 错误 = %错误, "推进「实现中」失败");
        }
        // 节点汇报（生产化 1.1）：开始实现 → 鸿钧落一条对话记录。
        crate::落对话记录(
            "鸿钧",
            &format!("任务汇报：要求 {} 开始实现（{} 个任务并发）", 要求.id, 任务们.len()),
            &["界主".to_string(), "鸿钧".to_string()],
        );
        let mut 产物们: Vec<crate::产物条目> = Vec::new();
        let mut 失败说明: Option<String> = None;
        // 并发派遣：任务相互独立，LLM 生成并行（构建由调度器内部锁串行，防 target-dir 冲突）。
        // 地道并行：LLM 生成期间只做增量变更检测（白嫖等待期）；机制归纳推迟到 join 后，
        // 任务期间记忆读取保持稳定（不读不写格位），任务完成后再统一归纳登记。
        let 根路径 = 工作区.根路径().to_path_buf();
        let 地道结果 = std::sync::Arc::new(std::sync::Mutex::new(Ok::<shihai_fu::变更报告, String>(
            shihai_fu::变更报告::default(),
        )));
        let 回执们 = std::thread::scope(|作用域| {
            let 地道结果 = std::sync::Arc::clone(&地道结果);
            let 根路径 = 根路径.clone();
            作用域.spawn(move || {
                // 变更报告无论如何保留（地道整理失败存 Err 交外部登记）。
                let 报告 = match shihai_fu::地道整理(&shihai_fu::工作区::新(&根路径)) {
                    Ok(报告) => 报告,
                    Err(说明) => {
                        *地道结果.lock().unwrap() = Err(说明);
                        return;
                    }
                };
                *地道结果.lock().unwrap() = Ok(报告);
            });
            let 句柄们: Vec<_> = 任务们
                .iter()
                .enumerate()
                .map(|(序号, 任务)| {
                    // 重投任务id加「-重试N」后缀，防回滚垫分组与日志与上次尝试冲突。
                    let 任务id = if 尝试 > 0 {
                        format!("{}-{}-重试{}", 要求.id, 序号, 尝试)
                    } else {
                        format!("{}-{}", 要求.id, 序号)
                    };
                    let 背景 = &背景;
                    let 现状 = &执行现状;
                    let 涉及路径 = &要求.约束.涉及路径;
                    作用域.spawn(move || 调度.派遣执行(&任务id, 任务, 背景, 现状, 涉及路径))
                })
                .collect();
            句柄们
                .into_iter()
                .map(|句柄| 句柄.join().unwrap_or_else(|_| Err("任务线程异常".to_string())))
                .collect::<Vec<_>>()
        });
        // 地道收尾：任务全部完成后统一 机制归纳 → 登记变更（时序稳定：任务期间记忆读取不受归纳写入干扰）。
        match 地道结果.lock().unwrap().as_ref() {
            Ok(报告) if !报告.空() => {
                if let Err(说明) = shihai_fu::机制归纳(存储, 配置, &图, &根路径, 报告) {
                    warn!(说明 = %说明, "机制归纳失败");
                }
                shihai_fu::登记变更(存储, 报告)?;
            }
            Ok(_) => {}
            Err(说明) => warn!(说明 = %说明, "地道整理失败"),
        }
        let mut 总轮数: u64 = 0;
        for 回执 in 回执们 {
            let 回执 = 回执?;
            总用量.加(&回执.用量);
            总轮数 += 回执.轮数 as u64;
            // 失败回执的产物也收集：失败但已落盘的改动仍记录（与真实盘面一致），裁决另按失败说明定夺。
            for 产物 in &回执.产物们 {
                产物们.push(crate::产物条目 {
                    路径: 产物.路径.clone(),
                    类别: 产物.类别.clone(),
                    字节数: 产物.字节数,
                    变化类型: 产物.变化类型.clone(),
                });
            }
            if 回执.状态 != 执行状态::成功 {
                warn!(状态 = ?回执.状态, 说明 = %回执.说明, "执行未成功");
                失败说明 = Some(回执.说明);
                break;
            }
        }
        info!(任务数 = 任务们.len(), 产物数 = 产物们.len(), 总轮数, 尝试, 提示词 = 总用量.提示词, 缓存命中 = 总用量.缓存命中, "一轮执行完毕");
        // 产物清单按路径去重：同一路径多次写入只保留终版（幂等排序输出），
        // 防多版本条目被六准圣误判「孤儿文件冲突」（设计稿 §11.2 规则 6）。
        {
            let mut 按路径 = std::collections::HashMap::new();
            for 产物 in std::mem::take(&mut 产物们) {
                按路径.insert(产物.路径.clone(), 产物);
            }
            let mut 去重后: Vec<_> = 按路径.into_values().collect();
            去重后.sort_by(|甲, 乙| 甲.路径.cmp(&乙.路径));
            // 字节数回填真实盘面：产物条目字节数以文件系统为准（工具执行返回的是"改动量"，
            // 非文件真实大小，曾致六准圣按体量误判"疑似未实现"——2026-08-16 渐次披露投递打回根因）。
            for 产物 in 去重后.iter_mut() {
                if let Ok(元) = std::fs::metadata(根.join(&产物.路径)) {
                    产物.字节数 = 元.len();
                }
            }
            产物们 = 去重后;
        }
        // 上下文投入量化：工具循环总轮数写入事件格位，供后续复盘（轮数跨重试累计，由 执行回执 汇聚）。
        let _ = 存储.写记录(&shihai_fu::记录::新(
            "事件",
            &format!("执行总轮数 {总轮数} 轮（任务 {} 个，产物 {} 件，尝试 {}）", 任务们.len(), 产物们.len(), 尝试),
            "运行一轮",
            "代码",
        ));

        // 失败归因 → 教训格位：为下轮执行注入经验（失败必归因，成功不花 token）。
        if let Some(说明) = &失败说明 {
            if let Err(归因错误) = shihai_fu::归因教训(存储, 配置, &要求.方向, "失败", 说明) {
                warn!(归因错误 = %归因错误, "教训归因失败");
            }
            // 失败沉淀 → 世界状态.失败模式：按 要求id+阶段 去重累加次数（供进化环归因）。
            // 设计稿 §12 P2-8：失败模式沉淀 → 执行提示模板自动改进。
            if let Err(沉淀错误) = 沉淀失败(&要求.id, "运行一轮", 说明) {
                warn!(要求id = %要求.id, 沉淀错误 = %沉淀错误, "失败沉淀失败");
            }
        }

        // 三段流程终裁：机械前置门槛 → 六准圣分维独立审验 → 鸿钧终裁。
        // 要求书 + LLM 配置齐备则启用完整 LLM 流程；任一缺失自动降级为规则兜底。
        // 回执保留完整终裁回执（含六准圣意见/终裁依据/用量），供验收.jsonl 落盘明细可追溯。
        let 回执 = crate::终裁裁决(&要求, &产物们, 0.0, &相关文件, 失败说明.as_deref(), Some(配置));
        // 事件流：验收结论（append-only 事实源，通过/打回都记录）。
        let 流 = shihai_fu::事件流::在工作区(&工作区);
        let _ = 流.追加事件(shihai_fu::事件类型::验收结论, serde_json::json!({
            "要求id": 要求.id,
            "结论": format!("{:?}", 回执.验收.结论),
            "终裁依据": 回执.终裁依据,
            "尝试": 尝试,
        }));
        // 状态机推进：实现中 → 已验收（验收回执已落定）。
        if let Err(错误) = 推进要求状态(&要求.id, 要求状态::已验收) {
            warn!(要求id = %要求.id, 错误 = %错误, "推进「已验收」失败");
        }
        if 回执.验收.结论 == 验收结论::通过 {
            crate::定档(存储, &回执.验收, &产物们, &总用量)?;
            // 事件流：版本存档（append-only 事实源）。
            let _ = 流.追加事件(shihai_fu::事件类型::版本存档, serde_json::json!({
                "要求id": 要求.id,
                "产物数": 产物们.len(),
            }));
            // 定档成功：清理回滚垫全部存档（产物已入库，不再需要回滚）。
            let 垫 = shihai_fu::回滚垫::在工作区(&工作区);
            if let Err(清理错误) = 垫.清理全部() {
                warn!(要求id = %要求.id, 错误 = %清理错误, "定档后回滚垫清理失败");
            }
            // 状态机推进：已验收 → 已存档（定档入库完成，终态落定）。
            if let Err(错误) = 推进要求状态(&要求.id, 要求状态::已存档) {
                warn!(要求id = %要求.id, 错误 = %错误, "推进「已存档」失败");
            }
            if 尝试 > 0 {
                info!(要求id = %要求.id, 尝试, "打回自动重投成功");
            }
            return Ok(回执);
        }
        // 打回 = 产物不可信：按最近定档版本快照撤销本轮产物（设计稿 §11.2 规则 9）。
        // 实测：第二次投递打回后 流式历法.rs 4781 残留盘面，第三次模型在半成品上续写致 5663 半成品——
        // 不可信产物残留会污染下次实现与版本快照。
        match 打回撤销产物(&要求.id, &产物们, &工作区) {
            Ok(撤销数) => info!(要求id = %要求.id, 撤销数, 产物数 = 产物们.len(), 尝试, "打回已撤销本轮产物（回最近定档版本）"),
            Err(错误) => warn!(要求id = %要求.id, 错误 = %错误, "打回撤销产物失败（产物可能残留盘面）"),
        }
        // 事件流：失败沉淀（append-only 事实源，打回撤销留痕）。
        let _ = 流.追加事件(shihai_fu::事件类型::失败沉淀, serde_json::json!({
            "要求id": 要求.id,
            "尝试": 尝试,
            "终裁依据": 回执.终裁依据,
        }));
        // 打回意见汇入重投清单，供下一次尝试注入执行现状。
        打回意见们.push(汇总打回意见(&回执));
        if 尝试 < 最大重试次数 {
            尝试 += 1;
            // 状态机推进：已验收 → 待实现（回实现层待自动重投）。
            if let Err(错误) = 推进要求状态(&要求.id, 要求状态::待实现) {
                warn!(要求id = %要求.id, 错误 = %错误, "推进「待实现」失败");
            }
            info!(要求id = %要求.id, 尝试, 上限 = 最大重试次数, "打回，自动重投实现层");
            continue;
        }
        // 重试耗尽：状态落 待实现，打回结论仍落 验收.jsonl 与验收结果格位供追溯。
        if let Err(错误) = 推进要求状态(&要求.id, 要求状态::待实现) {
            warn!(要求id = %要求.id, 错误 = %错误, "推进「待实现」失败");
        }
        info!(要求id = %要求.id, 重试次数 = 尝试, "重试耗尽，落「待实现」");
        return Ok(回执);
    }
}

/// 汇总打回意见：把 六准圣意见 + 终裁依据 + 验收意见 拼成文本，
/// 供打回自动重投注入实现层执行现状（设计稿 §11.2 规则 11）。
fn 汇总打回意见(回执: &终裁回执) -> String {
    let mut 行 = Vec::new();
    行.push(format!("鸿钧终裁：{}", 回执.终裁依据));
    if let Some(意见) = &回执.验收.验收意见 {
        if !意见.is_empty() {
            行.push(format!("验收意见：{意见}"));
        }
    }
    for 准圣 in &回执.准圣意见们 {
        let 改进 = 准圣.改进建议.join("；");
        if 改进.is_empty() {
            行.push(format!("{:?}（{} 分）：{}", 准圣.维度, 准圣.评分, 准圣.关键问题));
        } else {
            行.push(format!("{:?}（{} 分）：{} 建议：{}", 准圣.维度, 准圣.评分, 准圣.关键问题, 改进));
        }
    }
    行.join("\n")
}

/// 打回撤销产物：按「最近定档版本快照」恢复产物路径文件（内容回定档基线）。
/// 版本库为增量快照（v1 全量，其后只存变更文件），故按 版本-vN 数字降序回溯，
/// 取最近一份含该文件的快照覆盖回盘面；全部版本都不含 → 该文件是本轮新增 → 删除。
/// 「打回 = 产物不可信」——产物残留盘面会污染下次实现与版本快照（2026-08-16 实测第二次打回残留）。
/// 返回撤销的文件数；版本库缺失/无版本时视为无事发生（打回仅回状态，不删盘面）。
fn 打回撤销产物(要求id: &str, 产物们: &[crate::产物条目], 工作区: &shihai_fu::工作区) -> Result<usize, String> {
    // 优先回滚垫：恢复世界写前状态（含未存档的界主/助手改动），比版本快照精确——
    // 版本快照不含未存档改动，按快照恢复会覆盖它们。
    // 只撤销本任务前缀组（要求id 及其 -子N/-重试N），不碰其他任务/界主的组——
    // 2026-08-17 实锤：`撤销全部` 恢复所有存档组，旧快照覆盖工作区未提交合法改动
    // （兜底分发.rs 命令接线曾被 10:50 打回撤销覆盖丢失）。
    let 垫 = shihai_fu::回滚垫::在工作区(工作区);
    match 垫.撤销任务前缀(要求id) {
        Ok(恢复) => {
            if let Err(清理错误) = 垫.清理全部() {
                warn!(错误 = %清理错误, "打回撤销后回滚垫清理失败");
            }
            if 恢复 > 0 {
                info!(要求id, 恢复数 = 恢复, "打回撤销：回滚垫恢复本任务写前盘面");
                return Ok(恢复 as usize);
            }
        }
        Err(说明) => {
            // 有任务分组撤销失败：存档保留供追溯，继续版本快照兜底尽力恢复。
            warn!(说明 = %说明, "回滚垫撤销部分失败，存档保留在 .上下文/回滚垫 供追溯；继续版本快照兜底");
        }
    }
    // 回滚垫无记录（世界未写或已清理）→ 版本快照兜底（原有逻辑）。
    let 版本库 = 工作区.上下文目录().join("版本库");
    // 版本目录（版本-vN → 源码-快照），N 数字降序（最新在前）。
    let mut 快照们: Vec<(u32, std::path::PathBuf)> = Vec::new();
    let Ok(条目们) = std::fs::read_dir(&版本库) else { return Ok(0) };
    for 条目 in 条目们.flatten() {
        let 名 = 条目.file_name().to_string_lossy().to_string();
        let Some(数字) = 名.strip_prefix("版本-v").and_then(|末| 末.parse::<u32>().ok()) else { continue };
        let 快照 = 条目.path().join("源码-快照");
        if 快照.is_dir() {
            快照们.push((数字, 快照));
        }
    }
    快照们.sort_by(|甲, 乙| 乙.0.cmp(&甲.0));
    let 根 = 工作区.根路径();
    let mut 撤销数 = 0usize;
    for 产物 in 产物们 {
        let 相对 = std::path::Path::new(&产物.路径);
        let 目标 = 根.join(相对);
        // 回溯最近含该文件的快照；全部不含则按「本轮新增」删除。
        let 恢复自 = 快照们.iter().map(|(_, 快照)| 快照.join(相对)).find(|候选| 候选.is_file());
        match 恢复自 {
            Some(源) => {
                if let Some(父) = 目标.parent() {
                    if let Err(错误) = std::fs::create_dir_all(父) {
                        warn!(路径 = %产物.路径, 错误 = %错误, "打回恢复建目录失败，跳过该文件");
                        continue;
                    }
                }
                std::fs::copy(&源, &目标)
                    .map_err(|错误| format!("打回恢复失败：{}：{错误}", 产物.路径))?;
                撤销数 += 1;
            }
            None => {
                if 目标.is_file() {
                    std::fs::remove_file(&目标)
                        .map_err(|错误| format!("打回删除失败：{}：{错误}", 产物.路径))?;
                    撤销数 += 1;
                }
            }
        }
    }
    Ok(撤销数)
}

