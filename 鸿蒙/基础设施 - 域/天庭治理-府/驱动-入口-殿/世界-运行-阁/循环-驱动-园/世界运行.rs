/// 状态目录：工作区根下的 .上下文/状态（与命令操作-府的 状态目录 行为对齐，本府复制以保持跨府引用只走 lib 根符号的边界）。
fn 状态目录() -> std::path::PathBuf {
    let 根 = std::env::var("WORLD_WORKSPACE_ROOT")
        .map(std::path::PathBuf::from)
        .unwrap_or_else(|_| std::env::current_dir().unwrap_or_default());
    根.join(".上下文").join("状态")
}

/// 失败沉淀：把一次失败写进世界状态.失败模式（按 要求id+阶段 去重累加次数）。
/// 失败模式是进化环归因的输入，不再恒空；所在层先记「实现层」，由后续进化归因细化。
fn 沉淀失败(要求id: &str, 阶段: &str, 原因: &str) -> Result<(), String> {
    let 目录 = 状态目录();
    let mut 状态 = crate::确保世界状态初始化(&目录)?;
    let 已有 = 状态.失败模式.iter_mut().find(|条目| 条目.要求id == 要求id && 条目.阶段 == 阶段);
    if let Some(条目) = 已有 {
        条目.次数 += 1;
        if !原因.is_empty() {
            条目.原因 = 原因.to_string();
        }
    } else {
        状态.失败模式.push(crate::失败条目 {
            要求id: 要求id.to_string(),
            阶段: 阶段.to_string(),
            原因: 原因.to_string(),
            所在层: crate::缺陷层::实现层,
            次数: 1,
            时间: shihai_fu::当前毫秒(),
        });
    }
    crate::写世界状态(&目录, &状态)
}

