/// 临时天道守卫（§14.19 规则五分类）：想法带【任务规则】段 → 写入 铁律·总纲（级别=临时天道）
/// → 任务全程注入固定规则段 → drop（任务结束）写失效标记清理（注入时按 失效 过滤跳过）。
/// 纯配置化：规则条文来自想法文本（界主），代码只做 注入+生命周期 机制。
struct 临时天道守卫 {
    存储: shihai_fu::模型存储,
    /// 任务独立实体键（临时天道-<想法id>）：任务结束写失效标记后，实体键级失效判定
    /// 跳过该键全部旧记录。**每任务独立键**——若共用键"临时天道"，下一任务的新记录
    /// 会把键最新置为未失效，上一任务的失效标记随之失效，旧规则"复活"注入后续任务
    /// （§14.19 真实任务复验抓出的缺陷）。
    实体键: String,
}

impl 临时天道守卫 {
    /// 想法内容含【任务规则】段 → 写入临时天道并返回守卫；否则 None。
    fn 尝试注入(
        存储: &shihai_fu::模型存储, 想法id: &str, 想法内容: &str
    ) -> Option<Self> {
        let 开始 = 想法内容.find("【任务规则】")?;
        let 段 = &想法内容[开始 + "【任务规则】".len()..];
        let 规则文本 = 段.split("【").next().unwrap_or("").trim();
        if 规则文本.is_empty() {
            return None;
        }
        let 实体键 = format!("临时天道-{想法id}");
        let mut 记录 = shihai_fu::记录::新带级别(
            "铁律·总纲",
            规则文本,
            "界主任务规则（临时天道）",
            "人类",
            shihai_fu::规则级别::临时天道,
        );
        记录.实体键 = 实体键.clone();
        if let Err(错误) = 存储.写记录(&记录) {
            warn!(错误 = %错误, "临时天道写入失败");
            return None;
        }
        info!(规则 = %规则文本, 实体键 = %实体键, "临时天道已写入（任务级规则）");
        Some(临时天道守卫 {
            存储: 存储.clone(),
            实体键,
        })
    }
}

impl Drop for 临时天道守卫 {
    fn drop(&mut self) {
        // 任务结束：写失效标记（同实体键 的新链头），固定规则段注入时按 失效 过滤跳过。
        let mut 失效记录 =
            shihai_fu::记录::新("铁律·总纲", "临时天道已清理", "任务结束", "代码");
        失效记录.失效 = true;
        失效记录.实体键 = self.实体键.clone();
        if let Err(错误) = self.存储.写记录(&失效记录) {
            warn!(错误 = %错误, "临时天道清理标记失败");
        } else {
            debug!(实体键 = %self.实体键, "临时天道已清理（任务结束失效）");
        }
    }
}

/// 主政回执：主政一轮（想法级）的汇总结果。
pub struct 主政回执 {
    /// 想法级结论：全部子要求通过 → 通过；任一打回/失败 → 打回。
    pub 结论: 验收结论,
    /// 每个子要求/单要求的完整终裁回执（供验收.jsonl 落盘明细）。
    pub 回执们: Vec<终裁回执>,
    /// 子要求数（不拆时为 1）。
    pub 子要求数: usize,
    /// 定档数（验收通过且已定档的子要求数）。
    pub 定档数: usize,
}

/// 主政一轮：鸿钧主政编排入口。
/// 先请 LLM 做需求拆分决策（设计稿 §11.2 规则 10：拆分决策是 LLM 的事、编排是智能体的事），
/// 不拆走原单要求；拆则逐个子要求串行走全链，每个子要求独立验收/定档/打回撤销，
/// 打回不拖累其余子要求。想法级结论聚合：全部通过 → 通过；任一打回/失败 → 打回。
/// 要求 id 全局递增（设计稿 §1.5.5 拍板 7：多任务线并发的追溯前提）。
pub fn 主政一轮(
    想法: &想法,
    配置: &模型配置,
    存储: &shihai_fu::模型存储,
) -> Result<主政回执, String> {
    // 状态共享：写入当前想法id（供观览查询读取，全局状态未初始化时不阻断主循环）
    if let Some(状态) = zhuangtai_fu::取全局状态() {
        let _ = 状态.写入(zhuangtai_fu::当前想法id(想法.id.clone()));
    }
    // 白箱观测：主政编排（含需求拆分决策）进入鸿钧角色（想法级上下文；要求id在拆分/运行一轮内再细化）。
    let _观测守卫 = 进入观测(观测角色::鸿钧, Some(想法.id.clone()), None, None);
    // 临时天道（§14.19）：想法带【任务规则】段 → 注入任务级规则（铁律·总纲 临时天道级别），
    // 必须在本轮所有背景（需求拆分/提审/执行）生成**之前**注入——元数据层化固定规则段
    // 在调用时读格位，注入太晚则本任务背景读不到自己的任务规则。
    // 守卫 drop（主政一轮结束 = 想法级全部子要求跑完）写失效标记清理，规则不泄漏到后续任务。
    let _临时天道 = 临时天道守卫::尝试注入(存储, &想法.id, &想法.内容);
    let 起始序号 = 下一个要求序号()?;
    // 继承制权限矩阵（2026-08-19）：主政/设计级调元数据层化——看任务级临时天道 + 大道级（底座+项目），
    // 不看项目级天道项目（审验标准是给验收层用的，噪音）。
    let 识海服务 = chajian_fu::取全局上下文()
        .ok_or("全局上下文未初始化")?
        .查找服务::<std::sync::Arc<dyn shihai_fu::识海服务>>()
        .ok_or("识海服务未注册")?;
    let 背景 = 识海服务
        .回想(
            "多宝",
            &shihai_fu::全部格位(),
            3_000,
            shihai_fu::调用方层级::设计,
        )
        .unwrap_or_default();
    // 事件流：想法投递（append-only 事实源，想法级一条）。
    let 流 = shihai_fu::事件流::在工作区(&shihai_fu::工作区::定位());
    流.追加事件静默(
        shihai_fu::事件类型::想法投递,
        serde_json::json!({
            "想法id": 想法.id,
            "内容": 想法.内容,
        }),
    );
    let 决策 = crate::需求拆分决策(&想法.内容, &背景, 配置);
    match 决策 {
        crate::拆分决策::不拆 => {
            let 要求id = format!("要求-{起始序号}");
            let 回执 = 运行一轮(想法, &要求id, 配置, 存储)?;
            let 定档数 = if 回执.验收.结论 == 验收结论::通过 {
                1
            } else {
                0
            };
            info!(要求id = %回执.验收.要求id, 结论 = ?回执.验收.结论, "主政一轮完成（单要求）");
            Ok(主政回执 {
                结论: 回执.验收.结论.clone(),
                回执们: vec![回执],
                子要求数: 1,
                定档数,
            })
        }
        crate::拆分决策::拆分(子要求们) => {
            let 数 = 子要求们.len();
            let mut 回执们 = Vec::with_capacity(数);
            let mut 定档数 = 0usize;
            for (序号, 子) in 子要求们.iter().enumerate() {
                let 子想法 = 想法 {
                    id: format!("{}-子{}", 想法.id, 序号 + 1),
                    内容: 子.合成文本(序号 + 1),
                    ..想法.clone()
                };
                let 要求id = format!("要求-{}", 起始序号 + 序号 as u64);
                match 运行一轮(&子想法, &要求id, 配置, 存储) {
                    Ok(回执) => {
                        if 回执.验收.结论 == 验收结论::通过 {
                            定档数 += 1;
                        }
                        回执们.push(回执);
                    }
                    // 子要求执行失败：不阻断后续子要求；想法级记为打回，并落一条失败回执供追溯。
                    Err(错误) => {
                        warn!(要求id = %要求id, 错误 = %错误, "子要求执行失败，想法级记为打回");
                        回执们.push(终裁回执 {
                            验收: 验收回执 {
                                要求id: 要求id.clone(),
                                结论: 验收结论::打回,
                                验收意见: Some(format!("子要求执行失败：{错误}")),
                                产物: vec![],
                                耗时秒: 0.0,
                            },
                            准圣意见们: vec![],
                            终裁依据: format!("执行失败：{错误}"),
                            用量: moxing_fu::用量::default(),
                        });
                    }
                }
            }
            let 结论 = if 定档数 == 数 {
                验收结论::通过
            } else {
                验收结论::打回
            };
            info!(子要求数 = 数, 定档数, 结论 = ?结论, "主政一轮完成（拆分）");
            Ok(主政回执 {
                结论,
                回执们,
                子要求数: 数,
                定档数,
            })
        }
    }
}

/// 运行一轮：把一个想法走完「要求 → 设计 → 实现 → 验收 → 定档」。
/// 返回完整终裁回执（含六准圣意见与鸿钧终裁依据），供验收.jsonl 落盘明细。
pub fn 运行一轮(
    想法: &想法,
    要求id: &str,
    配置: &模型配置,
    存储: &shihai_fu::模型存储,
) -> Result<终裁回执, String> {
    // 状态共享：写入当前要求id（供观览查询读取）
    if let Some(状态) = zhuangtai_fu::取全局状态() {
        let _ = 状态.写入(zhuangtai_fu::当前要求id(要求id.to_string()));
    }
    // 白箱观测：主政整轮进入鸿钧角色（要求级上下文）；设计/实现/验收子调用以栈顶覆盖。
    let _观测守卫 = 进入观测(观测角色::鸿钧, None, Some(要求id.to_string()), None);
    // 元数据层化初始背景（设计稿 §4.2 规则3 第 1 件）：首屏只拼最前+最后档（首因+近因），
    // 按 3000 字符预算（与 Python 模拟最优参数一致）；中间档不直接喂，在首屏末尾注脚列出名字供模型按需调用 读格位 展开。
    // 较原 100k 字符全量拼装：节省约 97% 首屏 token，且让模型养成"按需展开"的习惯。
    // 继承制权限矩阵（2026-08-19）：执行级调元数据层化——只看任务级临时天道 + 大道全局底座，
    // 不看项目级天道（审验标准/项目规则对执行任务无意义，避免噪音淹没执行专注）。
    let 识海服务 = chajian_fu::取全局上下文()
        .ok_or("全局上下文未初始化")?
        .查找服务::<std::sync::Arc<dyn shihai_fu::识海服务>>()
        .ok_or("识海服务未注册")?;
    let 背景 = 识海服务
        .回想(
            "多宝",
            &shihai_fu::全部格位(),
            3_000,
            shihai_fu::调用方层级::执行,
        )
        .unwrap_or_default();
    let 工作区 = shihai_fu::工作区::定位();
    let mut 图 = shihai_fu::依赖图::加载自工作区(&工作区).unwrap_or_default();
    // 人类格位临时代偿（设计稿 §4.2 规则5）：来源=人类的格位（初心/铁律/标准/架构/细则等）
    // 在人类未录时，用 LLM 探索项目生成临时内容落格位，让首屏投影携带真实项目通则。
    // 放在背景投影之后：本次已按旧空摘要投影，任务执行期间模型可用 读格位 展开新内容，
    // 下一次任务首屏即带全新内容（临时代偿失败仅记警告，不阻断主流程）。
    if let Err(说明) = shihai_fu::临时代偿(存储, 配置, 工作区.根路径(), &图) {
        warn!(说明 = %说明, "人类格位临时代偿失败（继续执行）");
    }
    // 提审背景补全结构树：府级清单不足以定位目标文件，把府→殿→阁→园 全树喂给要求提审，
    // 让「涉及路径」能解析出真实存在的目标文件路径（否则现状装配缺目标文件，执行者只能瞎探索）。
    let 全树 = 图.下探(&[]);
    let 提审背景 = if 全树.is_empty() {
        背景.clone()
    } else {
        format!("{背景}\n\n【结构树（府→殿→阁→园 全量）】\n{全树}")
    };
    let (要求, 解析用量) = crate::解析想法(要求id, &想法.内容, &提审背景, 配置)?;
    let mut 总用量 = 解析用量;
    // 落点护栏：涉及路径为空且非审验/核查类 → 拒绝放行（防模型乱闯烧预算）。
    // 2026-08-17 实测：补测试任务因涉及路径空，模型 19 轮绕圈烧 53 万 token 后失败。
    if let Err(错误) = 落点护栏(&要求.方向, &要求.约束.涉及路径) {
        warn!(要求id = %要求.id, 方向 = %要求.方向, "落点护栏拒绝放行");
        return Err(错误);
    }
    // 状态机起点：待领 → 立刻入池到要求.jsonl，让「事项列表 要求」能实时看到该要求。
    let 想法id = Some(想法.id.clone());
    let mut 入池要求 = 要求.clone();
    入池要求.想法id = 想法id;
    入池要求.状态 = 要求状态::待领;
    if let Err(错误) = 追加要求(&入池要求) {
        error!(要求id = %入池要求.id, "要求入池失败：{错误}");
        return Err(format!("要求入池失败：{错误}"));
    }

    // 依赖图滞后防御：若涉及路径对应文件全是本轮新建的（旧依赖图档案不含），先扫一次重建再查相关文件。
    // 重建后图替换旧图，下游「查相关文件 / 补全同阁 / 下探 / 查文件」全部走新图，验收裁决不再误判「产物路径偏离涉及范围」。
    // 用「查涉及文件」（精确匹配涉及路径，无兜底）判空：避免「查相关文件」兜底接线文件干扰判断。
    // 只对含 .rs 的涉及路径触发扫描——结构目录路径（新建园/阁落点）依赖图不含，触发全量扫描会卡数分钟（2026-08-17 实测）。
    let 精确 = 图.查涉及文件(&要求.约束.涉及路径);
    let 有rs路径 = 要求.约束.涉及路径.iter().any(|路径| 路径.ends_with(".rs"));
    if 精确.is_empty() && 有rs路径 && !要求.约束.涉及路径.is_empty() {
        info!("涉及路径在依赖图中无匹配，触发代码扫描重建依赖图");
        if let Err(说明) = shihai_fu::扫描(存储, 工作区.根路径()) {
            warn!(说明 = %说明, "依赖图重建失败，继续用旧图");
        }
        图 = shihai_fu::依赖图::加载自工作区(&工作区).unwrap_or_default();
    }

    // 设计上呈：分级设计（设计稿 §1.5.5 拍板 2：简单任务单轮商讨 / 复杂任务圣人工作群多轮商讨），模板兜底。
    let 方案 = crate::分级设计(&要求, 配置);
    // 事件流：设计上呈（append-only 事实源）。
    let 流 = shihai_fu::事件流::在工作区(&工作区);
    流.追加事件静默(
        shihai_fu::事件类型::设计上呈,
        serde_json::json!({
            "要求id": 要求.id,
            "拆解数": 方案.拆解.len(),
        }),
    );
    // 节点汇报（生产化 1.1）：设计完成 → 鸿钧落一条对话记录（界主「对话 历史」可见）。
    crate::落对话记录(
        "鸿钧",
        &format!(
            "任务汇报：要求 {} 设计完成（圣人商讨已收敛，拆解 {} 项，即将开始实现）",
            要求.id,
            方案.拆解.len()
        ),
        &["界主".to_string(), "鸿钧".to_string()],
    );

    // 状态机推进：待领 → 设计中（设计方案已构造，机械校验通过前不进入待确认）。
    推进并警(&要求.id, 要求状态::设计中);

    // 设计打回自动重审（§14.14 修复 2B）：确认设计打回 → 带机械校验明细重新 分级设计（上限 2 次）。
    // 治「LLM 设计填多值工作流被机械校验打回即整条任务线夭折」——设计缺陷可修，不该终止投递。
    let mut 方案 = 方案;
    let mut 设计尝试 = 0usize;
    const 设计重审上限: usize = 2;
    loop {
        if crate::确认设计(&方案, &要求.约束.涉及路径) == 验收结论::通过 {
            break;
        }
        if 设计尝试 >= 设计重审上限 {
            return Err("设计被打回（重审耗尽）".to_string());
        }
        设计尝试 += 1;
        warn!(要求id = %要求.id, 尝试 = 设计尝试, 上限 = 设计重审上限, "设计打回，自动重审");
        // 重审 = 重新 分级设计（模板提示已强化 工作流 单值约束，重审大概率修正；明细传递留后续）。
        方案 = crate::分级设计(&要求, 配置);
    }

    // 状态机推进：设计中 → 待确认 → 已确认（甲阶段流水线：设计自动确认，无人工确认节点）。
    推进并警(&要求.id, 要求状态::待确认);
    推进并警(&要求.id, 要求状态::已确认);
    推进并警(&要求.id, 要求状态::待实现);

    // 现状构造：依赖图精确读涉及路径 → 波及文件 → 结构下探 → 文件签名/定义 → 教训注入 → 图谱契约 → 事前推演。
    // 提取为 构造现状 函数（2026-08-20 任务间现状刷新入稿），供串行循环中每个任务执行前调用刷新。
    let mut 现状;
    let mut 相关文件;
    (现状, 相关文件) = 构造现状(存储, &图, &要求, &工作区);
    // 根路径：产物清单去重时回填字节数用（原 519-644 行内声明，提取函数后保留于外层作用域）。
    let 根 = 工作区.根路径();

    // 打回自动重投（设计稿 §11.2 规则 11）：验收打回 = 实现不可信 → 鸿钧主政自动把
    // 「六准圣意见+终裁依据+缺陷层」带回实现层重投（上限 最大重试次数），不再等界主再次投递。
    // 重投前先按 规则 9 撤销本轮产物清盘；重投预算独立（每次 派遣执行 独立 32 轮/90 万 token）；
    // 重投成功正常定档，重试耗尽才落 待实现。
    let mut 打回意见们: Vec<String> = Vec::new();
    let mut 尝试 = 0usize;
    loop {
        // 重投执行现状：上次打回意见注入现状末尾，供实现层模型对症修正。
        // 声明 mut：串行循环中任务间刷新现状后重新拼接执行现状（2026-08-20 任务间现状刷新入稿）。
        let mut 执行现状 = if 尝试 > 0 && !打回意见们.is_empty() {
            format!(
                "{现状}\n\n【上次打回意见（自动重投，第 {尝试} 次）】\n{}",
                打回意见们.join("\n")
            )
        } else {
            现状.clone()
        };
        let 任务们 = crate::拆解为任务(&方案);
        // 状态机推进：待实现 → 实现中（任务开始执行；重投前已回 待实现，迁移合法）。
        推进并警(&要求.id, 要求状态::实现中);
        // 节点汇报（生产化 1.1）：开始实现 → 鸿钧落一条对话记录。
        crate::落对话记录(
            "鸿钧",
            &format!(
                "任务汇报：要求 {} 开始实现（{} 个任务串行）",
                要求.id,
                任务们.len()
            ),
            &["界主".to_string(), "鸿钧".to_string()],
        );
        let mut 产物们: Vec<crate::产物条目> = Vec::new();
        let mut 失败说明: Option<String> = None;
        // 串行执行+任务间现状刷新：同涉及路径任务串行（前一个完成后刷新依赖图+现状再开始下一个），
        // 治要求-89 三子任务并行时子任务1引用子任务0新定义导致编译失败的依赖问题（2026-08-20 入稿）。
        // 地道整理线程仍并行（LLM 生成期间做增量变更检测，白嫖等待期），串行循环后 join。
        let 根路径 = 工作区.根路径().to_path_buf();
        let 地道结果 = std::sync::Arc::new(std::sync::Mutex::new(
            Ok::<shihai_fu::变更报告, String>(shihai_fu::变更报告::default()),
        ));
        let 地道句柄 = {
            let 地道结果 = std::sync::Arc::clone(&地道结果);
            let 根路径 = 根路径.clone();
            std::thread::spawn(move || {
                // 变更报告无论如何保留（地道整理失败存 Err 交外部登记）。
                let 报告 = match shihai_fu::地道整理(&shihai_fu::工作区::新(&根路径)) {
                    Ok(报告) => 报告,
                    Err(说明) => {
                        // Mutex poison 容错：poison 后仍取数据，避免级联 panic（D2 §2.3.1）。
                        *地道结果.lock().unwrap_or_else(|e| e.into_inner()) = Err(说明);
                        return;
                    }
                };
                // Mutex poison 容错：poison 后仍取数据，避免级联 panic（D2 §2.3.1）。
                *地道结果.lock().unwrap_or_else(|e| e.into_inner()) = Ok(报告);
            })
        };
        // 串行循环：任务间现状刷新（同涉及路径任务有依赖时，前一个产物入盘后下一个才能引用）
        let mut 回执们 = Vec::new();
        for (序号, 任务) in 任务们.iter().enumerate() {
            // 任务间现状刷新：非首个任务执行前，用上一轮任务后已重建的依赖图重新构造现状。
            // 依赖图重建已移至任务后无条件触发（设计稿 §4.2 依赖图滞后放宽），此处只构造现状。
            if 序号 > 0 {
                let (新现状, 新相关文件) = 构造现状(存储, &图, &要求, &工作区);
                现状 = 新现状;
                相关文件 = 新相关文件;
                // 重投执行现状同步刷新（基于新现状重新拼接打回意见）
                执行现状 = if 尝试 > 0 && !打回意见们.is_empty() {
                    format!(
                        "{现状}\n\n【上次打回意见（自动重投，第 {尝试} 次）】\n{}",
                        打回意见们.join("\n")
                    )
                } else {
                    现状.clone()
                };
                info!(要求id = %要求.id, 序号, "任务间现状已刷新");
            }
            // 重投任务id加「-重试N」后缀，防回滚垫分组与日志与上次尝试冲突。
            let 任务id = if 尝试 > 0 {
                format!("{}-{}-重试{}", 要求.id, 序号, 尝试)
            } else {
                format!("{}-{}", 要求.id, 序号)
            };
            // 白箱观测：任务进入执行角色，下游 模型调用 与 工具交接 埋点经 当前观测() 自动关联。
            let _观测守卫 = 进入观测(
                观测角色::执行,
                Some(任务id.clone()),
                Some(要求.id.clone()),
                None,
            );
            // 设计方案文本（问题7：设计方案传执行层）：圣人工作群商讨产物（设计思路+自评），
            // 注入执行提示让执行者照设计落码，不再凭空探索。方案在运行一轮上层产出，此处拼成文本传入。
            let 设计方案文本 = format!("【设计思路】\n{}\n\n【自评】\n{}", 方案.设计, 方案.自评);
            let 道术服务 = chajian_fu::取全局上下文()
                .ok_or("全局上下文未初始化")?
                .查找服务::<std::sync::Arc<dyn daoshu_fu::道术服务>>()
                .ok_or("道术服务未注册")?;
            let 回执 = 道术服务.执行任务(
                &任务id,
                任务,
                &背景,
                &执行现状,
                &要求.约束.涉及路径,
                &设计方案文本,
                &要求.验收标准,
            );
            回执们.push(回执);
            // 任务结束后无条件触发依赖图重建（设计稿 §4.2 依赖图滞后放宽）：
            // 防单任务改非涉及路径文件后依赖图滞后，致下一任务现状装配缺新定义。
            // 原条件触发（只在查涉及文件为空时）覆盖不到「涉及路径有匹配但非涉及路径文件已变」的场景。
            match shihai_fu::扫描(存储, 工作区.根路径()) {
                Ok(条数) => info!(条数, 序号, "任务后依赖图重建"),
                Err(说明) => warn!(说明 = %说明, 序号, "任务后依赖图重建失败"),
            }
            图 = shihai_fu::依赖图::加载自工作区(&工作区).unwrap_or_default();
        }
        // 地道整理 join（任务串行完成后收尾）
        地道句柄.join().unwrap_or(());
        // 地道收尾：任务全部完成后统一 机制归纳 → 登记变更（时序稳定：任务期间记忆读取不受归纳写入干扰）。
        // Mutex poison 容错：poison 后仍取数据，避免级联 panic（D2 §2.3.1）。
        match 地道结果.lock().unwrap_or_else(|e| e.into_inner()).as_ref() {
            Ok(报告) if !报告.空() => {
                if let Err(说明) = shihai_fu::机制归纳(存储, 配置, &图, &根路径, 报告)
                {
                    warn!(说明 = %说明, "机制归纳失败");
                }
                shihai_fu::登记变更(存储, 报告)?;
            }
            Ok(_) => {}
            Err(说明) => warn!(说明 = %说明, "地道整理失败"),
        }
        let mut 总轮数: u64 = 0;
        for 回执 in 回执们 {
            let 回执 = 回执?;
            总用量.加(&回执.用量);
            总轮数 += 回执.轮数 as u64;
            // 失败回执的产物也收集：失败但已落盘的改动仍记录（与真实盘面一致），裁决另按失败说明定夺。
            for 产物 in &回执.产物们 {
                产物们.push(crate::产物条目 {
                    路径: 产物.路径.clone(),
                    类别: 产物.类别.clone(),
                    字节数: 产物.字节数,
                    变化类型: 产物.变化类型.clone(),
                });
            }
            if 回执.状态 != 执行状态::成功 {
                warn!(状态 = ?回执.状态, 说明 = %回执.说明, "执行未成功");
                失败说明 = Some(回执.说明);
                break;
            }
        }
        info!(
            任务数 = 任务们.len(),
            产物数 = 产物们.len(),
            总轮数,
            尝试,
            提示词 = 总用量.提示词,
            缓存命中 = 总用量.缓存命中,
            "一轮执行完毕"
        );
        // 产物清单按路径去重：同一路径多次写入只保留终版（幂等排序输出），
        // 防多版本条目被六准圣误判「孤儿文件冲突」（设计稿 §11.2 规则 6）。
        {
            let mut 按路径 = std::collections::HashMap::new();
            for 产物 in std::mem::take(&mut 产物们) {
                按路径.insert(产物.路径.clone(), 产物);
            }
            let mut 去重后: Vec<_> = 按路径.into_values().collect();
            去重后.sort_by(|甲, 乙| 甲.路径.cmp(&乙.路径));
            // 字节数回填真实盘面：产物条目字节数以文件系统为准（工具执行返回的是"改动量"，
            // 非文件真实大小，曾致六准圣按体量误判"疑似未实现"——2026-08-16 渐次披露投递打回根因）。
            for 产物 in 去重后.iter_mut() {
                if let Ok(元) = std::fs::metadata(根.join(&产物.路径)) {
                    产物.字节数 = 元.len();
                }
            }
            产物们 = 去重后;
        }
        // 上下文投入量化：工具循环总轮数写入事件格位，供后续复盘（轮数跨重试累计，由 执行回执 汇聚）。
        let _ = 存储.写记录(&shihai_fu::记录::新(
            "事件",
            &format!(
                "执行总轮数 {总轮数} 轮（任务 {} 个，产物 {} 件，尝试 {}）",
                任务们.len(),
                产物们.len(),
                尝试
            ),
            "运行一轮",
            "代码",
        ));

        // 失败归因 → 教训格位：为下轮执行注入经验（失败必归因，成功不花 token）。
        if let Some(说明) = &失败说明 {
            if let Err(归因错误) = shihai_fu::归因教训(存储, 配置, &要求.方向, "失败", 说明)
            {
                warn!(归因错误 = %归因错误, "教训归因失败");
            }
            // 失败沉淀 → 世界状态.失败模式：按 要求id+阶段 去重累加次数（供进化环归因）。
            // 设计稿 §12 P2-8：失败模式沉淀 → 执行提示模板自动改进。
            if let Err(沉淀错误) = 沉淀失败(&要求.id, "运行一轮", 说明) {
                warn!(要求id = %要求.id, 沉淀错误 = %沉淀错误, "失败沉淀失败");
            }
        }

        // 三段流程终裁：机械前置门槛 → 六准圣分维独立审验 → 鸿钧终裁。
        // 要求书 + LLM 配置齐备则启用完整 LLM 流程；任一缺失自动降级为规则兜底。
        // 回执保留完整终裁回执（含六准圣意见/终裁依据/用量），供验收.jsonl 落盘明细可追溯。
        // 验收耗时实测：终裁调用前记起点，结束后回填 回执.验收.耗时秒（此前恒 0 无法量化）。
        let 验收起点 = std::time::Instant::now();
        let mut 回执 = crate::终裁裁决(
            &要求,
            &产物们,
            0.0,
            &相关文件,
            失败说明.as_deref(),
            Some(配置),
        );
        回执.验收.耗时秒 = 验收起点.elapsed().as_secs_f64();
        info!(要求id = %要求.id, 验收耗时秒 = 回执.验收.耗时秒, "验收阶段完成");
        // 事件流：验收结论（append-only 事实源，通过/打回都记录）。
        let 流 = shihai_fu::事件流::在工作区(&工作区);
        流.追加事件静默(
            shihai_fu::事件类型::验收结论,
            serde_json::json!({
                "要求id": 要求.id,
                "结论": format!("{:?}", 回执.验收.结论),
                "终裁依据": 回执.终裁依据,
                "尝试": 尝试,
            }),
        );
        // 状态机推进：实现中 → 已验收（验收回执已落定）。
        推进并警(&要求.id, 要求状态::已验收);
        if 回执.验收.结论 == 验收结论::通过 {
            crate::定档(存储, &回执.验收, &产物们, &总用量)?;
            // 事件流：版本存档（append-only 事实源）。
            流.追加事件静默(
                shihai_fu::事件类型::版本存档,
                serde_json::json!({
                    "要求id": 要求.id,
                    "产物数": 产物们.len(),
                }),
            );
            // 定档成功：清理回滚垫全部存档（产物已入库，不再需要回滚）。
            let 垫 = shihai_fu::回滚垫::在工作区(&工作区);
            if let Err(清理错误) = 垫.清理全部() {
                warn!(要求id = %要求.id, 错误 = %清理错误, "定档后回滚垫清理失败");
            }
            // 状态机推进：已验收 → 已存档（定档入库完成，终态落定）。
            推进并警(&要求.id, 要求状态::已存档);
            if 尝试 > 0 {
                info!(要求id = %要求.id, 尝试, "打回自动重投成功");
            }
            return Ok(回执);
        }
        // 打回 = 产物不可信：按最近定档版本快照撤销本轮产物（设计稿 §11.2 规则 9）。
        // 实测：第二次投递打回后 流式历法.rs 4781 拗留盘面，第三次模型在半成品上续写致 5663 半成品——
        // 不可信产物残留会污染下次实现与版本快照。
        match 打回撤销产物(&要求.id, &产物们, &工作区) {
            Ok(撤销数) => {
                info!(要求id = %要求.id, 撤销数, 产物数 = 产物们.len(), 尝试, "打回已撤销本轮产物（回最近定档版本）")
            }
            Err(错误) => {
                warn!(要求id = %要求.id, 错误 = %错误, "打回撤销产物失败（产物可能残留盘面）")
            }
        }
        // 事件流：失败沉淀（append-only 事实源，打回撤销留痕）。
        流.追加事件静默(
            shihai_fu::事件类型::失败沉淀,
            serde_json::json!({
                "要求id": 要求.id,
                "尝试": 尝试,
                "终裁依据": 回执.终裁依据,
            }),
        );
        // 打回意见汇入重投清单，供下一次尝试注入执行现状。
        打回意见们.push(汇总打回意见(&回执));
        // 事件总线（阶段 2 转事件化）：重投循环通知——打回撤销后、重投前，
        // 监听器可挂钩重试策略/审计/告警（对齐 dsh 事件域「重试」）。
        全局总线().通知(
            "重投/循环",
            &mut Box::new(重投事件 {
                要求id: 要求.id.clone(),
                尝试,
                上限: 最大重试次数,
                继续: 尝试 < 最大重试次数,
            }),
        );
        if 尝试 < 最大重试次数 {
            尝试 += 1;
            // 状态机推进：已验收 → 待实现（回实现层待自动重投）。
            推进并警(&要求.id, 要求状态::待实现);
            info!(要求id = %要求.id, 尝试, 上限 = 最大重试次数, "打回，自动重投实现层");
            continue;
        }
        // 重试耗尽：状态落 待实现，打回结论仍落 验收.jsonl 与验收结果格位供追溯。
        推进并警(&要求.id, 要求状态::待实现);
        info!(要求id = %要求.id, 重试次数 = 尝试, "重试耗尽，落「待实现」");
        return Ok(回执);
    }
}

/// 打回自动重投上限（设计稿 §11.2 规则 11）：重投前撤销本轮产物、注入上次打回意见，
/// 预算独立；重试耗尽落「待实现」。常量提为模块根供契约测试钉住（变更属流程级调整须入稿）。
const 最大重试次数: usize = 2;

/// 重投循环事件载荷：事件总线「重投/循环」通知的载荷（阶段 2 转事件化）。
/// 监听器 downcast 到本类型取重投状态（重试策略/审计/告警挂钩用）。
#[derive(Clone, Debug)]
pub struct 重投事件 {
    pub 要求id: String,
    pub 尝试: usize,
    pub 上限: usize,
    pub 继续: bool,
}

/// 汇总打回意见：把 六准圣意见 + 终裁依据 + 验收意见 拼成文本，
/// 供打回自动重投注入实现层执行现状（设计稿 §11.2 规则 11）。
fn 汇总打回意见(回执: &终裁回执) -> String {
    let mut 行 = Vec::new();
    行.push(format!("鸿钧终裁：{}", 回执.终裁依据));
    if let Some(意见) = &回执.验收.验收意见 {
        if !意见.is_empty() {
            行.push(format!("验收意见：{意见}"));
        }
    }
    for 准圣 in &回执.准圣意见们 {
        let 改进 = 准圣.改进建议.join("；");
        if 改进.is_empty() {
            行.push(format!(
                "{:?}（{} 分）：{}",
                准圣.维度, 准圣.评分, 准圣.关键问题
            ));
        } else {
            行.push(format!(
                "{:?}（{} 分）：{} 建议：{}",
                准圣.维度, 准圣.评分, 准圣.关键问题, 改进
            ));
        }
    }
    行.join("\n")
}

/// 打回撤销产物：回到任务写前状态——优先 回滚垫（任务写前备份，含未存档的界主/助手改动）。
/// §14.14 修复：**移除版本快照兜底**——版本快照是定档时点，含其后的未存档改动会在恢复时被抹掉
/// （2026-08-19 实测：阶段 2 事件埋点被 v16 快照恢复误抹）。回滚垫无记录时核对「执行-基线」：
/// 任务期间改动未走回滚垫 → warn 留痕并保留当前盘面（不抹未存档改动）。
/// 「打回 = 产物不可信」——产物残留盘面会污染下次实现（2026-08-16 实测第二次打回残留）；
/// 两害相权：残留可后续清理，抹掉未存档成果不可恢复。
fn 打回撤销产物(
    要求id: &str,
    产物们: &[crate::产物条目],
    工作区: &shihai_fu::工作区,
) -> Result<usize, String> {
    // 优先回滚垫：恢复世界写前状态（含未存档的界主/助手改动），比版本快照精确——
    // 版本快照不含未存档改动，按快照恢复会覆盖它们。
    // 只撤销本任务前缀组（要求id 及其 -子N/-重试N），不碰其他任务/界主的组——
    // 2026-08-17 实锤：`撤销全部` 恢复所有存档组，旧快照覆盖工作区未提交合法改动
    // （兜底分发.rs 命令接线曾被 10:50 打回撤销覆盖丢失）。
    let 垫 = shihai_fu::回滚垫::在工作区(工作区);
    match 垫.撤销任务前缀(要求id) {
        Ok(恢复) => {
            if let Err(清理错误) = 垫.清理全部() {
                warn!(错误 = %清理错误, "打回撤销后回滚垫清理失败");
            }
            if 恢复 > 0 {
                info!(要求id, 恢复数 = 恢复, "打回撤销：回滚垫恢复本任务写前盘面");
                return Ok(恢复 as usize);
            }
        }
        Err(说明) => {
            // 有任务分组撤销失败：存档保留供追溯，继续版本快照兜底尽力恢复。
            warn!(说明 = %说明, "回滚垫撤销部分失败，存档保留在 .上下文/回滚垫 供追溯；继续版本快照兜底");
        }
    }
    // 回滚垫无记录（世界未写或已清理）→ **不再走版本快照**（§14.14 修复：版本快照是定档时点，
    // 含其后的任何未存档改动——阶段 2 埋点曾被 v16 快照恢复抹掉）。改为核对「执行-基线」：
    // 基线有该文件且当前≠基线（任务期间改过但回滚垫无记录）→ warn 留痕（保留当前盘面，防抹掉未存档改动）；
    // 基线无记录 → 该文件非本轮改动，忽略。
    let 根 = 工作区.根路径();
    let 基线指纹们: std::collections::HashMap<String, serde_json::Value> =
        std::fs::read_to_string(工作区.上下文目录().join("状态").join("执行-基线.json"))
            .ok()
            .and_then(|文本| serde_json::from_str(&文本).ok())
            .unwrap_or_default();
    // 基线结构：{"指纹们": {路径: {大小, 修改}}}。
    let 指纹们 = 基线指纹们.get("指纹们").and_then(|v| v.as_object());
    for 产物 in 产物们 {
        let 相对 = std::path::Path::new(&产物.路径);
        let 目标 = 根.join(相对);
        let 基线条目 = 指纹们.and_then(|表| 表.get(&产物.路径)).or_else(|| {
            // 兼容正反斜杠：基线键可能用 `\`（Windows 路径记录）。
            指纹们.and_then(|表| {
                表.iter()
                    .find(|(键, _)| 键.replace('\\', "/") == 产物.路径)
                    .map(|(_, v)| v)
            })
        });
        match 基线条目 {
            Some(条目) => {
                // 基线有记录：当前内容与基线指纹一致 → 本轮未改（或已恢复到基线），无事；不一致 → 改动未走回滚垫，留痕不恢复。
                let 当前指纹 = 文件指纹(&目标);
                let 基线指纹 = 基线指纹字符串(条目);
                if 当前指纹.as_deref() != 基线指纹.as_deref() {
                    warn!(
                        路径 = %产物.路径,
                        "打回撤销：该文件任务期间被改动但回滚垫无记录，未恢复（保留当前盘面，防抹掉未存档改动）；如需复原请人工核对",
                    );
                }
            }
            None => {
                debug!(路径 = %产物.路径, "打回撤销：基线无记录（非本轮改动或新增未跟踪），跳过");
            }
        }
    }
    Ok(0)
}

/// 文件指纹：大小 + 修改时间毫秒（与 识海 增量检测 同口径；读失败返回 None）。
fn 文件指纹(路径: &std::path::Path) -> Option<String> {
    let 元 = std::fs::metadata(路径).ok()?;
    let 修改 = 元
        .modified()
        .ok()?
        .duration_since(std::time::UNIX_EPOCH)
        .ok()?
        .as_millis();
    Some(format!("{}:{}", 元.len(), 修改))
}

/// 基线条目指纹：{大小, 修改} → "大小:修改毫秒"（与 文件指纹 同格式；缺字段返回 None）。
fn 基线指纹字符串(条目: &serde_json::Value) -> Option<String> {
    let 大小 = 条目.get("大小")?.as_u64()?;
    let 修改 = 条目.get("修改")?.as_u64()?;
    Some(format!("{大小}:{修改}"))
}

/// 执行一条待执行任务线（守护/驱动共用）：领取 → 主政一轮全链 → 回填结果 → 汇报入对话记录。
/// 返回 Some(汇报) 表示消费了一条；None 表示无待执行（或锁被他人持有）。
pub fn 执行一条待执行任务线(
    存储: &shihai_fu::模型存储,
) -> Result<Option<String>, String> {
    let 任务线 = match 领取待执行任务线()? {
        Some(任务线) => 任务线,
        None => return Ok(None),
    };
    let 开始毫秒 = shihai_fu::当前毫秒();
    info!(任务线id = %任务线.id, "任务线开始执行");
    let 想法 = 想法 {
        id: 任务线.想法id.clone(),
        内容: 任务线.想法内容.clone(),
        时间: 任务线.时间,
        状态: 想法状态::未处理,
    };
    // 想法入池（与对话发布任务同链路，保证想法.jsonl 可追溯）。
    let 想法路径 = super::状态推进::状态目录().join("想法.jsonl");
    let 想法池 = crate::落盘队列::<想法>::打开(想法路径.clone());
    if let Err(错误) = 想法池.入队(&想法) {
        error!(任务线id = %任务线.id, "想法入池失败：{错误}");
        return Err(错误);
    }
    let 工作区根 = std::env::var("WORLD_WORKSPACE_ROOT")
        .map(std::path::PathBuf::from)
        .unwrap_or_else(|_| std::env::current_dir().unwrap_or_default());
    let 天庭服务 = chajian_fu::取全局上下文()
        .ok_or("全局上下文未初始化")?
        .查找服务::<std::sync::Arc<dyn crate::天庭服务>>()
        .ok_or("天庭服务未注册")?;
    let (汇报, 结论, 失败原因, 主线要求id) = match 天庭服务.调度要求(&想法) {
        Ok(回执) => {
            let 验收 = crate::落盘队列::<crate::终裁回执>::打开(
                super::状态推进::状态目录().join("验收.jsonl"),
            );
            for 回执 in &回执.回执们 {
                let _ = 验收.入队(回执);
            }
            let 结论 = match 回执.结论 {
                验收结论::通过 => "通过",
                验收结论::打回 => "打回",
            };
            let 明细 = 回执
                .回执们
                .iter()
                .map(|回执| format!("{} {:?}", 回执.验收.要求id, 回执.验收.结论))
                .collect::<Vec<_>>()
                .join("；");
            let 汇报 = format!("任务线 {} 完成：{结论}（{}）", 任务线.id, 明细);
            // 想法状态按汇总结论推进。
            let 新状态 = match 回执.结论 {
                验收结论::通过 => 想法状态::已化为要求,
                验收结论::打回 => 想法状态::已打回,
            };
            let _ = 推进想法状态(&想法.id, 新状态);
            // 回填任务线（取首个回执的要求id 作为主线 id）。
            let 要求id = 回执
                .回执们
                .first()
                .map(|回执| 回执.验收.要求id.clone())
                .unwrap_or_else(|| 任务线.id.clone());
            let _ = 回填任务线结果(&任务线.id, &要求id, 结论, &汇报);
            (汇报, 结论.to_string(), String::new(), 要求id)
        }
        Err(错误) => {
            error!(任务线id = %任务线.id, 错误 = %错误, "任务线执行失败");
            let _ = 推进想法状态(&想法.id, 想法状态::已打回);
            归位要求状态(&想法.id);
            let 汇报 = format!("任务线 {} 执行失败：{错误}", 任务线.id);
            let _ = 回填任务线结果(&任务线.id, &任务线.id, "打回", &汇报);
            (汇报, "打回".to_string(), 错误, 任务线.id.clone())
        }
    };
    // 回填前检查中止标记（生产化 1.3）：执行期间被中止 → 撤销产物、不汇报。
    if 任务线状态(&任务线.id) == 任务线状态::已中止 {
        warn!(任务线id = %任务线.id, "任务线执行期间被中止，撤销产物不汇报");
        let 垫 = shihai_fu::回滚垫::在工作区(&shihai_fu::工作区::新(&工作区根));
        match 垫.撤销任务前缀(&任务线.id) {
            Ok(恢复) => info!(恢复数 = 恢复, "中止任务线产物已撤销"),
            Err(说明) => warn!(说明 = %说明, "中止任务线撤销产物失败"),
        }
        let _ = 垫.清理全部();
        记指标(
            &任务线.id,
            &任务线.id,
            "已中止",
            shihai_fu::当前毫秒() - 开始毫秒,
            0,
            "界主中止",
        );
        return Ok(None);
    }
    // 指标落盘（生产化 3.3）：结论/耗时/token/失败原因 → .上下文/状态/指标.jsonl。
    // token 口径：从验收.jsonl 汇总主线要求的全部回执用量（主政一轮不返回用量，从回执取；
    // 重试多次的累计成本都算入本任务线）。2026-08-17 体检修复：原用领取时 任务线.要求id（None），
    // 导致指标 token 恒 0——改用执行后回填的主线要求id。
    let 用总token = if 失败原因.is_empty() {
        crate::落盘队列::<crate::终裁回执>::打开(
            super::状态推进::状态目录().join("验收.jsonl"),
        )
        .读全部()
        .unwrap_or_default()
        .iter()
        .filter(|回执| 回执.验收.要求id == 主线要求id)
        .map(|回执| 回执.用量.总计)
        .sum()
    } else {
        0
    };
    记指标(
        &任务线.id,
        &主线要求id,
        &结论,
        shihai_fu::当前毫秒() - 开始毫秒,
        用总token,
        &失败原因,
    );
    // 失败告警（生产化 3.4）：连续失败 → 鸿钧对话汇报。
    失败告警(&结论);
    // 汇报写对话记录（鸿钧 → 界主），界主追问可见；事件格位同步留痕。
    crate::落对话记录("鸿钧", &汇报, &["界主".to_string(), "鸿钧".to_string()]);
    let _ = 存储.写记录(&shihai_fu::记录::新(
        "事件",
        &format!("任务线汇报：{汇报}"),
        "鸿钧",
        "代码",
    ));
    info!(任务线id = %任务线.id, 结论 = %结论, "任务线执行完成");
    Ok(Some(汇报))
}

