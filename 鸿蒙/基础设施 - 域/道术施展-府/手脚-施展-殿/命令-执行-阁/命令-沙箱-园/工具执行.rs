//! 命令 - 沙箱 - 园：工具执行前的路径归一化与涉及范围校验。
//!
//! 设计要点（与 `任务-调度-殿/任务-派遣-阁/工具-循环-园/工具执行.rs::校验涉及路径` 对齐语义、提升性能）：
//! 1. 路径归一化（`replace('\\', "/")`）抽成可复用函数 `归一化路径`；
//! 2. 在执行前一次性把允许列表与拒绝列表都归一化为 `Vec<String>`，并预拼接 `{涉及}/` 前缀；
//! 3. `iter().any()` 闭包内只做 `&str` 相等比较，循环体内零额外堆分配。
//!
//! 背景：原版仅在涉及列表侧预归一化（拒绝列表缺失、前缀格式仍在闭包内分配）；
//! 本园把整套归一化全部上移到执行前，循环内不再产生任何 String 分配，且支持拒绝列表。

/// 路径归一化：把 Windows 反斜杠归一为正斜杠，与原 iter().any() 闭包中
/// `s.replace('\\', "/")` 的语义等价（不折叠大小写、不消除 `./`，由调用方按需处理）。
pub fn 归一化路径(输入: &str) -> String {
    输入.replace('\\', "/")
}

/// 涉及路径护栏（预归一版）：允许列表与拒绝列表均在执行前一次性归一化 + 预拼接前缀，
/// `iter().any()` 闭包内只做 `&str` 相等比较，零额外堆分配。
///
/// 命中规则（允许列表）：
/// ① 目标 == 涉及路径 → 命中；
/// ② 目标 starts_with `{涉及}/`（目录树内） → 命中；
/// ③ 目标与涉及文件（末段含 `.`）同目录（补测试/同园场景） → 命中。
///
/// 拒绝规则：① 目标 == 拒绝；② 目标 starts_with `{拒绝}/`。命中即拒。
///
/// 目标不做 `trim_start_matches('.')`：`.上下文` 与 `上下文` 是不同语义，
/// 拒绝列表 `.上下文` 应严格命中 `.上下文/...`，去点会破坏匹配。
pub fn 校验涉及路径预归一(
    原始: &str,
    涉及路径: &[String],
    涉及路径_拒绝: &[String],
) -> Result<(), String> {
    // 双空：审验/核查类，弃权放行（纪律靠执行提示）。
    if 涉及路径.is_empty() && 涉及路径_拒绝.is_empty() {
        return Ok(());
    }
    // 1) 目标路径一次性归一化（trim 首尾空白 + 反斜杠→斜杠），保留开头 `.`。
    let 目标 = 原始.trim().replace('\\', "/");

    // 2) 拒绝列表预归一化为 `Vec<(规范串, 前缀串)>`，前缀在初始化阶段一次性拼接。
    let 拒绝规范: Vec<(String, String)> = 涉及路径_拒绝
        .iter()
        .map(|拒绝| {
            let 规范 = 拒绝.replace('\\', "/");
            (规范.clone(), format!("{}/", 规范))
        })
        .collect();

    // 3) 拒绝命中判定：循环内仅 `&str` 比较，零分配。
    let 拒绝命中 = 拒绝规范
        .iter()
        .any(|(拒绝, 前缀)| 目标 == 拒绝.as_str() || 目标.starts_with(前缀.as_str()));
    if 拒绝命中 {
        return Err(format!(
            "涉及路径拒绝列表命中：{原始}（不允许落在以下路径或其子目录下：{}）",
            涉及路径_拒绝.join("、")
        ));
    }
    // 仅拒绝列表非空、允许列表为空：不在拒绝内即视为放行（审验/核查类允许列表可空）。
    if 涉及路径.is_empty() {
        return Ok(());
    }

    // 4) 允许列表预归一化为 `Vec<(规范串, 前缀串)>`。
    let 涉及规范: Vec<(String, String)> = 涉及路径
        .iter()
        .map(|涉及| {
            let 规范 = 涉及.replace('\\', "/");
            (规范.clone(), format!("{}/", 规范))
        })
        .collect();

    // 5) 允许命中判定：循环内仅 `&str` 比较，零分配。
    //    形态分支（文件同目录 vs 目录树前缀）在闭包内统一为「要么前缀命中、要么同父目录命中」。
    let 在内 = 涉及规范.iter().any(|(涉及, 前缀)| {
        if 目标 == 涉及.as_str() || 目标.starts_with(前缀.as_str()) {
            return true;
        }
        // 同目录：仅当涉及路径形态为文件（末段含扩展名）时，允许改/建同目录文件（补测试/同园场景）；
        // 目录型涉及路径走 ② 目录树前缀，不适用同目录（防兄弟目录误放行）。
        let 涉及是文件 = 涉及
            .rsplit('/')
            .next()
            .map(|末段| 末段.contains('.'))
            .unwrap_or(false);
        match 涉及.rsplit_once('/') {
            Some((涉及父, _)) if 涉及是文件 => 目标
                .rsplit_once('/')
                .map(|(目标父, _)| 目标父 == 涉及父)
                .unwrap_or(false),
            _ => false,
        }
    });
    if 在内 {
        Ok(())
    } else {
        Err(format!(
            "涉及路径外拒写：{目标}（只允许落在要求书涉及路径内或同目录：{}）——如需改其他文件，请界主把目标路径写进涉及路径",
            涉及路径.join("、")
        ))
    }
}

#[cfg(test)]
mod 测试 {
    use super::{归一化路径, 校验涉及路径预归一};

    #[test]
    fn 归一化路径_反斜杠转斜杠() {
        assert_eq!(
            归一化路径("鸿蒙\\基础设施 - 域\\foo.rs"),
            "鸿蒙/基础设施 - 域/foo.rs"
        );
        assert_eq!(归一化路径("鸿蒙/基础设施/foo.rs"), "鸿蒙/基础设施/foo.rs");
        assert_eq!(归一化路径(""), "");
    }

    #[test]
    fn 涉及路径_文件精确与目录树内放行() {
        let 涉及 = vec![
            "乾坤/呈现-域/命令操作-府/观览-查询-殿/世界-观览-阁/流式-回放-园/流式回放.rs"
                .to_string(),
            "乾坤/呈现-域/命令操作-府/观览-查询-殿/世界-观览-阁/流式-直播-园".to_string(),
        ];
        let 拒绝: Vec<String> = vec![];
        assert!(
            校验涉及路径预归一(
                "乾坤/呈现-域/命令操作-府/观览-查询-殿/世界-观览-阁/流式-回放-园/流式回放.rs",
                &涉及,
                &拒绝,
            )
            .is_ok(),
            "涉及文件本身可写"
        );
        assert!(
            校验涉及路径预归一(
                "乾坤/呈现-域/命令操作-府/观览-查询-殿/世界-观览-阁/流式-回放-园/流式回放测试.rs",
                &涉及,
                &拒绝,
            )
            .is_ok(),
            "涉及文件同目录可新建（补测试场景）"
        );
        assert!(
            校验涉及路径预归一(
                "乾坤/呈现-域/命令操作-府/观览-查询-殿/世界-观览-阁/流式-直播-园/流式直播.rs",
                &涉及,
                &拒绝,
            )
            .is_ok(),
            "涉及目录树下可写"
        );
        assert!(
            校验涉及路径预归一(
                "乾坤/呈现-域/命令操作-府/观览-查询-殿/世界-观览-阁/流式-回放-园",
                &涉及,
                &拒绝,
            )
            .is_err(),
            "涉及文件的上级目录本身不可写"
        );
    }

    #[test]
    fn 涉及路径_越界拒绝() {
        let 涉及 = vec![
            "乾坤/呈现-域/命令操作-府/观览-查询-殿/世界-观览-阁/流式-回放-园/流式回放.rs"
                .to_string(),
        ];
        let 拒绝: Vec<String> = vec![];
        let 错 =
            校验涉及路径预归一("证道/鸿蒙 - 域/单元测试-府/Cargo.toml", &涉及, &拒绝).unwrap_err();
        assert!(错.contains("涉及路径外拒写"), "涉及路径外应拒写：{错}");
        assert!(
            校验涉及路径预归一("鸿蒙/基础设施 - 域/天庭治理-府/Cargo.toml", &涉及, &拒绝,).is_err(),
            "其他府文件拒写"
        );
        let 涉及目录 = vec!["乾坤/甲-园".to_string()];
        assert!(
            校验涉及路径预归一("乾坤/甲-园X/乙.rs", &涉及目录, &[]).is_err(),
            "前缀相似不应放行"
        );
        assert!(
            校验涉及路径预归一(
                "乾坤/呈现-域/命令操作-府/观览-查询-殿/世界-观览-阁/流式-直播-园/流式直播.rs",
                &涉及,
                &拒绝,
            )
            .is_err(),
            "同目录规则不跨目录"
        );
    }

    #[test]
    fn 涉及路径_空放行() {
        assert!(
            校验涉及路径预归一("任何/路径.rs", &[], &[]).is_ok(),
            "审验类无涉及路径应放行"
        );
    }

    #[test]
    fn 涉及路径_拒绝列表命中() {
        let 涉及 = vec!["鸿蒙".to_string()];
        let 拒绝 = vec![".上下文".to_string()];
        let 错 = 校验涉及路径预归一(".上下文/格位/xxx.json", &涉及, &拒绝).unwrap_err();
        assert!(错.contains("拒绝列表命中"), "拒绝列表应命中：{错}");
    }

    #[test]
    fn 涉及路径_拒绝列表放行() {
        let 涉及 = vec!["鸿蒙".to_string()];
        let 拒绝 = vec![".上下文".to_string()];
        assert!(
            校验涉及路径预归一("鸿蒙/基础设施 - 域/某-园/foo.rs", &涉及, &拒绝).is_ok(),
            "非拒绝路径应放行"
        );
    }

    #[test]
    fn 涉及路径_拒绝列表带反斜杠也命中() {
        let 涉及: Vec<String> = vec![];
        let 拒绝 = vec![".上下文".to_string()];
        let 错 = 校验涉及路径预归一(".上下文\\格位\\xxx.json", &涉及, &拒绝).unwrap_err();
        assert!(错.contains("拒绝列表命中"), "反斜杠也应归一化命中：{错}");
    }

    #[test]
    fn 涉及路径_仅拒绝非空允许空_放行() {
        let 涉及: Vec<String> = vec![];
        let 拒绝 = vec![".上下文".to_string()];
        assert!(
            校验涉及路径预归一("乾坤/呈现-域/某-园/foo.rs", &涉及, &拒绝).is_ok(),
            "仅拒绝列表非空且未命中应放行"
        );
    }
}
