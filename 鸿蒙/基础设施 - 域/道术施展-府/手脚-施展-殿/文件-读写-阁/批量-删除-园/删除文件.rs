//! 批量 - 删除 - 园：批量删除文件。
//! 删除前经 回滚垫 备份旧内容：任务失败时可单文件撤销恢复。

use rizhi_fu::{debug, error};
use shihai_fu::{世界结果, 回滚垫, 工作区, 当前任务};

/// 批量删除多个文件，任一失败即返回错误；删除前先备份进回滚垫（失败只警告不阻断）。
/// 只允许删文件、拒绝目录路径：目录无文件级「写前状态」可备份，强行记录目录会致
/// 撤销时 remove_file(目录) 在 Windows 抛 os error 5 → 整组撤销失败 → 半成品残留盘面
/// （2026-08-17 打回残留实锤：模型删 `.../src` 目录致 流式-昼夜-园 整园残留）。
pub fn 删文件(路径们: &[&str]) -> 世界结果<()> {
    let 垫 = 回滚垫::在工作区(&工作区::定位());
    for 路径 in 路径们 {
        if std::path::Path::new(路径).is_dir() {
            return Err(format!("删文件只支持文件路径：{路径} 是目录，请逐个删目录内文件").into());
        }
        if let Err(错误) = 垫.备份(&当前任务(), 路径) {
            debug!(路径, "回滚垫备份跳过：{错误}");
        }
        std::fs::remove_file(路径).map_err(|错误| {
            error!(路径, "删文件失败：{错误}");
            format!("删文件失败：{路径}：{错误}")
        })?;
    }
    debug!(路径数 = 路径们.len(), "文件已删除");
    Ok(())
}
