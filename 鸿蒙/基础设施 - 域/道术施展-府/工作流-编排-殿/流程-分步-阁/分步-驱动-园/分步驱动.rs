//! 分步 - 驱动 - 园：按工作流级别分步驱动执行。

use crate::类型_定义_殿::工作流级别;

/// 按级别返回执行步骤清单（L1-L4 逐档加深）。
pub fn 级别步骤(级别: &工作流级别) -> Vec<&'static str> {
    match 级别 {
        工作流级别::问答 => vec!["作答"],
        工作流级别::脚本 => vec!["分析", "落笔", "自证"],
        工作流级别::程序 => vec!["分析", "设计", "实现", "自证"],
        工作流级别::复杂 => vec!["分析", "设计", "实现", "审验", "自证"],
    }
}

#[cfg(test)]
mod 测试 {
    use super::*;

    #[test]
    fn 级别步骤递进() {
        assert_eq!(级别步骤(&工作流级别::问答).len(), 1);
        assert_eq!(级别步骤(&工作流级别::脚本).len(), 3);
        assert_eq!(级别步骤(&工作流级别::程序).len(), 4);
        assert_eq!(级别步骤(&工作流级别::复杂).len(), 5);
    }
}
