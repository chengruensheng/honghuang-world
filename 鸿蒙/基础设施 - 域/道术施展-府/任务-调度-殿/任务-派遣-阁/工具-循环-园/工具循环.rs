//! 工具 - 循环 - 园：让模型主动调用 手脚-施展-殿 的工具逐步干活（function calling）。
//!
//! 循环：发消息与工具定义 → 模型请求工具调用 → 系统执行并回传结果 → 再问，直到模型给出最终文本。
//! 本文件只放主循环编排；工具 schema 在 工具定义.rs，工具执行与落盘护栏在 工具执行.rs。
//!
//! 预算双轨（设计稿 §4.2 规则3）：
//! - 轮数预算：跨重试共享总轮数，模型探索/收敛控制；
//! - token 预算：90 万/任务（约 200+ 轮常规对话容量），防 prompt 异常放大；
//!   任一耗尽即熔断终止。
//!
//! 会话内压缩（设计稿 §4.2 规则3）：
//! - 历史总字符 > 10000 → 中间段摘要占位替换（保留首尾与最新）；
//! - 单条工具结果 > 12000 字符 → 追加「按需回读」入口，提示用 读文件 按路径取详情。

