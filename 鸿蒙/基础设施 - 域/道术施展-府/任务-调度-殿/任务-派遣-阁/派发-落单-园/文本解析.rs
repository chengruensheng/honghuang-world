//! 文本 - 解析：按 <<<文件:路径>>> ... <<<结束>>> 协议解析落盘文本。

/// 落盘文件：LLM 声明要写的一个文件。
pub struct 落盘文件 {
    pub 路径: String,
    pub 内容: String,
}

/// 解析落盘文本：按成对标记 <<<文件:路径>>> ... <<<结束>>> 提取文件清单。
/// 成对检查：前缀缺 >>> 或后缀缺 <<<结束>>> 即报错（未闭合 / 被中断）。
/// 容错：占位路径块（如「路径」「相对项目根的文件路径」等模板复述）跳过，继续找真实块。
pub fn 解析落盘文本(文本: &str) -> Result<Vec<落盘文件>, String> {
    const 前缀: &str = "<<<文件:";
    const 后缀: &str = "<<<结束>>>";
    let mut 文件们 = Vec::new();
    let mut 剩余 = 文本;
    while let Some(位置) = 剩余.find(前缀) {
        剩余 = &剩余[位置 + 前缀.len()..];
        let 路径尾 = 剩余
            .find(">>>")
            .ok_or_else(|| "文件块前缀未闭合（缺 >>>）".to_string())?;
        let 路径 = 剩余[..路径尾].trim().to_string();
        if 路径.is_empty() || !是具体文件路径(&路径) {
            // 模板复述 / 占位路径，跳过该标记继续找下一个真实块
            剩余 = &剩余[路径尾 + 3..];
            continue;
        }
        剩余 = &剩余[路径尾 + 3..];
        let 内容尾 = 剩余
            .find(后缀)
            .ok_or_else(|| format!("文件「{路径}」缺结束标记 <<<结束>>>（输出被中断）"))?;
        let 内容 = 剩余[..内容尾].trim().to_string();
        if 内容.is_empty() {
            return Err(format!("文件「{路径}」内容为空"));
        }
        剩余 = &剩余[内容尾 + 后缀.len()..];
        文件们.push(落盘文件 { 路径, 内容 });
    }
    if 文件们.is_empty() {
        return Err("未找到任何文件块（缺 <<<文件:...>>> 标记）".to_string());
    }
    Ok(文件们)
}

/// 判断路径是否为具体文件路径（含合法后缀且非占位符）。
fn 是具体文件路径(路径: &str) -> bool {
    const 合法后缀: [&str; 7] = [".rs", ".toml", ".json", ".md", ".html", ".css", ".js"];
    let 有后缀 = 合法后缀.iter().any(|末| 路径.ends_with(末));
    let 是占位符 = 路径.contains("...") || 路径.contains("省略");
    有后缀 && !是占位符
}
