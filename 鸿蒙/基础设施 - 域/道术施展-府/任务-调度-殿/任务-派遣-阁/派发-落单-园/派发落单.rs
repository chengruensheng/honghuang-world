const 构建超时毫秒: u64 = 30 * 60 * 1000;

/// 判定一次构建是否为「环境/进程启动故障」而非「编译错误」（2026-08-18 入稿）。
///
/// 背景：实测曾遇系统级 DLL 初始化失败（cargo 子进程退出码 -1073741502 = 0xC0000142），
/// 被旧逻辑误判为「编译失败」反复重试、白烧约 18 轮 token 才打回。故须区分——
/// 编译错误：cargo 正常返回的非 0 退出码（如 101、1），子进程完整运行、输出里含 Rust 编译错误，可重试修复；
/// 环境故障：负退出码（Windows 上表示 SEH 异常/进程被系统终止，如 0xC0000142=-1073741502）
///         或 None（进程未能产生退出码/未能启动），重试无益，应立即中止避免空转。
/// 纯函数，供单元测试直接验证。
pub fn 是环境故障(退出码: Option<i32>) -> bool {
    match 退出码 {
        None => true,
        Some(码) => 码 < 0,
    }
}

/// 读取根 Cargo.toml 的 [workspace] members 并展开 glob 模式为实际目录列表（设计稿 §11.2 规则 13）。
/// members 可能是显式路径（如 `鸿蒙/基础设施 - 域/识海承载-府`）或 glob 模式（如 `鸿蒙/*`）。
/// 返回相对于工作区根的目录路径列表。读不到或解析失败返回空表（调用方决定是否阻断）。
pub(crate) fn 读取并展开workspace成员(工作区根: &std::path::Path) -> Vec<PathBuf> {
    let cargo_toml = 工作区根.join("Cargo.toml");
    let 内容 = match std::fs::read_to_string(&cargo_toml) {
        Ok(内容) => 内容,
        Err(错误) => {
            warn!("读取 Cargo.toml 失败，无法校验产物入编译树：{错误}");
            return Vec::new();
        }
    };
    let 模式们 = 解析workspace成员(&内容);
    let mut 成员们 = Vec::new();
    for 模式 in 模式们 {
        if 模式.contains('*') {
            成员们.extend(展开glob模式(&模式, 工作区根));
        } else {
            成员们.push(PathBuf::from(模式));
        }
    }
    成员们
}

/// 手动解析 Cargo.toml 的 [workspace] members 字段（避免引入 toml crate 依赖）。
/// 返回成员模式列表（可能是显式路径或 glob 模式如 `鸿蒙/*`）。
pub(crate) fn 解析workspace成员(内容: &str) -> Vec<String> {
    let mut 在workspace段 = false;
    let mut 在members = false;
    let mut 成员们 = Vec::new();
    for 行 in 内容.lines() {
        let 行 = 行.trim();
        if 行.starts_with('[') {
            在workspace段 = 行 == "[workspace]";
            在members = false;
            continue;
        }
        if !在workspace段 {
            continue;
        }
        if 在members {
            if 行.starts_with(']') {
                在members = false;
                continue;
            }
            if let Some(成员) = 提取引号字符串(行) {
                成员们.push(成员);
            }
        } else if 行.starts_with("members") {
            if let Some(等号位) = 行.find('=') {
                let 右 = 行[等号位 + 1..].trim();
                if let Some(去括号) = 右.strip_prefix('[') {
                    在members = true;
                    // 同行可能已有成员或闭合 ]
                    let 剩余 = 去括号.trim();
                    if 剩余.starts_with(']') {
                        在members = false;
                    } else if let Some(成员) = 提取引号字符串(剩余) {
                        成员们.push(成员);
                    }
                }
            }
        }
    }
    成员们
}

/// 从文本中提取第一个引号字符串（"..."）。用于解析 members 列表里的成员路径。
fn 提取引号字符串(文本: &str) -> Option<String> {
    let 起 = 文本.find('"')?;
    let 余 = &文本[起 + 1..];
    let 止 = 余.find('"')?;
    Some(余[..止].to_string())
}

/// 展开 glob 模式为实际目录列表。支持简单 glob：`前缀/*` 或 `前缀/*/后缀`。
/// 多个 `*` 的复杂 glob 不支持，原样返回当作显式路径。
fn 展开glob模式(模式: &str, 工作区根: &std::path::Path) -> Vec<PathBuf> {
    let 部分: Vec<&str> = 模式.split('*').collect();
    if 部分.len() != 2 {
        return vec![PathBuf::from(模式)];
    }
    let 前缀 = 部分[0].trim_end_matches('/');
    let 后缀 = 部分[1].trim_start_matches('/');
    let 前缀目录 = 工作区根.join(前缀);
    let mut 结果 = Vec::new();
    if let Ok(条目们) = std::fs::read_dir(&前缀目录) {
        for 条目 in 条目们.flatten() {
            if !条目.file_type().map(|t| t.is_dir()).unwrap_or(false) {
                continue;
            }
            let 名 = 条目.file_name();
            let 名str = 名.to_string_lossy();
            let 相对 = if 后缀.is_empty() {
                PathBuf::from(前缀).join(名str.as_ref())
            } else {
                PathBuf::from(前缀).join(名str.as_ref()).join(后缀)
            };
            结果.push(相对);
        }
    }
    结果
}

/// 检查产物路径是否以某个 workspace 成员目录为前缀（按路径组件比较，非字符串前缀）。
/// 统一用 `/` 作分隔符，避免 Windows `\` / `/` 混用误判。
pub(crate) fn 产物在workspace内(产物路径: &str, 成员们: &[PathBuf]) -> bool {
    let 产物 = PathBuf::from(产物路径.replace('\\', "/"));
    成员们.iter().any(|成员| 产物.starts_with(成员))
}

/// 任务调度：派遣执行任务，真实落盘改代码，跑构建验证，失败重试。
pub struct 任务调度 {
    配置: 模型配置,
    工作区根: PathBuf,
    /// 构建串行锁：并发派遣时保证同一时刻只有一次 cargo build（防 target-dir 锁与半成品互扰）。
    构建锁: std::sync::Mutex<()>,
}

/// 在途守卫（阶段 3 角色插件化 · §14.10.3a）：派遣开始登记角色在途，结束（Drop）自动清除。
/// 经 全局角色册 同源计数——卸载角色时查到的在途数 = 本守卫登记的数，防两套计数漂移。
/// 软保护：角色卸载在有在途任务时被拒绝，动态变更不影响在途任务。
struct 在途守卫 {
    角色们: Vec<String>,
}

impl 在途守卫 {
    /// 登记一组角色为在途（锁失败时静默降级为空守卫，不阻断派遣主流程）。
    fn 登记(角色们: &[String]) -> Self {
        {
            let Ok(mut 册) = 全局角色册().lock() else {
                return Self {
                    角色们: Vec::new()
                };
            };
            for 角色 in 角色们 {
                册.在途登记(角色);
            }
        }
        Self {
            角色们: 角色们.to_vec(),
        }
    }
}

impl Drop for 在途守卫 {
    fn drop(&mut self) {
        if let Ok(mut 册) = 全局角色册().lock() {
            for 角色 in &self.角色们 {
                册.在途清除(角色);
            }
        }
    }
}

impl 任务调度 {
    /// 新建调度器（持有模型配置与工作区根）。
    pub fn 新(配置: 模型配置, 工作区根: PathBuf) -> 任务调度 {
        任务调度 {
            配置,
            工作区根,
            构建锁: std::sync::Mutex::new(()),
        }
    }

    /// 成本分级轮数：按工作流级别给轮数预算，每级可用环境变量覆盖。
    /// 问答 32 / 脚本 64 / 程序 128 / 复杂 256（M3 长线程试错，2026-08-20 入稿）。
    /// 环境变量：WORLD_ROUNDS_QA / WORLD_ROUNDS_SCRIPT / WORLD_ROUNDS_PROGRAM / WORLD_ROUNDS_COMPLEX。
    fn 分级轮数(工作流: &工作流级别) -> usize {
        let (默认, 变量) = match 工作流 {
            工作流级别::问答 => (32, "WORLD_ROUNDS_QA"),
            工作流级别::脚本 => (64, "WORLD_ROUNDS_SCRIPT"),
            工作流级别::程序 => (128, "WORLD_ROUNDS_PROGRAM"),
            工作流级别::复杂 => (256, "WORLD_ROUNDS_COMPLEX"),
        };
        std::env::var(变量)
            .ok()
            .and_then(|值| 值.trim().parse().ok())
            .unwrap_or(默认)
    }

    /// 派遣执行：让 LLM 主动调用工具逐步写代码，真实写文件，跑 cargo build 验证。
    /// 现状非空时直接采用（组织层已按依赖图精确读取），为空则回退 LLM 猜路径。
    /// 跨重试共享同一会话历史与总预算：构建失败在同一历史后追加报错续跑（重试保留轨迹），不再开新对话。
    /// 跨重试累计轮数并写入回执：上层的「总轮数」= 跨任务全程累加的 工具循环轮数（首调起算，重试不重置）。
    /// 只读借用：并发派遣共享同一调度器（配置/根只读，构建由内部锁串行）。
    /// 设计方案/验收标准由上层（运行一轮）传入，注入执行提示让执行者照设计落码、按验收标准自证。
    #[allow(clippy::too_many_arguments)]
    pub fn 派遣执行(
        &self,
        任务id: &str,
        任务: &执行任务,
        背景: &str,
        现状: &str,
        涉及路径: &[String],
        设计方案: &str,
        验收标准: &str,
    ) -> Result<执行回执, String> {
        info!(任务id, 目标 = %任务.目标, "开始派遣执行");
        // 阶段 3 在途登记：派遣开始登记角色在途，结束（Drop）自动清除（角色卸载软保护）。
        let _在途 = 在途守卫::登记(&任务.角色们);
        // 线程本地当前任务：写操作经 回滚垫 归档到本任务分组，失败可整体撤销。
        let _守卫 = 进入任务(任务id);
        let 垫 = 回滚垫::在工作区(&工作区::新(self.工作区根.clone()));
        // 任务沙箱守卫：工具循环内的命令在隔离视图跑（真实盘面零污染），任务结束自动清理视图与备份。
        // 构建自证复用本守卫的沙箱引用（设计稿 §11.2 规则 17）：打开当前 基于线程本地任务id 落固定目录，
        // 循环内另开新守卫会在迭代结束 Drop 时删整箱——删掉本守卫还在用的视图；裸视图无 Drop 残留。
        let 沙箱守卫 = 沙箱守卫 {
            沙箱: 沙箱视图::打开当前(&self.工作区根),
        };
        // 现状须含真实文件块（【文件：...】）；只有结构下探而无文件内容时视为无现状，强制走读现状。
        let (现状, mut 总用量) = if 现状.trim().is_empty() || !现状.contains("【文件：") {
            self.读现状(任务, 背景)?
        } else {
            (现状.to_string(), 用量::default())
        };
        debug!(任务id, 现状长度 = 现状.len(), "现状已读");
        // 产物兜底基线：任务开始前快照，结束后 diff 补齐（防模型绕过工具记录写盘）。
        let 基线 = 全量基线(&self.工作区根);
        // 执行前基线落盘：供验收审验「改前→改后」对比，防准圣拿当前盘面当改前状态误判
        //（2026-08-16 实测：流式历法.rs 已加测试，但「涉及现状=产物=同字节数」被判「未见增量」打回）。
        if let Err(错误) = 保存执行基线(&工作区::新(self.工作区根.clone()), &基线)
        {
            warn!(任务id, 错误 = %错误, "执行前基线保存失败（不影响执行）");
        }

        // 一次任务的总预算（跨重试共享）：初提示告知预算，工具循环按剩余预算扣减，续跑不重置。
        // 成本分级（生产化 3.5）：按工作流级别给轮数预算，防简单任务按全额 32 轮烧钱
        //（2026-08-17 实测：补测试任务绕圈 19 轮烧 53 万 token 后失败的教训）。
        let 预算 = Self::分级轮数(&任务.工作流);
        // 规则已由 元数据层化 背景的【固定规则】段统一注入（含 细则·解读），此处不再重复注入。
        let 初提示 = 渲染落盘提示(背景, &现状, &任务.目标, 预算, "", 设计方案, 验收标准);
        let mut 历史 = vec![对话消息::用户(初提示)];
        let mut 剩余预算 = 预算;
        let mut 累计轮数: u32 = 0;
        let mut 尝试 = 0u32;
        loop {
            // 一轮执行：在同一会话历史上继续工具循环，收集写入产物与消耗轮数。
            let 产物们 = match self.执行一轮(任务id, &mut 历史, 剩余预算, 涉及路径)
            {
                Ok((产物们, 轮数, 用量)) => {
                    总用量.加(&用量);
                    累计轮数 = 累计轮数.saturating_add(轮数 as u32);
                    剩余预算 -= 轮数;
                    产物们
                }
                Err((错误, 轮数, 本轮产物们, 本轮用量)) => {
                    总用量.加(&本轮用量);
                    累计轮数 = 累计轮数.saturating_add(轮数 as u32);
                    剩余预算 -= 轮数;
                    尝试 += 1;
                    let 产物们 = self.合并产物(本轮产物们, self.diff补产物(&基线));
                    warn!(
                        任务id,
                        尝试,
                        剩余预算,
                        累计轮数,
                        保留产物数 = 产物们.len(),
                        "本轮执行失败：{错误}"
                    );
                    // 预算耗尽/熔断即失败不重试：剩余预算为 0 时续跑必然 0 轮立即失败，白烧教训归因轮
                    //（设计稿 §4.2 参数修正注）。
                    if 尝试 >= 最大重试次数() || 剩余预算 == 0 {
                        error!(任务id, 尝试, 累计轮数, "重试耗尽，任务失败");
                        if let Err(撤销错误) = 垫.撤销(&当前任务()) {
                            error!(任务id, 撤销错误 = %撤销错误, "任务失败后回滚垫撤销失败");
                        } else {
                            warn!(任务id, "任务失败，已撤销全部写操作");
                        }
                        return Ok(执行回执 {
                            状态: 执行状态::失败,
                            产物们,
                            说明: format!(
                                "执行失败（重试 {尝试} 次，累计 {累计轮数} 轮）：{错误}"
                            ),
                            用量: 总用量,
                            轮数: 累计轮数,
                        });
                    }
                    // 同会话续跑：历史已含完整上下文，只追加报错。
                    历史.push(对话消息::用户(渲染续跑提示(&错误)));
                    continue;
                }
            };

            // 机械前置全绿（设计稿 §11.2 规则 12）：build 通过后再 cargo test ——
            // 防 test-only 编译错误/断言失败漏过验收（实测：闰年边界测试投递遗留重复 `mod tests`，
            // 六准圣一致通过后 cargo test 编译失败）。
            // 构建串行：并发派遣时 cargo 只在同一时刻编译一次，防 target-dir 锁冲突与半成品互相干扰。
            // 构建自证走任务沙箱视图（2026-08-17 直播实锤修复）：原在真实工作区直接跑 cargo，
            // 模型改 证道/Cargo.toml 后 cargo 连锁更新【真实区】Cargo.lock——不经沙箱越界检测、
            // 不在回滚垫，打回撤销不恢复，根级文件被污染。改走沙箱后，cargo 副作用落在视图，
            // 由沙箱越界检测回滚，真实盘面零污染。
            // 复用任务级沙箱守卫（设计稿 §11.2 规则 17）：打开当前 落固定目录，另开新守卫会 Drop 删整箱。
            let 沙箱 = &沙箱守卫.沙箱;
            let (构建, 走测试门禁) = {
                let _锁 = self.构建锁.lock().map_err(|_| "构建锁中毒".to_string())?;
                // 构建/测试显式 30 分钟超时（沙箱默认 10 分钟——冷启动全量编译 8 crate 可能超，
                // 2026-08-17 轮9 体检：构建自证改走沙箱后默认超时不足风险）。
                let 库构建 = 沙箱.运行(
                    "cargo",
                    &["build", "--workspace", "--lib"],
                    None,
                    Some(构建超时毫秒),
                )?;
                if 库构建.结果.退出码 == Some(0) {
                    // 库构建通过 → 测试门禁：全量测试运行（含编译），非零退出同等视为构建失败。
                    let 测试 = 沙箱.运行(
                        "cargo",
                        &["test", "--workspace", "--lib"],
                        None,
                        Some(构建超时毫秒),
                    )?;
                    (测试, true)
                } else {
                    (库构建, false)
                }
            };
            let 构建结果 = &构建.结果;
            // 白箱探针：产物判定（构建/测试）。关联继承线程本地 任务线/要求。
            // 命令标签区分 build/test：构建成功后 `构建` 实为 test 结果（测试门禁），
            // 此前一律标 "cargo build" 误导观测（可追溯性缺陷）。
            let 判定命令 = if 走测试门禁 {
                "cargo test --workspace --lib"
            } else {
                "cargo build --workspace --lib"
            };
            {
                // 构建观测落盘：标准输出与标准错误都记（设计稿 §11.2 规则 17），
                // 防 cargo test 失败摘要（在 stdout）被「标准错误优先」二选一遗漏导致不可诊断。
                let 合并输出 = if 构建结果.标准错误.is_empty() {
                    构建结果.标准输出.clone()
                } else if 构建结果.标准输出.is_empty() {
                    构建结果.标准错误.clone()
                } else {
                    format!(
                        "=== 标准输出 ===\n{}\n=== 标准错误 ===\n{}",
                        构建结果.标准输出, 构建结果.标准错误
                    )
                };
                记构建(
                    观测角色::执行,
                    "任务调度::构建自证",
                    判定命令,
                    构建结果.退出码,
                    &合并输出,
                    当前关联(),
                );
            }
            // 无论构建成败，产物清单都并入 diff 兜底（与真实落盘一致）。
            let 产物们 = self.合并产物(产物们, self.diff补产物(&基线));
            // 产物须入编译树（设计稿 §11.2 规则 13）：构建通过后检查产物路径是否在 workspace members 内，
            // 不在则构建假阳性——cargo --workspace 不编译非 members 的文件，产物未经验证即"通过"。
            // 涉及路径为空（审验/核查类）或产物为非 RS 必需文件（如 Cargo.toml）时不检查。
            let 产物未入编译树 = if 构建结果.退出码 == Some(0) {
                self.校验产物入编译树(&产物们, 涉及路径).err()
            } else {
                None
            };
            if 构建结果.退出码 == Some(0) && 产物未入编译树.is_none() {
                info!(任务id, 尝试 = 尝试 + 1, 累计轮数, "构建通过");
                // 回滚垫保留写前状态（不清理）：供「打回撤销」恢复世界写前盘面，
                // 防按版本快照覆盖未存档的界主/助手改动；定档成功后由主政统一清理。
                return Ok(执行回执 {
                    状态: 执行状态::成功,
                    说明: format!(
                        "cargo build 与 cargo test 均通过；落盘 {} 个产物，累计 {累计轮数} 轮",
                        产物们.len()
                    ),
                    产物们,
                    用量: 总用量,
                    轮数: 累计轮数,
                });
            }

            // 机械前置全绿（设计稿 §11.2 规则 12）之上：环境故障（进程启动失败/异常终止）短路。
            // 不把「系统级 0xC0000142 进程启动失败」误当「编译错误」反复重试烧 token（2026-08-18 实测教训）。
            // 产物未入编译树是构建假阳性而非环境故障，走重试不短路。
            if 产物未入编译树.is_none() && 是环境故障(构建结果.退出码) {
                error!(任务id, 退出码 = ?构建结果.退出码, "构建进程环境故障（非编译错误），立即终止不重试");
                if let Err(撤销错误) = 垫.撤销(&当前任务()) {
                    error!(任务id, 撤销错误 = %撤销错误, "环境故障后回滚垫撤销失败");
                } else {
                    warn!(任务id, "环境故障，已撤销全部写操作");
                }
                return Ok(执行回执 {
                    状态: 执行状态::失败,
                    产物们,
                    说明: format!("构建环境故障（退出码 {:?}，进程未能正常编译），非代码错误，请检查运行环境后重试", 构建结果.退出码),
                    用量: 总用量,
                    轮数: 累计轮数,
                });
            }

            尝试 += 1;
            // 构建报错：产物未入编译树时用检查原因，否则用构建标准错误。续跑据此提示模型修正。
            let 构建报错 = 产物未入编译树
                .clone()
                .unwrap_or_else(|| 构建结果.标准错误.clone());
            warn!(任务id, 尝试, 剩余预算, 累计轮数, 退出码 = ?构建结果.退出码, "构建失败");
            if 尝试 >= 最大重试次数() {
                error!(任务id, 尝试, 累计轮数, "重试耗尽，任务失败");
                if let Err(撤销错误) = 垫.撤销(&当前任务()) {
                    error!(任务id, 撤销错误 = %撤销错误, "构建失败后回滚垫撤销失败");
                } else {
                    warn!(任务id, "构建失败重试耗尽，已撤销全部写操作");
                }
                return Ok(执行回执 {
                    状态: 执行状态::失败,
                    产物们,
                    说明: format!(
                        "cargo build 失败（重试 {尝试} 次，累计 {累计轮数} 轮）：{}",
                        构建报错
                    ),
                    用量: 总用量,
                    轮数: 累计轮数,
                });
            }
            // 同会话续跑：追加构建报错，模型基于轨迹继续修正。
            历史.push(对话消息::用户(渲染续跑提示(&构建报错)));
        }
    }

    /// 产物兜底：以任务开始前基线 diff 当前盘面，把新增/修改文件合成产物（防工具记录遗漏）。
    /// 未变文件不补入：增量变更 只报 新增/修改，报告内即不含未变文件。
    pub(crate) fn diff补产物(&self, 基线: &文件索引) -> Vec<产物条目> {
        let 报告 = 增量变更(&self.工作区根, 基线);
        let mut 产物们 = Vec::new();
        for 路径 in &报告.新增 {
            let 绝对 = self.工作区根.join(路径);
            if let Ok(元) = std::fs::metadata(&绝对) {
                产物们.push(产物条目 {
                    路径: 路径.clone(),
                    类别: 产物类别::代码,
                    字节数: 元.len(),
                    变化类型: 变化类型::新增,
                });
            }
        }
        for 路径 in &报告.修改 {
            let 绝对 = self.工作区根.join(路径);
            if let Ok(元) = std::fs::metadata(&绝对) {
                产物们.push(产物条目 {
                    路径: 路径.clone(),
                    类别: 产物类别::代码,
                    字节数: 元.len(),
                    变化类型: 变化类型::修改,
                });
            }
        }
        if !产物们.is_empty() {
            info!(兜底数 = 产物们.len(), "diff 兜底补齐产物");
        }
        产物们
    }

    /// 合并产物：工具记录为主，diff 兜底补充未记录的路径（按路径去重）。
    pub(crate) fn 合并产物(
        &self,
        主们: Vec<产物条目>,
        兜底们: Vec<产物条目>,
    ) -> Vec<产物条目> {
        let mut 结果 = 主们;
        for 产物 in 兜底们 {
            if !结果.iter().any(|已有| 已有.路径 == 产物.路径) {
                结果.push(产物);
            }
        }
        结果
    }

    /// 产物须入编译树（设计稿 §11.2 规则 13）：检查每个产物路径是否落在 workspace members 覆盖的目录范围内。
    /// 不在则构建假阳性——`cargo build --workspace` 不编译非 members 的文件，产物未经验证即"通过"。
    /// 涉及路径为空（审验/核查类）时跳过检查；产物为非 RS 必需文件（如 Cargo.toml）时跳过该产物。
    /// 返回 Err 时说明哪些产物不在 workspace members 里（未经编译验证），调用方应按构建失败处理。
    pub(crate) fn 校验产物入编译树(
        &self,
        产物们: &[产物条目],
        涉及路径: &[String],
    ) -> Result<(), String> {
        if 涉及路径.is_empty() {
            return Ok(());
        }
        let 成员们 = 读取并展开workspace成员(&self.工作区根);
        if 成员们.is_empty() {
            warn!("workspace members 为空或读取失败，跳过产物入编译树检查");
            return Ok(());
        }
        let 脱靶们: Vec<&str> = 产物们
            .iter()
            .filter(|产物| {
                产物.路径.ends_with(".rs") && !产物在workspace内(&产物.路径, &成员们)
            })
            .map(|产物| 产物.路径.as_str())
            .collect();
        if 脱靶们.is_empty() {
            Ok(())
        } else {
            Err(format!(
                "产物未入编译树（不在 workspace members 覆盖范围，未经编译验证）：{}",
                脱靶们.join(", ")
            ))
        }
    }

    /// 执行一轮：在同一会话历史上继续工具循环，收集写入产物。
    /// 返回 (产物清单, 消耗轮数, 累计用量)；Err 为 (错误说明, 消耗轮数, 已写产物, 已用 token)。
    /// 首调用已并入工具循环（历史末位即初提示/续跑提示），不再单独探测模型，省一次往返。
    /// clippy type_complexity：Err 分支的元组 (错误说明, 轮数, 已写产物, 已用 token) 是部分回执，
    /// 拆命名结构需连带 执行工具循环 的失败类型一起改，收益低于成本，故允许。
    #[allow(clippy::type_complexity)]
    fn 执行一轮(
        &self,
        任务id: &str,
        历史: &mut Vec<对话消息>,
        剩余预算: usize,
        涉及路径: &[String],
    ) -> Result<(Vec<产物条目>, usize, 用量), (String, usize, Vec<产物条目>, 用量)> {
        let 事件流实例 = 事件流::在工作区(&工作区::新(&self.工作区根));
        let (文本, 写入文件们, 轮数, _历史, 用量) = match 执行工具循环(
            任务id,
            &self.配置,
            历史,
            剩余预算,
            &self.工作区根,
            Some(&事件流实例),
            涉及路径,
        ) {
            Ok(回执) => (回执.文本, 回执.写入文件们, 回执.轮数, 回执.历史, 回执.用量),
            Err(失败) => {
                // 部分回执已带已写文件、消耗轮数与累计用量，转成产物一并交还上层。
                let mut 产物们 = Vec::new();
                for (路径, 字节数) in 失败.部分回执.写入文件们 {
                    产物们.push(产物条目 {
                        路径,
                        类别: 产物类别::代码,
                        字节数,
                        变化类型: 变化类型::修改,
                    });
                }
                return Err((失败.错误, 失败.部分回执.轮数, 产物们, 失败.部分回执.用量));
            }
        };
        let mut 产物们 = Vec::new();
        for (路径, 字节数) in 写入文件们 {
            产物们.push(产物条目 {
                路径,
                类别: 产物类别::代码,
                字节数,
                变化类型: 变化类型::修改,
            });
        }
        // 纯文本回退：模型无法调用工具时按文件块协议落盘；工具模式收敛文本不含 <<<文件: 标记，自动跳过。
        if 文本.contains("<<<文件:") {
            let 文件们 = match 解析落盘文本(&文本) {
                Ok(文件们) => 文件们,
                Err(错误) => return Err((错误, 轮数, 产物们, 用量)),
            };
            for 文件 in &文件们 {
                // 纯文本回退同样过落盘护栏（空/超长/越界）+ 涉及路径护栏，与工具模式约束一致。
                if let Err(错误) = 校验落盘(&self.工作区根, &文件.路径, &文件.内容)
                {
                    return Err((错误, 轮数, 产物们, 用量));
                }
                if let Err(错误) = 校验涉及路径(&文件.路径, 涉及路径) {
                    return Err((错误, 轮数, 产物们, 用量));
                }
                let 绝对路径 = self.工作区根.join(&文件.路径);
                let 路径文本 = match 绝对路径.to_str() {
                    Some(文本) => 文本,
                    None => return Err(("路径含非 UTF-8 字符".to_string(), 轮数, 产物们, 用量)),
                };
                if let Err(错误) = 写文件(路径文本, &文件.内容) {
                    return Err((错误, 轮数, 产物们, 用量));
                }
                debug!(路径 = %文件.路径, 字节数 = 文件.内容.len(), "文件已落盘");
                产物们.push(产物条目 {
                    路径: 文件.路径.clone(),
                    类别: 产物类别::代码,
                    字节数: 文件.内容.len() as u64,
                    变化类型: 变化类型::修改,
                });
            }
        }
        info!(
            文本长度 = 文本.len(),
            产物数 = 产物们.len(),
            消耗轮数 = 轮数,
            "本轮执行完成"
        );
        Ok((产物们, 轮数, 用量))
    }

    /// 读现状：让 LLM 决定要读哪些文件，系统读回内容，供写阶段参考。
    fn 读现状(&self, 任务: &执行任务, 背景: &str) -> Result<(String, 用量), String> {
        let 读提示 = 渲染读现状提示(背景, &任务.目标);
        let (回复, 用量) =
            调用模型(&self.配置, &[对话消息::用户(&读提示)], moxing_fu::精简上限)?;
        let 干净 = 提取对象(&回复)?;
        let 值: serde_json::Value = json5::from_str(&干净)
            .map_err(|错误| format!("解析读请求失败: {错误}；原文：{干净}"))?;

        let mut 现状 = String::new();
        if let Some(路径们) = 值["读文件们"].as_array() {
            for 路径 in 路径们 {
                if let Some(路径) = 路径.as_str() {
                    let 绝对 = self.工作区根.join(路径);
                    match 读文件(绝对.to_str().unwrap_or("")) {
                        Ok(内容) => 现状.push_str(&format!("【文件：{路径}】\n{内容}\n\n")),
                        Err(_) => {
                            现状.push_str(&format!("【文件：{路径}】\n（读取失败或不存在）\n\n"))
                        }
                    }
                }
            }
        }
        if 现状.is_empty() {
            现状.push_str("（无需读取现状）");
        }
        Ok((现状, 用量))
    }
}

/// 任务沙箱守卫：作用域结束（任务收尾）自动清理沙箱视图与备份，防残留占用盘面。
struct 沙箱守卫 {
    沙箱: 沙箱视图,
}

impl Drop for 沙箱守卫 {
    fn drop(&mut self) {
        if let Err(错误) = self.沙箱.清理() {
            error!("任务沙箱清理失败：{错误}");
        }
    }
}

