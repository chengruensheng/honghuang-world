/// 最大重试次数：默认 6，可用环境变量 WORLD_MAX_RETRY 覆盖。
/// 重试时不回滚（模型基于轨迹继续修正编译错误），重试耗尽才回滚清理盘面。
/// 6 的依据：M3 长线程试错需要足够迭代空间（2026-08-20 入稿，见设计稿 §1.5.5）。
fn 最大重试次数() -> u32 {
    std::env::var("WORLD_MAX_RETRY")
        .ok()
        .and_then(|值| 值.trim().parse().ok())
        .unwrap_or(6)
}

