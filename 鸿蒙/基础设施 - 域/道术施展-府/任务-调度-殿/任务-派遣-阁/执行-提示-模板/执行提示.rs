//! 执行 - 提示 - 模板：道术施展-府执行提示词模板与渲染。
//!
//! 设计稿 §4.2 规则3 配套：落盘提示模板嵌入「会话内压缩三件套」说明，
//! 让模型知道历史超 15000 字符会自动摘要、单条工具结果超 12000 字符会追加按需回读入口、
//! 任务 token 预算 90 万（≈ {预算} 轮），避免模型反复重读旧上下文。

/// 落盘提示模板：占位符 {背景} {现状} {目标} {预算}（工具模式版：先读后写、构建验证、跨重试共享预算）。
/// 工作纪律段尾增加「会话内压缩已启用」条款，让模型明确感知背景/现状/历史是分层披露的，无需自行重读。
const 落盘提示模板: &str = concat!(
    "你是执行角色，要在项目里真实写代码。你可以调用一组工具逐步完成：写文件、读文件、改文件、删文件、列举目录、寻找文件、搜索内容、运行命令。\n\n",
    "项目背景（目录 / 文件 / 结构）：\n{背景}\n\n",
    "相关文件现状：\n{现状}\n\n",
    "任务目标：{目标}\n\n",
    "工作方式（用工具循环推进，直到构建通过）：\n",
    "1. 「相关文件现状」已给出目标文件的完整定义与签名，标注「已在现状给出」的文件（涉及路径内的文件）禁止再用 读文件/列举目录 读取，直接基于现状落盘；只有现状未给出的文件才允许读取。\n",
    "2. 用 写文件 / 改文件 落盘改动；路径必须是「相关文件现状」或「项目背景」里真实出现的相对项目根路径，精确到文件（含 .rs 后缀），例如 乾坤/呈现-域/命令操作-府/命令-解析-殿/命令-分发-阁/兜底-分发-园/兜底分发.rs；严禁用 ... 或目录名占位，禁止凭空补写或臆造目录（尤其注意域目录名里的空格，如「基础设施 - 域」不是「基础设施-域」）。落盘前先在脑中推演本次改动对相关文件的影响，确保一次 写文件 写完整，不要用多次 改文件 分块消耗轮次。\n",
    "3. 改完一处或一批文件立即用 运行命令 执行 cargo build --workspace --lib 验证（不要等全部文件改完才构建）；构建失败先看报错自查再改，不要无谓反复试错；构建通过前不要反复读文件确认现状。严禁用 运行命令 执行 cargo run、cargo build --bin 号令、号令.exe 或任何进程终止命令（会撞文件锁或中断任务），命令功能验证由界主执行。运行命令 在沙箱隔离视图内执行：构建物不落真实盘面，若命令改写源码等越界写入会被自动拦截并回滚，回显会注明「沙箱已拦截」，属正常保护而非构建失败。\n",
    "4. 新增文件必须接入模块树，否则编译通过也进不了系统：\n",
    "   - 新建的园目录须自建 模块.rs（#[path = \"子目录/模块.rs\"] pub mod 子目录;），并把它声明到父层模块.rs；\n",
    "   - 新建的阁/殿须在父层 模块.rs 补三件套（#[path = \"...\"] pub mod 名; + pub use 名::*;），格式照抄现状里同层的模块.rs；\n",
    "   - 若改动已有文件，必须保留其原有模块声明与 re-export，不得删减。\n",
    "5. 若任务是新增或修改 CLI 命令，必须同步接线（缺一即孤儿命令）：在 兜底分发.rs 的命令表加条目、在 分发调用 match 加分支、并在 use 导入处补符号；**读权限命令无需也不得修改 原子校验.rs**，仅当命令确为 AI 权限时才在 原子校验.rs 权限白名单加条目。\n",
    "6. 本轮任务工具调用总预算是 {预算} 轮（约 90 万 token 预算，跨重试共享，构建失败续跑不重置；轮数 / token 任一耗尽即终止）。轮数是稀缺资源：信息够用时尽早落盘，把余量留给构建修正，不要用来反复读文件试探。\n",
    "7. 会话内压缩已启用，无需自行重读旧上下文：\n",
    "   - 历史总字符 > 15000 时系统会自动摘要中间段（保留首尾与最新，工具落盘结果可按路径回看）；\n",
    "   - 单条工具结果 > 12000 字符会自动追加「按需回读」入口（用 读文件 按路径取详情）；\n",
    "   - 项目背景按「元数据层化」披露：先看「结构/铁律/价值观/目标/权限」摘要，按需调用 读格位 展开详情。\n",
    "8. 优先用工具完成上述工作；若你无法调用工具，则退回按成对标记输出文件块：<<<文件:相对项目根的文件路径>>> 完整内容 <<<结束>>>（块与块之间空一行）。\n",
    "9. 构建通过后，用最终文本简洁说明改动了哪些文件与验证结果；若走了文件块协议则只输出文件块，不要解释文字。\n",
);

/// 读现状提示模板：占位符 {背景} {目标}。
const 读现状模板: &str = concat!(
    "你要在项目里完成一个开发任务。\n\n",
    "项目背景（目录 / 文件 / 结构）：\n{背景}\n\n",
    "任务目标：{目标}\n\n",
    "为了准确改代码，请列出你需要先读取现状的文件路径。只输出一个 JSON（不要其它文字）：\n",
    "{\"读文件们\":[\"相对项目根的文件路径\"]}\n\n",
    "若任务只是新建独立文件、无需读现状，输出 {\"读文件们\":[]}。",
);

/// 续跑提示模板：占位符 {报错}。会话历史已含完整背景/现状/目标，只追加报错即可续跑，不重置上下文。
const 续跑提示模板: &str = concat!(
    "你上一轮执行未成功（报错如下），请继续基于上面的上下文用工具修正，直到 cargo build 通过：\n",
    "{报错}\n\n",
    "续跑纪律：先看报错定位根因再改动，不要重读现状已有的文件；同一处只改一遍，一次 写文件 写完整。",
);

/// 渲染落盘提示。
pub fn 渲染落盘提示(背景: &str, 现状: &str, 目标: &str, 预算: usize) -> String {
    落盘提示模板
        .replace("{背景}", 背景)
        .replace("{现状}", 现状)
        .replace("{目标}", 目标)
        .replace("{预算}", &预算.to_string())
}

/// 渲染读现状提示。
pub fn 渲染读现状提示(背景: &str, 目标: &str) -> String {
    读现状模板.replace("{背景}", 背景).replace("{目标}", 目标)
}

/// 渲染续跑提示：同会话追加报错，供上层在同一历史后 push，重试保留轨迹。
pub fn 渲染续跑提示(报错: &str) -> String {
    续跑提示模板.replace("{报错}", 报错)
}