/// 读现状提示模板：占位符 {背景} {目标}。
const 读现状模板: &str = concat!(
    "你要在项目里完成一个开发任务。\n\n",
    "项目背景（目录 / 文件 / 结构）：\n{背景}\n\n",
    "任务目标：{目标}\n\n",
    "为了准确改代码，请列出你需要先读取现状的文件路径。只输出一个 JSON（不要其它文字）：\n",
    "{\"读文件们\":[\"相对项目根的文件路径\"]}\n\n",
    "若任务只是新建独立文件、无需读现状，输出 {\"读文件们\":[]}。",
);

/// 续跑提示模板：占位符 {报错}。会话历史已含完整背景/现状/目标，只追加报错即可续跑，不重置上下文。
const 续跑提示模板: &str = concat!(
    "你上一轮执行未成功（报错如下），请继续基于上面的上下文用工具修正，直到 cargo build 通过：\n",
    "{报错}\n\n",
    "续跑纪律：先看报错定位根因再改动，不要重读现状已有的文件；同一处只改一遍，一次 写文件 写完整。",
);

/// 渲染落盘提示：注入 {规则}（可操作规则格位内容，可为空串则不注入）。
pub fn 渲染落盘提示(
    背景: &str, 现状: &str, 目标: &str, 预算: usize, 规则: &str
) -> String {
    let 规则段 = if 规则.is_empty() {
        String::new()
    } else {
        format!("\n{规则}")
    };
    落盘提示模板
        .replace("{背景}", 背景)
        .replace("{现状}", 现状)
        .replace("{目标}", 目标)
        .replace("{预算}", &预算.to_string())
        .replace("{规则}", &规则段)
}

/// 渲染读现状提示。
pub fn 渲染读现状提示(背景: &str, 目标: &str) -> String {
    读现状模板.replace("{背景}", 背景).replace("{目标}", 目标)
}

/// 渲染续跑提示：同会话追加报错，供上层在同一历史后 push，重试保留轨迹。
pub fn 渲染续跑提示(报错: &str) -> String {
    续跑提示模板.replace("{报错}", 报错)
}

#[cfg(test)]
mod 测试 {
    use super::*;

    #[test]
    fn 续跑提示含报错与续跑纪律() {
        let 报错 = "error[E0425]: cannot find value `foo` in this scope";
        let 提示 = 渲染续跑提示(报错);
        assert!(提示.contains(报错), "应包含传入的报错文本：{提示}");
        assert!(提示.contains("续跑纪律"), "应包含「续跑纪律」字样：{提示}");
    }

    #[test]
    fn 读现状提示含背景与目标() {
        let 提示 = 渲染读现状提示("项目背景ABC", "任务目标XYZ");
        assert!(提示.contains("项目背景ABC"), "应注入背景：{提示}");
        assert!(提示.contains("任务目标XYZ"), "应注入目标：{提示}");
        assert!(!提示.contains("{背景}"), "占位符 {{背景}} 应被替换：{提示}");
        assert!(!提示.contains("{目标}"), "占位符 {{目标}} 应被替换：{提示}");
    }

    #[test]
    fn 读现状提示不同背景目标相互独立() {
        let 提示甲 = 渲染读现状提示("背景甲", "目标甲");
        let 提示乙 = 渲染读现状提示("背景乙", "目标乙");
        assert!(
            提示甲.contains("背景甲") && !提示甲.contains("背景乙"),
            "背景甲应只出现在提示甲：{提示甲}"
        );
        assert!(
            提示乙.contains("背景乙") && !提示乙.contains("背景甲"),
            "背景乙应只出现在提示乙：{提示乙}"
        );
        assert!(提示甲.contains("目标甲") && 提示乙.contains("目标乙"));
    }

    #[test]
    fn 落盘提示五参注入并替换占位符() {
        let 提示 = 渲染落盘提示("背景A", "现状B", "目标C", 24, "可操作规则D");
        assert!(提示.contains("背景A"), "应注入背景：{提示}");
        assert!(提示.contains("现状B"), "应注入现状：{提示}");
        assert!(提示.contains("目标C"), "应注入目标：{提示}");
        assert!(提示.contains("24"), "应注入预算数字 24：{提示}");
        assert!(提示.contains("可操作规则D"), "非空规则应注入：{提示}");
        assert!(!提示.contains("{背景}"), "占位符 {{背景}} 应被替换：{提示}");
        assert!(!提示.contains("{现状}"), "占位符 {{现状}} 应被替换：{提示}");
        assert!(!提示.contains("{目标}"), "占位符 {{目标}} 应被替换：{提示}");
        assert!(!提示.contains("{预算}"), "占位符 {{预算}} 应被替换：{提示}");
        assert!(!提示.contains("{规则}"), "占位符 {{规则}} 应被替换：{提示}");
    }

    #[test]
    fn 读现状提示含读文件们JSON键() {
        let 提示 = 渲染读现状提示("背景ABC", "目标XYZ");
        assert!(
            提示.contains("\"读文件们\""),
            "应含「读文件们」JSON键：{提示}"
        );
        assert!(提示.contains("背景ABC"), "背景应被注入：{提示}");
        assert!(提示.contains("目标XYZ"), "目标应被注入：{提示}");
        assert!(!提示.contains("{背景}"), "占位符 {{背景}} 应被替换：{提示}");
        assert!(!提示.contains("{目标}"), "占位符 {{目标}} 应被替换：{提示}");
        assert!(!提示.contains("subtask goal"), "不应残留未替换标识：{提示}");
    }
}
